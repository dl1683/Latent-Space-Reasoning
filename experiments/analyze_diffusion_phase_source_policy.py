"""Audit simple phase-source selector policies from phase-hybrid loss targets."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from statistics import mean

if __package__ is None or __package__ == "":
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

DEFAULT_LOSS_TARGETS = Path("eval_results/diffusion_language/diffusion_phase_hybrid_loss_targets.jsonl")
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/diffusion_phase_source_policy_audit.json")
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_PHASE_SOURCE_POLICY_AUDIT.md")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--loss-targets", type=Path, default=DEFAULT_LOSS_TARGETS)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def build_phase_source_policy_audit(*, loss_targets_path: Path) -> dict[str, object]:
    targets = _load_jsonl(loss_targets_path)
    candidate_policies = _candidate_policies(targets)
    policy_rows = [
        _score_policy(policy, targets)
        for policy in candidate_policies
    ]
    selected = min(
        policy_rows,
        key=lambda row: (
            _float(row.get("weighted_error")),
            _float(row.get("false_positive_count")),
            -_float(row.get("history_recall")),
            _float(row.get("predicted_history_count")),
            str(row.get("policy_id", "")),
        ),
    )
    return {
        "generated_by": "experiments/analyze_diffusion_phase_source_policy.py",
        "loss_targets_path": str(loss_targets_path),
        "schema": "diffusion_phase_source_policy_audit.v1",
        "selected_policy": selected,
        "summary": _summary(targets, selected),
        "policy_rows": policy_rows,
        "targets": targets,
    }


def render_markdown(audit: dict[str, object]) -> str:
    summary = _dict(audit.get("summary"))
    selected = _dict(audit.get("selected_policy"))
    policies = _list_of_dicts(audit.get("policy_rows"))
    targets = _list_of_dicts(audit.get("targets"))
    lines = [
        "# Diffusion Phase-Source Policy Audit",
        "",
        "This file is generated by `experiments/analyze_diffusion_phase_source_policy.py`.",
        (
            "It turns the phase-hybrid source-choice loss targets into an auditable "
            "selector rule for deciding when denoise history should become the repair "
            "source instead of preserving final-state repair."
        ),
        "",
        "## Summary",
        "",
        f"- Loss targets: `{audit.get('loss_targets_path', '')}`",
        f"- Target count: `{summary.get('target_count', 0)}`",
        f"- History positives: `{summary.get('history_positive_count', 0)}`",
        f"- Final negatives: `{summary.get('final_negative_count', 0)}`",
        f"- Total loss weight: `{_format_float(summary.get('total_loss_weight'))}`",
        f"- Selected policy: `{selected.get('policy_id', '')}`",
        f"- Selected weighted error: `{_format_float(selected.get('weighted_error'))}`",
        f"- Selected weighted accuracy: `{_format_float(selected.get('weighted_accuracy'))}`",
        f"- Selected false positives / false negatives: `{selected.get('false_positive_count', 0)}` / `{selected.get('false_negative_count', 0)}`",
        "",
        "## Selected Rule",
        "",
        _policy_description(selected),
        "",
        "## Policy Comparison",
        "",
        (
            "| Policy | Weighted Error | Weighted Accuracy | Accuracy | "
            "TP | FP | TN | FN | Predicted History | Notes |"
        ),
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for row in policies:
        lines.append(
            "| "
            f"`{row.get('policy_id', '')}` | "
            f"{_format_float(row.get('weighted_error'))} | "
            f"{_format_float(row.get('weighted_accuracy'))} | "
            f"{_format_float(row.get('accuracy'))} | "
            f"{row.get('true_positive_count', 0)} | "
            f"{row.get('false_positive_count', 0)} | "
            f"{row.get('true_negative_count', 0)} | "
            f"{row.get('false_negative_count', 0)} | "
            f"{row.get('predicted_history_count', 0)} | "
            f"{row.get('notes', '')} |"
        )
    lines.extend(
        [
            "",
            "## Target Decisions",
            "",
            (
                "| Task | Label | Selected Prediction | Weight | Target Sim | "
                "Text Sim | Safe Count | First Safe | Lag |"
            ),
            "| --- | ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: |",
        ]
    )
    predictions = _dict(selected.get("predictions"))
    for target in targets:
        task_id = str(target.get("task_id", ""))
        lines.append(
            "| "
            f"{task_id} | "
            f"{int(_float(target.get('label')))} | "
            f"`{predictions.get(task_id, '')}` | "
            f"{_format_float(target.get('loss_weight'))} | "
            f"{_format_optional(target.get('target_similarity'))} | "
            f"{_format_optional(target.get('text_similarity'))} | "
            f"{_format_optional(target.get('phase_safe_repairable_count'))} | "
            f"{_format_optional(target.get('first_safe_repairable_step'))} | "
            f"{_format_optional(target.get('phase_retention_safety_lag'))} |"
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    args = parse_args()
    audit = build_phase_source_policy_audit(loss_targets_path=args.loss_targets)
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(audit, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(audit), encoding="utf-8")
    print(
        json.dumps(
            {
                "json_output": str(args.json_output),
                "policy_count": len(_list_of_dicts(audit.get("policy_rows"))),
                "report_output": str(args.report_output),
                "selected_policy": _dict(audit.get("selected_policy")).get("policy_id", ""),
                "target_count": _dict(audit.get("summary")).get("target_count", 0),
            },
            sort_keys=True,
        )
    )
    return 0


def _summary(targets: list[dict[str, object]], selected: dict[str, object]) -> dict[str, object]:
    labels = [int(_float(target.get("label"))) for target in targets]
    weights = [_float(target.get("loss_weight")) for target in targets]
    return {
        "final_negative_count": sum(1 for label in labels if label == 0),
        "history_positive_count": sum(1 for label in labels if label == 1),
        "mean_loss_weight": mean(weights) if weights else 0.0,
        "selected_policy_id": str(selected.get("policy_id", "")),
        "target_count": len(targets),
        "total_loss_weight": sum(weights),
    }


def _candidate_policies(targets: list[dict[str, object]]) -> list[dict[str, object]]:
    return [
        {
            "policy_id": "final_only",
            "type": "constant",
            "trust_history": False,
            "notes": "never trusts phase history",
        },
        {
            "policy_id": "any_repairable_phase",
            "type": "phase_presence",
            "requires_repairable": True,
            "notes": "naive denoise-phase replacement",
        },
        {
            "policy_id": "any_safe_phase",
            "type": "phase_presence",
            "requires_safe": True,
            "notes": "trusts any retention-safe phase state",
        },
        {
            "policy_id": "similarity_090",
            "type": "similarity_gate",
            "target_similarity_min": 0.90,
            "text_similarity_min": 0.90,
            "requires_safe": True,
            "notes": "loose phase-anchor retention proxy",
        },
        {
            "policy_id": "similarity_096",
            "type": "similarity_gate",
            "target_similarity_min": 0.96,
            "text_similarity_min": 0.96,
            "requires_safe": True,
            "notes": "strict retention proxy from current source-advantage gate",
        },
        _calibrated_similarity_policy(targets),
    ]


def _calibrated_similarity_policy(targets: list[dict[str, object]]) -> dict[str, object]:
    target_thresholds = _threshold_candidates(
        targets,
        "target_similarity",
        defaults=(0.90, 0.93, 0.94, 0.95, 0.96, 0.97),
    )
    text_thresholds = _threshold_candidates(
        targets,
        "text_similarity",
        defaults=(0.90, 0.93, 0.96, 0.98),
    )
    best_policy = {
        "policy_id": "calibrated_similarity_gate",
        "type": "similarity_gate",
        "target_similarity_min": 1.01,
        "text_similarity_min": 1.01,
        "requires_safe": True,
        "notes": "calibrated on phase-source loss targets",
    }
    best_row = _score_policy(best_policy, targets)
    for target_min in target_thresholds:
        for text_min in text_thresholds:
            policy = {
                "policy_id": "calibrated_similarity_gate",
                "type": "similarity_gate",
                "target_similarity_min": target_min,
                "text_similarity_min": text_min,
                "requires_safe": True,
                "notes": "calibrated on phase-source loss targets",
            }
            row = _score_policy(policy, targets)
            if _policy_rank(row, policy) < _policy_rank(best_row, best_policy):
                best_policy = policy
                best_row = row
    return best_policy


def _policy_rank(
    row: dict[str, object],
    policy: dict[str, object],
) -> tuple[float, float, float, float, float, str]:
    return (
        _float(row.get("weighted_error")),
        _float(row.get("false_positive_count")),
        -_float(row.get("history_recall")),
        -_float(policy.get("target_similarity_min")),
        -_float(policy.get("text_similarity_min")),
        str(policy.get("policy_id", "")),
    )


def _threshold_candidates(
    targets: list[dict[str, object]],
    field: str,
    *,
    defaults: tuple[float, ...],
) -> list[float]:
    _ = targets, field
    return sorted(set(defaults) | {1.01})


def _score_policy(policy: dict[str, object], targets: list[dict[str, object]]) -> dict[str, object]:
    true_positive = false_positive = true_negative = false_negative = 0
    weighted_error = 0.0
    predictions: dict[str, str] = {}
    for target in targets:
        label = int(_float(target.get("label")))
        predicted_history = _predict_history(policy, target)
        predictions[str(target.get("task_id", ""))] = (
            "trust_history_source" if predicted_history else "preserve_final_source"
        )
        if predicted_history and label == 1:
            true_positive += 1
        elif predicted_history and label == 0:
            false_positive += 1
            weighted_error += _float(target.get("loss_weight"))
        elif not predicted_history and label == 0:
            true_negative += 1
        else:
            false_negative += 1
            weighted_error += _float(target.get("loss_weight"))
    total = len(targets)
    total_weight = sum(_float(target.get("loss_weight")) for target in targets)
    positives = true_positive + false_negative
    row = {
        **policy,
        "accuracy": (true_positive + true_negative) / total if total else 0.0,
        "false_negative_count": false_negative,
        "false_positive_count": false_positive,
        "history_recall": true_positive / positives if positives else 0.0,
        "predicted_history_count": true_positive + false_positive,
        "predictions": predictions,
        "true_negative_count": true_negative,
        "true_positive_count": true_positive,
        "weighted_accuracy": 1.0 - weighted_error / total_weight if total_weight else 0.0,
        "weighted_error": weighted_error,
    }
    return row


def _predict_history(policy: dict[str, object], target: dict[str, object]) -> bool:
    policy_type = str(policy.get("type", ""))
    if policy_type == "constant":
        return bool(policy.get("trust_history", False))
    if bool(policy.get("requires_repairable", False)) and _float(target.get("phase_repairable_count")) <= 0.0:
        return False
    if bool(policy.get("requires_safe", False)) and _float(target.get("phase_safe_repairable_count")) <= 0.0:
        return False
    if policy_type == "phase_presence":
        return True
    if policy_type == "similarity_gate":
        return (
            _float(target.get("target_similarity")) >= _float(policy.get("target_similarity_min"))
            and _float(target.get("text_similarity")) >= _float(policy.get("text_similarity_min"))
        )
    raise ValueError(f"unsupported policy type: {policy_type}")


def _policy_description(policy: dict[str, object]) -> str:
    policy_type = str(policy.get("type", ""))
    if policy_type == "constant":
        return "`trust_history_source = false`"
    if policy_type == "phase_presence":
        if bool(policy.get("requires_safe", False)):
            return "`trust_history_source = phase_safe_repairable_count > 0`"
        return "`trust_history_source = phase_repairable_count > 0`"
    if policy_type == "similarity_gate":
        return (
            "`trust_history_source = phase_safe_repairable_count > 0 "
            f"and target_similarity >= {_format_float(policy.get('target_similarity_min'))} "
            f"and text_similarity >= {_format_float(policy.get('text_similarity_min'))}`"
        )
    return "`unsupported policy`"


def _load_jsonl(path: Path) -> list[dict[str, object]]:
    records = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            value = json.loads(line)
            if isinstance(value, dict):
                records.append(value)
    return records


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    if not isinstance(value, list):
        return []
    return [item for item in value if isinstance(item, dict)]


def _float(value: object) -> float:
    if value is None or value == "":
        return 0.0
    try:
        return float(value)
    except (TypeError, ValueError):
        return 0.0


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


def _format_optional(value: object) -> str:
    if value is None or value == "":
        return ""
    return _format_float(value)


