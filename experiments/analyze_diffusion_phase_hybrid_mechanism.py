DEFAULT_RAW = Path(
    "eval_results/diffusion_language/"
    "llada_moe_mixed_phase_hybrid_preserve_seeded_gated_fresh_v2_raw.jsonl"
)
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/diffusion_phase_hybrid_mechanism_audit.json")
DEFAULT_LOSS_TARGETS_OUTPUT = Path(
    "eval_results/diffusion_language/diffusion_phase_hybrid_loss_targets.jsonl"
)
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_PHASE_HYBRID_MECHANISM_AUDIT.md")
PHASE_HYBRID_REPAIR_NAME = "constraint_gap_span_phase_hybrid_preserve_seeded_gated_repair"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scores", type=Path, default=DEFAULT_SCORES)
    parser.add_argument("--raw", type=Path, default=DEFAULT_RAW)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--loss-targets-output", type=Path, default=DEFAULT_LOSS_TARGETS_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def build_phase_hybrid_mechanism_audit(*, scores_path: Path, raw_path: Path) -> dict[str, object]:
    scores = _read_json(scores_path)
    repair_rows = _phase_hybrid_repair_rows(raw_path)
    comparison_rows = _planning_comparison_rows(scores)
    task_rows = []
    by_task = {row["task_id"]: row for row in repair_rows}
    for comparison in comparison_rows:
        task_id = str(comparison.get("task_id", ""))
        repair_row = _dict(by_task.get(task_id))
        task_rows.append(
            {
                "anchor_reason": str(repair_row.get("anchor_reason", "")),
                "delta_vs_source": _optional_float(repair_row.get("delta_vs_source")),
                "final_task_score": _float(comparison.get("fixed_task_score")),
                "first_repairable_step": _optional_int(repair_row.get("phase_first_repairable_step")),
                "first_safe_repairable_step": _optional_int(
                    repair_row.get("phase_first_safe_repairable_step")
                ),
                "phase_repairable_count": _optional_int(repair_row.get("phase_repairable_sample_count")),
                "phase_retention_safety_lag": _optional_int(
                    repair_row.get("phase_retention_safety_lag")
                ),
                "phase_safe_repairable_count": _optional_int(
                    repair_row.get("phase_safe_repairable_sample_count")
                ),
                "random_task_score": _float(comparison.get("random_task_score")),
                "repair_task_score": _float(comparison.get("repair_task_score")),
                "selected_repair": bool(repair_row),
                "source_state": str(repair_row.get("source_state", comparison.get("repair_source_state", ""))),
                "source_task_score": _optional_float(repair_row.get("source_task_score")),
                "task_id": task_id,
                "target_similarity": _optional_float(repair_row.get("target_similarity")),
                "text_similarity": _optional_float(repair_row.get("text_similarity")),
            }
        )
    loss_targets = _phase_source_loss_targets(task_rows)
    return {
        "generated_by": "experiments/analyze_diffusion_phase_hybrid_mechanism.py",
        "loss_targets": loss_targets,
        "raw_path": str(raw_path),
        "repair_name": PHASE_HYBRID_REPAIR_NAME,
        "schema": "diffusion_phase_hybrid_mechanism_audit.v2",
        "scores_path": str(scores_path),
        "summary": _summary(scores, task_rows, loss_targets),
        "task_rows": task_rows,
    }


