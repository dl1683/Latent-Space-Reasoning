def main() -> int:
    args = parse_args()
    audit = build_phase_hybrid_mechanism_audit(scores_path=args.scores, raw_path=args.raw)
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.loss_targets_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(audit, indent=2, sort_keys=True), encoding="utf-8")
    loss_targets = _list_of_dicts(audit.get("loss_targets"))
    args.loss_targets_output.write_text(
        "".join(json.dumps(row, sort_keys=True) + "\n" for row in loss_targets),
        encoding="utf-8",
    )
    args.report_output.write_text(render_markdown(audit), encoding="utf-8")
    print(
        json.dumps(
            {
                "json_output": str(args.json_output),
                "loss_targets": len(loss_targets),
                "loss_targets_output": str(args.loss_targets_output),
                "report_output": str(args.report_output),
                "rows": len(_list_of_dicts(audit.get("task_rows"))),
            },
            sort_keys=True,
        )
    )
    return 0


def _summary(
    scores: dict[str, object],
    task_rows: list[dict[str, object]],
    loss_targets: list[dict[str, object]],
) -> dict[str, object]:
    selected = [row for row in task_rows if bool(row.get("selected_repair"))]
    deltas = [_float(row.get("delta_vs_source")) for row in selected]
    loss_weights = [_float(target.get("loss_weight")) for target in loss_targets]
    first_repairable = [
        _float(row.get("first_repairable_step"))
        for row in selected
        if row.get("first_repairable_step") is not None
    ]
    first_safe = [
        _float(row.get("first_safe_repairable_step"))
        for row in selected
        if row.get("first_safe_repairable_step") is not None
    ]
    lags = [
        _float(row.get("phase_retention_safety_lag"))
        for row in selected
        if row.get("phase_retention_safety_lag") is not None
    ]
    return {
        "anchor_reason_counts": dict(Counter(str(row.get("anchor_reason", "")) for row in selected)),
        "final_kept_with_phase_signal_count": sum(
            1
            for row in selected
            if str(row.get("source_state")) == "final"
            and _float(row.get("phase_repairable_count")) > 0.0
        ),
        "final_preserve_loss_target_count": sum(
            1 for target in loss_targets if str(target.get("target_action")) == "preserve_final_source"
        ),
        "history_trust_loss_target_count": sum(
            1 for target in loss_targets if str(target.get("target_action")) == "trust_history_source"
        ),
        "loss_target_count": len(loss_targets),
        "mean_delta_vs_source": mean(deltas) if deltas else 0.0,
        "mean_first_repairable_step": mean(first_repairable) if first_repairable else 0.0,
        "mean_first_safe_repairable_step": mean(first_safe) if first_safe else 0.0,
        "mean_loss_weight": mean(loss_weights) if loss_weights else 0.0,
        "mean_phase_retention_safety_lag": mean(lags) if lags else 0.0,
        "planning_repair_score": _nested_float(
            scores,
            ("by_family_arm", "planning", "repair_selected", "mean_task_score"),
        ),
        "positive_delta_count": sum(1 for value in deltas if value > 0.0),
        "relative_gpu_cost": _nested_float(
            scores,
            ("by_family_arm", "planning", "repair_selected", "mean_generation_budget_per_task"),
        ),
        "repair_candidate_count": len(selected),
        "run_id": str(scores.get("run_id", "")),
        "source_state_counts": dict(Counter(str(row.get("source_state", "")) for row in selected)),
    }


def _phase_source_loss_targets(task_rows: list[dict[str, object]]) -> list[dict[str, object]]:
    targets = []
    for row in task_rows:
        if not bool(row.get("selected_repair")):
            continue
        source_state = str(row.get("source_state", ""))
        if source_state not in {"final", "history"}:
            continue
        target_action = "trust_history_source" if source_state == "history" else "preserve_final_source"
        delta = _float(row.get("delta_vs_source"))
        targets.append(
            {
                "anchor_reason": str(row.get("anchor_reason", "")),
                "delta_vs_source": delta,
                "first_repairable_step": _optional_int(row.get("first_repairable_step")),
                "first_safe_repairable_step": _optional_int(row.get("first_safe_repairable_step")),
                "label": 1 if source_state == "history" else 0,
                "loss_weight": max(delta, 0.0),
                "phase_repairable_count": _optional_int(row.get("phase_repairable_count")),
                "phase_retention_safety_lag": _optional_int(
                    row.get("phase_retention_safety_lag")
                ),
                "phase_safe_repairable_count": _optional_int(row.get("phase_safe_repairable_count")),
                "repair_task_score": _float(row.get("repair_task_score")),
                "source_state": source_state,
                "source_task_score": _optional_float(row.get("source_task_score")),
                "target_action": target_action,
                "target_similarity": _optional_float(row.get("target_similarity")),
                "task_id": str(row.get("task_id", "")),
                "teaching_signal": _phase_source_teaching_signal(source_state, row),
                "text_similarity": _optional_float(row.get("text_similarity")),
            }
        )
    return targets


def _phase_source_teaching_signal(source_state: str, row: dict[str, object]) -> str:
    if source_state == "history":
        return "trust denoise history when retention and source advantage both hold"
    if _optional_int(row.get("first_safe_repairable_step")) is None:
        return "preserve final source when repairable phase lacks retention-safe skeleton"
    return "preserve final source when phase evidence lacks source advantage"


def _phase_hybrid_repair_rows(raw_path: Path) -> list[dict[str, object]]:
    rows = []
    for record in _load_jsonl(raw_path):
        repair = _dict(record.get("repair"))
        if repair.get("name") != PHASE_HYBRID_REPAIR_NAME:
            continue
        features = _dict(repair.get("anchor_selection_features"))
        task_id = _task_id(record.get("task"))
        source_task = _float(repair.get("source_task_score"))
        repair_task = _task_score(record)
        rows.append(
            {
                "anchor_reason": str(repair.get("anchor_selection_reason", "")),
                "delta_vs_source": repair_task - source_task,
                "phase_first_repairable_step": _optional_int(
                    features.get("phase_first_repairable_step")
                ),
                "phase_first_safe_repairable_step": _optional_int(
                    features.get("phase_first_safe_repairable_step")
                ),
                "phase_repairable_sample_count": _optional_int(
                    features.get("phase_repairable_sample_count")
                ),
                "phase_retention_safety_lag": _optional_int(
                    features.get("phase_retention_safety_lag")
                ),
                "phase_safe_repairable_sample_count": _optional_int(
                    features.get("phase_safe_repairable_sample_count")
                ),
                "repair_task_score": repair_task,
                "source_state": str(repair.get("source_state", "")),
                "source_task_score": source_task,
                "target_similarity": _optional_float(features.get("target_similarity")),
                "task_id": task_id,
                "text_similarity": _optional_float(features.get("text_similarity")),
            }
        )
    return rows


def _planning_comparison_rows(scores: dict[str, object]) -> list[dict[str, object]]:
    rows = []
    for row in _list_of_dicts(scores.get("comparison_rows")):
        task_id = str(row.get("task_id", ""))
        if task_id.startswith("plan_"):
            rows.append(row)
    return sorted(rows, key=lambda row: str(row.get("task_id", "")))


def _read_json(path: Path) -> dict[str, object]:
    return json.loads(path.read_text(encoding="utf-8"))


def _load_jsonl(path: Path) -> list[dict[str, object]]:
    records = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            records.append(json.loads(line))
    return records


def _task_id(task: object) -> str:
    if isinstance(task, dict):
        return str(task.get("task_id", ""))
    return ""


def _task_score(record: dict[str, object]) -> float:
    score = _dict(record.get("task_score"))
    return _float(score.get("score"))


def _nested_float(data: dict[str, object], keys: tuple[str, ...]) -> float:
    value: object = data
    for key in keys:
        value = _dict(value).get(key)
    return _float(value)


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    if not isinstance(value, list):
        return []
    return [item for item in value if isinstance(item, dict)]


def _optional_int(value: object) -> int | None:
    if value is None or value == "":
        return None
    try:
        return int(float(value))
    except (TypeError, ValueError):
        return None


def _optional_float(value: object) -> float | None:
    if value is None or value == "":
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def _float(value: object) -> float:
    optional = _optional_float(value)
    return optional if optional is not None else 0.0


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


def _format_optional(value: object) -> str:
    optional = _optional_float(value)
    return "" if optional is None else f"{optional:.6f}"


