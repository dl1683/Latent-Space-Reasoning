"""Build counterfactual probe target rows from spend-transfer eval labels."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_SPEND_EVAL = Path("eval_results/diffusion_language/diffusion_independent_spend_transfer_v3_eval.json")
DEFAULT_JSON_OUTPUT = Path(
    "eval_results/diffusion_language/diffusion_counterfactual_probe_spend_eval_targets_v1.json"
)
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_COUNTERFACTUAL_PROBE_SPEND_EVAL_TARGETS_V1.md")
DEFAULT_PROBE_POLICY = "span_tomography_probe_v4"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spend-eval", type=Path, default=DEFAULT_SPEND_EVAL)
    parser.add_argument("--task-ids", default="")
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--probe-policy", default=DEFAULT_PROBE_POLICY)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    targets = build_counterfactual_probe_spend_eval_targets(
        probe_policy=args.probe_policy,
        spend_eval_path=args.spend_eval,
        task_ids=_task_id_filter(args.task_ids),
    )
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(targets, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(targets), encoding="utf-8")
    print(
        json.dumps(
            {
                "json_output": str(args.json_output),
                "positive_count": targets["summary"]["positive_label_count"],
                "report_output": str(args.report_output),
                "target_count": targets["summary"]["target_count"],
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def build_counterfactual_probe_spend_eval_targets(
    *,
    probe_policy: str,
    spend_eval_path: Path,
    task_ids: set[str] | None = None,
) -> dict[str, object]:
    spend_eval = json.loads(spend_eval_path.read_text(encoding="utf-8"))
    rows = []
    for row in _list_of_dicts(spend_eval.get("rows")):
        task_id = str(row.get("task_id", ""))
        if not task_id.startswith("plan_"):
            continue
        if task_ids is not None and task_id not in task_ids:
            continue
        rows.append(_target_row(row, probe_policy=probe_policy))
    rows.sort(key=lambda row: str(row.get("task_id", "")))
    return {
        "generated_by": "experiments/build_diffusion_counterfactual_probe_spend_eval_targets.py",
        "inputs": {
            "spend_eval": str(spend_eval_path),
        },
        "probe_policy": probe_policy,
        "rows": rows,
        "schema": "diffusion_counterfactual_probe_spend_eval_targets.v1",
        "summary": _summary(rows),
    }


def render_markdown(targets: dict[str, object]) -> str:
    summary = _dict(targets.get("summary"))
    inputs = _dict(targets.get("inputs"))
    lines = [
        "# Diffusion Counterfactual Probe Spend Eval Targets V1",
        "",
        "This file is generated by `experiments/build_diffusion_counterfactual_probe_spend_eval_targets.py`.",
        (
            "It converts independent spend-transfer eval rows into the target "
            "schema used by measured counterfactual probe audits."
        ),
        "",
        "## Summary",
        "",
        f"- Spend eval: `{inputs.get('spend_eval', '')}`",
        f"- Probe policy under test: `{targets.get('probe_policy', '')}`",
        f"- Target rows: `{summary.get('target_count', 0)}`",
        f"- Positive labels: `{summary.get('positive_label_count', 0)}`",
        f"- Negative labels: `{summary.get('negative_label_count', 0)}`",
        f"- Positive tasks: {_join_tasks(summary.get('positive_task_ids'))}",
        f"- Negative tasks: {_join_tasks(summary.get('negative_task_ids'))}",
        f"- Total positive lift: `{_format_float(summary.get('total_positive_lift'))}`",
        f"- Gate decision: `{summary.get('gate_decision', '')}`",
        "",
        "## Rows",
        "",
        "| Task | Promote | Lift | Source Quality | Gap | First Step | Decomposed | Trajectory-Relative |",
        "| --- | --- | ---: | ---: | ---: | ---: | --- | --- |",
    ]
    for row in _list_of_dicts(targets.get("rows")):
        labels = _dict(row.get("labels"))
        pre = _dict(row.get("pre_probe_features"))
        lines.append(
            "| "
            f"`{row.get('task_id', '')}` | "
            f"{bool(labels.get('promote_vs_trajectory'))} | "
            f"{_format_float(labels.get('candidate_lift_vs_trajectory'))} | "
            f"{_format_float(pre.get('source_quality'))} | "
            f"{int(_float(pre.get('prompt_gap_count')))} | "
            f"{_format_optional(pre.get('first_repairable_step'))} | "
            f"{bool(pre.get('decomposed_prediction'))} | "
            f"{bool(pre.get('trajectory_relative_prediction'))} |"
        )
    lines.extend(
        [
            "",
            "## Reading",
            "",
            (
                "This target sheet is for frozen probe-rule validation only. Labels "
                "come from prior independent spend-transfer repair-value rows; no "
                "threshold should be fit on this sheet before reporting transfer."
            ),
        ]
    )
    return "\n".join(lines) + "\n"


def _target_row(row: dict[str, object], *, probe_policy: str) -> dict[str, object]:
    lift = _float(row.get("repair_lift"))
    return {
        "counterexample_type": "spend_eval_transfer",
        "labels": {
            "candidate_lift_vs_trajectory": lift,
            "promote_vs_trajectory": bool(row.get("profitable")),
            "repair_lift": lift,
            "repair_selector_edge": _float(row.get("selected_repair_lift")),
        },
        "pre_probe_features": {
            "decomposed_prediction": bool(row.get("decomposed_prediction")),
            "first_repairable_step": _float(row.get("first_repairable_step")),
            "prompt_gap_count": _float(row.get("prompt_gap_count")),
            "single_repairability_prediction": bool(row.get("single_repairability_prediction")),
            "source_quality": _float(row.get("source_quality")),
            "source_task_delta_vs_trajectory": _float(row.get("source_task_delta_vs_trajectory")),
            "trajectory_relative_prediction": bool(row.get("trajectory_relative_prediction")),
        },
        "probe_policy": probe_policy,
        "task_id": str(row.get("task_id", "")),
    }


def _summary(rows: list[dict[str, object]]) -> dict[str, object]:
    positives = [row for row in rows if bool(_dict(row.get("labels")).get("promote_vs_trajectory"))]
    negatives = [row for row in rows if not bool(_dict(row.get("labels")).get("promote_vs_trajectory"))]
    return {
        "gate_decision": "diagnostic_only",
        "negative_label_count": len(negatives),
        "negative_task_ids": [str(row.get("task_id", "")) for row in negatives],
        "positive_label_count": len(positives),
        "positive_task_ids": [str(row.get("task_id", "")) for row in positives],
        "target_count": len(rows),
        "total_positive_lift": sum(
            _float(_dict(row.get("labels")).get("candidate_lift_vs_trajectory"))
            for row in positives
        ),
    }


def _task_id_filter(value: str) -> set[str] | None:
    task_ids = {item.strip() for item in value.split(",") if item.strip()}
    return task_ids or None


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    if not isinstance(value, list):
        return []
    return [item for item in value if isinstance(item, dict)]


def _float(value: object) -> float:
    if value is None or value == "":
        return 0.0
    try:
        return float(value)
    except (TypeError, ValueError):
        return 0.0


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


def _format_optional(value: object) -> str:
    if value in (None, ""):
        return ""
    return _format_float(value)


def _join_tasks(value: object) -> str:
    tasks = [str(item) for item in value] if isinstance(value, list) else []
    return ", ".join(f"`{task}`" for task in tasks) if tasks else "_none_"


if __name__ == "__main__":
    raise SystemExit(main())
