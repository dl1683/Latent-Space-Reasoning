"""Build a post-hoc aggregation replay from planning rubric-hit labels."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from experiments.analyze_latent_trajectory_aggregation import (
    build_aggregation_scout_from_rows,
    render_markdown as render_base_markdown,
)

DEFAULT_RAW = Path("eval_results/diffusion_language/three_arm_planning_mix_guarded_v1_raw.jsonl")
DEFAULT_COMPONENTS_OUTPUT = Path(
    "eval_results/diffusion_language/latent_aggregation_replay_rubric_components.jsonl"
)
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/latent_aggregation_replay_rubric.json")
DEFAULT_REPORT_OUTPUT = Path(
    "docs/reports/diffusion/LATENT_AGGREGATION_RUBRIC_REPLAY.md"
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--raw", type=Path, default=DEFAULT_RAW)
    parser.add_argument("--components-output", type=Path, default=DEFAULT_COMPONENTS_OUTPUT)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    result = build_replay(raw_path=args.raw)
    components = _list_of_dicts(result.get("component_rows"))
    result_without_components = {key: value for key, value in result.items() if key != "component_rows"}
    args.components_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.components_output.write_text(
        "\n".join(json.dumps(row, sort_keys=True) for row in components) + "\n",
        encoding="utf-8",
    )
    args.json_output.write_text(
        json.dumps(result_without_components, indent=2, sort_keys=True),
        encoding="utf-8",
    )
    args.report_output.write_text(render_markdown(result_without_components), encoding="utf-8")
    summary = _dict(result_without_components.get("summary"))
    print(
        json.dumps(
            {
                "aggregate_win_count": summary.get("aggregate_win_count", 0),
                "component_rows": len(components),
                "json_output": str(args.json_output),
                "promoted_task_count": summary.get("promoted_task_count", 0),
                "report_output": str(args.report_output),
                "task_count": summary.get("task_count", 0),
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def build_replay(*, raw_path: Path) -> dict[str, object]:
    records = _read_jsonl(raw_path)
    component_rows = _component_rows(records)
    scout = build_aggregation_scout_from_rows(
        rows=component_rows,
        input_label=str(raw_path),
    )
    summary = _dict(scout.get("summary"))
    return {
        **scout,
        "component_rows": component_rows,
        "generated_by": "experiments/build_latent_aggregation_replay_from_rubric_hits.py",
        "inputs": {"raw": str(raw_path)},
        "replay_boundary": {
            "status": "oracle_replay_not_inference_time",
            "reason": (
                "Rubric-hit labels are used after scoring to estimate component-level "
                "aggregation headroom. This does not prove an online extractor or verifier."
            ),
        },
        "schema": "latent_aggregation_rubric_replay.v1",
        "summary": {
            **summary,
            "component_row_count": len(component_rows),
            "planning_record_count": len(_planning_records(records)),
            "schema_note": "post-hoc rubric replay only; not inference-time aggregation evidence",
        },
    }


def render_markdown(result: dict[str, object]) -> str:
    boundary = _dict(result.get("replay_boundary"))
    lines = [
        "# Latent Aggregation Rubric Replay",
        "",
        "This file is generated by `experiments/build_latent_aggregation_replay_from_rubric_hits.py`.",
        "",
        "## Boundary",
        "",
        f"- Status: `{boundary.get('status', '')}`",
        f"- Reason: {boundary.get('reason', '')}",
        "",
        "## Replay Result",
        "",
    ]
    base = render_base_markdown(result)
    base = base.replace(
        (
            "It is a deterministic protocol scout, not a promoted model result: the rows are "
            "component-level fixtures used to test whether the aggregation accounting can "
            "distinguish compositional gain from unsafe fusion."
        ),
        (
            "It is a post-hoc replay over already-scored planning rubric components. "
            "It estimates component-union headroom in existing trajectories, but it does "
            "not prove an inference-time extractor, verifier, or final-answer realizer."
        ),
    )
    base = base.replace(
        (
            "## Next Experiment\n\n"
            "Replace the fixture rows with extracted components from frozen prefix-perturbation, "
            "diffusion-repair, and baseline trajectories. Keep the same gates fixed before any "
            "headline run: `aggregate_score > best_single_score`, positive component gain over "
            "loss, zero hard contradictions, and zero unsupported additions."
        ),
        (
            "## Next Experiment\n\n"
            "Turn this oracle replay into an inference-time experiment by freezing an extractor "
            "that predicts rubric components before labels are known, then realize a final answer "
            "from the selected component set and rescore that answer against best-single selection."
        ),
    )
    lines.extend(line for line in base.splitlines() if line != "# Latent Trajectory Aggregation Scout")
    lines.extend(
        [
            "",
            "## Interpretation",
            "",
            (
                "This replay asks a narrower but more real question than the fixture scout: "
                "if scored rubric components from existing trajectories were available to an "
                "aggregator, how often would component union beat best-single selection? "
                "Any positive rows are oracle headroom, not deployed reasoning gains."
            ),
        ]
    )
    return "\n".join(lines) + "\n"


def _component_rows(records: list[dict[str, object]]) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    for index, record in enumerate(_planning_records(records)):
        task = _dict(record.get("task"))
        task_id = str(task.get("task_id", record.get("task_id", "")))
        details = _dict(_dict(record.get("task_score")).get("details"))
        rubric_hits = _list_of_dicts(details.get("rubric_hits"))
        trajectory_id = _trajectory_id(record, index)
        family = _trajectory_family(record)
        support_base = _float(_dict(record.get("task_score")).get("score"))
        for hit_index, hit in enumerate(rubric_hits):
            item = str(hit.get("item", ""))
            if not item:
                continue
            supported = bool(hit.get("hit"))
            rows.append(
                {
                    "component_id": _component_id(item),
                    "component_type": "planning_rubric_hit",
                    "component_weight": 1.0,
                    "source_span": _source_span(record),
                    "supported": supported,
                    "support_score": support_base if supported else 0.0,
                    "task_id": task_id,
                    "trajectory_family": family,
                    "trajectory_id": trajectory_id,
                    "rubric_item": item,
                    "rubric_item_index": hit_index,
                }
            )
    return rows


def _planning_records(records: list[dict[str, object]]) -> list[dict[str, object]]:
    return [
        record
        for record in records
        if str(_dict(record.get("task")).get("family", "")) == "planning"
        and _list_of_dicts(_dict(_dict(record.get("task_score")).get("details")).get("rubric_hits"))
    ]


def _trajectory_id(record: dict[str, object], index: int) -> str:
    task = _dict(record.get("task"))
    task_id = str(task.get("task_id", record.get("task_id", "")))
    candidate = str(record.get("candidate_key", "candidate"))
    schedule = str(_dict(record.get("schedule")).get("name", "schedule"))
    stage = str(record.get("generation_stage", "generation"))
    return f"{task_id}:{candidate}:{schedule}:{stage}:{index}"


def _trajectory_family(record: dict[str, object]) -> str:
    candidate = str(record.get("candidate_key", "candidate"))
    schedule = str(_dict(record.get("schedule")).get("name", "schedule"))
    stage = str(record.get("generation_stage", "generation"))
    return f"{candidate}:{schedule}:{stage}"


def _component_id(item: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "_", item.lower()).strip("_")
    return slug[:96] or "rubric_item"


def _source_span(record: dict[str, object]) -> str:
    text = " ".join(str(record.get("text", "")).split())
    return text[:180]


def _read_jsonl(path: Path) -> list[dict[str, object]]:
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        row = json.loads(line)
        if isinstance(row, dict):
            rows.append(row)
    return rows


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    return [row for row in value if isinstance(row, dict)] if isinstance(value, list) else []


def _float(value: object) -> float:
    if value is None:
        return 0.0
    return float(value)


if __name__ == "__main__":
    raise SystemExit(main())
