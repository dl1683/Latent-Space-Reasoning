"""Analyze the latent aggregation multi-aspect v3 probe measurement run."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_RAW = Path("eval_results/diffusion_language/latent_aggregation_multi_aspect_v3_probe_raw.jsonl")
DEFAULT_SCORES = Path("eval_results/diffusion_language/latent_aggregation_multi_aspect_v3_probe_scores.json")
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/latent_aggregation_multi_aspect_v3_probe_analysis.json")
DEFAULT_REPORT_OUTPUT = Path("docs/reports/diffusion/LATENT_AGGREGATION_MULTI_ASPECT_V3_PROBE_ANALYSIS.md")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--raw", type=Path, default=DEFAULT_RAW)
    parser.add_argument("--scores", type=Path, default=DEFAULT_SCORES)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    analysis = analyze_v3_probe_run(raw_path=args.raw, scores_path=args.scores)
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(analysis, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(analysis), encoding="utf-8")
    print(
        json.dumps(
            {
                "measured_probe_count": analysis["summary"]["measured_probe_count"],
                "probe_task_delta_mean": analysis["summary"]["probe_task_delta_mean"],
                "report_output": str(args.report_output),
                "stage1_valid_probe_count": analysis["summary"]["stage1_valid_probe_count"],
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def analyze_v3_probe_run(*, raw_path: Path, scores_path: Path) -> dict[str, object]:
    scores = json.loads(scores_path.read_text(encoding="utf-8"))
    raw_rows = _read_jsonl(raw_path)
    probe_records = [
        row for row in raw_rows if row.get("generation_stage") == "counterfactual_probe"
    ]
    probes_by_task = {
        str(_dict(record.get("task")).get("task_id", "")): record for record in probe_records
    }
    gate_rows = _list_of_dicts(scores.get("repair_spend_gate_rows"))
    rows = [_row(gate_row, probes_by_task.get(str(gate_row.get("task_id", "")), {})) for gate_row in gate_rows]
    rows.sort(key=lambda row: str(row.get("task_id", "")))
    return {
        "generated_by": "experiments/analyze_latent_aggregation_multi_aspect_v3_probe.py",
        "inputs": {
            "raw": str(raw_path),
            "scores": str(scores_path),
        },
        "rows": rows,
        "schema": "latent_aggregation_multi_aspect_v3_probe_analysis.v1",
        "summary": _summary(rows, scores, probe_records),
    }


def render_markdown(analysis: dict[str, object]) -> str:
    stats = _dict(analysis.get("summary"))
    lines = [
        "# Latent Aggregation Multi-Aspect V3 Probe Analysis",
        "",
        "This file is generated by `experiments/analyze_latent_aggregation_multi_aspect_v3_probe.py`.",
        (
            "It analyzes the corrected v3 probe measurement run. The probe rows are "
            "diagnostic observations, not promoted repairs or final aggregation outputs."
        ),
        "",
        "## Summary",
        "",
        f"- Full model generations: `{stats.get('all_generation_count', 0)}`",
        f"- Counterfactual probe generations: `{stats.get('counterfactual_probe_generation_count', 0)}`",
        f"- Measured probe rows: `{stats.get('measured_probe_count', 0)}`",
        f"- Stage-1 valid probe texts: `{stats.get('stage1_valid_probe_count', 0)}`",
        f"- Full repair authorizations: `{stats.get('should_run_count', 0)}`",
        f"- Mean probe cost relative to full repair: `{_format_float(stats.get('mean_probe_cost_relative'))}`",
        f"- Mean measured probe value prediction: `{_format_float(stats.get('mean_measured_probe_value_prediction'))}`",
        f"- Mean resolved gap count: `{_format_float(stats.get('mean_resolved_gap_count'))}`",
        f"- Maximum remaining gap count: `{int(_float(stats.get('max_remaining_gap_count')))}`",
        f"- Probe task-score delta vs source mean: `{_format_float(stats.get('probe_task_delta_mean'))}`",
        f"- Probe task-score wins/ties/losses vs source: `{stats.get('probe_task_wins', 0)}/{stats.get('probe_task_ties', 0)}/{stats.get('probe_task_losses', 0)}`",
        f"- Run content hash: `{stats.get('content_hash', '')}`",
        "",
        "## Reading",
        "",
        (
            "The corrected command reached the probe branch and generated a full "
            "24-row LLaDA probe cohort. The result is useful as coverage/visibility "
            "evidence, but it is not direct aggregation success: `should_run` remains "
            "false for every row, and the bounded probe texts underperform the source "
            "answers on task score on average."
        ),
        "",
        "## Rows",
        "",
        (
            "| Task | Source | Source Task | Probe Task | Delta | Measured Value | "
            "Resolved Gap | Remaining Gap | Stage1 Valid | Should Run |"
        ),
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | --- | --- |",
    ]
    for row in _list_of_dicts(analysis.get("rows")):
        lines.append(
            "| "
            f"`{row.get('task_id', '')}` | "
            f"`{row.get('source_control', '')}` | "
            f"{_format_float(row.get('source_task_score'))} | "
            f"{_format_float(row.get('probe_task_score'))} | "
            f"{_format_float(row.get('probe_task_delta_vs_source'))} | "
            f"{_format_float(row.get('measured_probe_value_prediction'))} | "
            f"{int(_float(row.get('resolved_gap_count')))} | "
            f"{int(_float(row.get('remaining_gap_count')))} | "
            f"{bool(row.get('stage1_valid'))} | "
            f"{bool(row.get('should_run'))} |"
        )
    return "\n".join(lines) + "\n"


def _row(gate_row: dict[str, object], probe_record: dict[str, object]) -> dict[str, object]:
    probe_task_score = _float(_dict(probe_record.get("task_score")).get("score"))
    source_task_score = _float(gate_row.get("source_task_score"))
    return {
        "measured_probe_value_prediction": _float(gate_row.get("measured_probe_value_prediction")),
        "probe_task_delta_vs_source": probe_task_score - source_task_score,
        "probe_task_score": probe_task_score,
        "remaining_gap_count": _float(gate_row.get("counterfactual_probe_remaining_gap_count")),
        "resolved_gap_count": _float(gate_row.get("counterfactual_probe_resolved_gap_count")),
        "should_run": bool(gate_row.get("should_run")),
        "source_control": str(gate_row.get("source_control", "")),
        "source_quality": _float(gate_row.get("source_quality")),
        "source_task_score": source_task_score,
        "stage1_valid": bool(gate_row.get("counterfactual_probe_text_valid_for_stage1")),
        "task_id": str(gate_row.get("task_id", "")),
    }


def _summary(
    rows: list[dict[str, object]],
    scores: dict[str, object],
    probe_records: list[dict[str, object]],
) -> dict[str, object]:
    deltas = [_float(row.get("probe_task_delta_vs_source")) for row in rows]
    measured_values = [_float(row.get("measured_probe_value_prediction")) for row in rows]
    probe_costs = [
        _float(_dict(record.get("counterfactual_probe")).get("probe_cost_relative"))
        for record in probe_records
    ]
    return {
        "all_generation_count": int(_float(scores.get("all_generation_count"))),
        "content_hash": str(scores.get("content_hash", "")),
        "counterfactual_probe_generation_count": int(
            _float(scores.get("counterfactual_probe_generation_count"))
        ),
        "max_remaining_gap_count": max((_float(row.get("remaining_gap_count")) for row in rows), default=0.0),
        "mean_measured_probe_value_prediction": _mean(measured_values),
        "mean_probe_cost_relative": _mean(probe_costs),
        "mean_resolved_gap_count": _mean([_float(row.get("resolved_gap_count")) for row in rows]),
        "measured_probe_count": len(probe_records),
        "probe_task_delta_mean": _mean(deltas),
        "probe_task_losses": sum(1 for delta in deltas if delta < -1e-9),
        "probe_task_ties": sum(1 for delta in deltas if abs(delta) <= 1e-9),
        "probe_task_wins": sum(1 for delta in deltas if delta > 1e-9),
        "row_count": len(rows),
        "should_run_count": sum(1 for row in rows if bool(row.get("should_run"))),
        "stage1_valid_probe_count": sum(1 for row in rows if bool(row.get("stage1_valid"))),
    }


def _read_jsonl(path: Path) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            row = json.loads(line)
            if isinstance(row, dict):
                rows.append(row)
    return rows


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    if not isinstance(value, list):
        return []
    return [item for item in value if isinstance(item, dict)]


def _mean(values: list[float]) -> float:
    return sum(values) / len(values) if values else 0.0


def _float(value: object) -> float:
    if value is None:
        return 0.0
    try:
        return float(value)
    except (TypeError, ValueError):
        return 0.0


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


if __name__ == "__main__":
    raise SystemExit(main())
