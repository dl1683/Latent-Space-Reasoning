        f"- Tasks with selected complement: `{summary['tasks_with_selected_complement']}`",
        f"- Tasks without selected complement: `{summary['tasks_without_selected_complement']}`",
        f"- No-complement blockers: `{_format_counts(summary['no_complement_blockers'])}`",
        f"- Mean non-anchor candidates: `{_format_float(summary['mean_non_anchor_candidate_count'])}`",
        f"- Mean nonempty non-anchor candidates: `{_format_float(summary['mean_nonempty_candidate_count'])}`",
