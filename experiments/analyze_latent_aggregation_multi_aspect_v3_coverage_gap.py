def _analyze_task(task_id: str, records: list[dict[str, object]]) -> dict[str, object]:
    if not records:
        return {**_empty_task(task_id, "missing_raw_records"), "selected_complement_sources": {}}
    anchor = max(records, key=_score)
    anchor_id = _trajectory_id(anchor, 0, stable=True)
    anchor_aspects = _aspect_scores(anchor)
    non_anchor = [
        record for record in records if _trajectory_id(record, 0, stable=True) != anchor_id
    ]
    deltas = []
    selected = []
    for record in non_anchor:
        candidate_aspects = _aspect_scores(record)
        selected.extend(
            _complement_aspects(
                anchor_aspects=anchor_aspects,
                candidate_aspects=candidate_aspects,
                trajectory_id=_trajectory_id(record, 0, stable=True),
            )
        )
        deltas.extend(_aspect_deltas(anchor_aspects, candidate_aspects))
    best_by_aspect: dict[str, dict[str, object]] = {}
    for row in selected:
        aspect_id = str(row.get("aspect_id", ""))
        current = best_by_aspect.get(aspect_id)
        if current is None or _float(row.get("delta")) > _float(current.get("delta")):
            best_by_aspect[aspect_id] = row
    selected_rows = list(best_by_aspect.values())
    positive = [row for row in deltas if _float(row.get("delta")) > EPSILON]
    near_miss = [
        row
        for row in positive
        if _float(row.get("delta")) < _float(row.get("selection_threshold")) - EPSILON
    ]
    max_dimension_delta = max(
        (_float(row.get("delta")) for row in deltas if row.get("aspect_class") == "dimension"),
        default=0.0,
    )
    max_rubric_delta = max(
        (_float(row.get("delta")) for row in deltas if row.get("aspect_class") == "rubric"),
        default=0.0,
    )
    nonempty_count = sum(1 for record in non_anchor if str(record.get("text", "")).strip())
    return {
        "anchor_score": _score(anchor),
        "anchor_trajectory_id": anchor_id,
        "coverage_blocker": _coverage_blocker(
            max_dimension_delta=max_dimension_delta,
            max_rubric_delta=max_rubric_delta,
            near_miss_count=len(near_miss),
            non_anchor_count=len(non_anchor),
            nonempty_count=nonempty_count,
            positive_count=len(positive),
            selected_count=len(selected_rows),
        ),
        "max_dimension_delta": max_dimension_delta,
        "max_rubric_delta": max_rubric_delta,
        "near_miss_aspect_count": len(near_miss),
        "non_anchor_candidate_count": len(non_anchor),
        "nonempty_candidate_count": nonempty_count,
        "positive_delta_aspect_count": len(positive),
        "selected_complement_count": len(selected_rows),
        "selected_complement_sources": _selected_source_counts(selected_rows),
        "task_id": task_id,
    }


def _summary(tasks: list[dict[str, object]]) -> dict[str, object]:
    no_complement = [
        task for task in tasks if int(_float(task.get("selected_complement_count"))) <= 0
    ]
    no_complement_max_dimension = [
        _float(task.get("max_dimension_delta")) for task in no_complement
    ]
    return {
        "complement_source_counts": _total_source_counts(tasks),
        "max_no_complement_dimension_delta": max(no_complement_max_dimension, default=0.0),
        "mean_no_complement_max_dimension_delta": _mean(no_complement_max_dimension),
        "mean_non_anchor_candidate_count": _mean(
            _float(task.get("non_anchor_candidate_count")) for task in tasks
        ),
        "mean_nonempty_candidate_count": _mean(
            _float(task.get("nonempty_candidate_count")) for task in tasks
        ),
        "no_complement_blockers": _blocker_counts(no_complement),
        "no_complement_tasks_with_near_miss": sum(
            1 for task in no_complement if int(_float(task.get("near_miss_aspect_count"))) > 0
        ),
        "task_count": len(tasks),
        "tasks_with_selected_complement": sum(
            1 for task in tasks if int(_float(task.get("selected_complement_count"))) > 0
        ),
        "tasks_without_selected_complement": len(no_complement),
    }


def _selected_source_counts(rows: list[dict[str, object]]) -> dict[str, int]:
    counts: Counter[str] = Counter()
    for row in rows:
        trajectory_id = str(row.get("trajectory_id", ""))
        if "counterfactual_probe" in trajectory_id:
            counts["counterfactual_probe"] += 1
        elif "repair_candidate" in trajectory_id:
            counts["repair_candidate"] += 1
        elif "random" in trajectory_id:
            counts["random"] += 1
        elif "low_confidence" in trajectory_id:
            counts["low_confidence"] += 1
        else:
            counts["other"] += 1
    return dict(sorted(counts.items()))


def _evidence_boundary(freeze: dict[str, object], raw_paths: list[Path]) -> dict[str, str]:
    if str(freeze.get("schema", "")) == "latent_aggregation_multi_aspect_v5_freeze.v1":
        return {
            "reason": (
                "Fresh v5 coverage diagnostic over predeclared 48-task label, probe, "
                "and diversity-extension raw sources. This explains the remaining "
                "no-complement tasks after the passing v5 replay."
            ),
            "status": "fresh_predeclared_multi_source_v5_coverage_gap",
        }
    if str(freeze.get("schema", "")) == "latent_aggregation_multi_aspect_v4_freeze.v1":
        return {
            "reason": (
                "Fresh v4 coverage diagnostic over predeclared label, probe, and "
                "diversity-extension raw sources. This explains the remaining "
                "no-complement tasks after the passing v4 replay."
            ),
            "status": "fresh_predeclared_multi_source_v4_coverage_gap",
        }
    if len(raw_paths) <= 1:
        return {
            "reason": (
                "Post-replay v3 coverage diagnostic over frozen label rows; used to choose "
                "the next coverage-improvement experiment, not to promote v3."
            ),
            "status": "held_out_multi_aspect_v3_coverage_gap",
        }
    return {
        "reason": (
            "Post-replay v3 coverage diagnostic over frozen label rows plus extra raw sources. "
            "This diagnoses candidate-source design after the baseline failure; it is not the "
            "original predeclared v3 promotion evidence."
        ),
        "status": "post_failure_augmented_v3_coverage_gap",
    }


def _boundary_intro(status: str) -> str:
    if status == "fresh_predeclared_multi_source_v5_coverage_gap":
        return (
            "It diagnoses remaining no-complement tasks after the fresh v5 48-task "
            "replay."
        )
    if status == "fresh_predeclared_multi_source_v4_coverage_gap":
        return "It diagnoses remaining no-complement tasks after the fresh v4 replay."
    return "It diagnoses why the v3 replay still has too few tasks with selected complement material."


def _boundary_version_title(status: str) -> str:
    if status == "fresh_predeclared_multi_source_v5_coverage_gap":
        return "V5"
    if status == "fresh_predeclared_multi_source_v4_coverage_gap":
        return "V4"
    return "V3"


def _total_source_counts(tasks: list[dict[str, object]]) -> dict[str, int]:
    counts: Counter[str] = Counter()
    for task in tasks:
        counts.update(_dict(task.get("selected_complement_sources")))
    return dict(sorted(counts.items()))


