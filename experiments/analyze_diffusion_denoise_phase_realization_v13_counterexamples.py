"""Analyze realization-value counterexamples from the v13 denoise replay."""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

if str(Path(__file__).resolve().parents[1]) not in sys.path:
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

DEFAULT_REPLAY = Path("eval_results/diffusion_language/denoise_phase_realization_v13_replay.json")
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/denoise_phase_realization_v13_counterexamples.json")
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_DENOISE_PHASE_REALIZATION_V13_COUNTEREXAMPLES.md")
DEFAULT_SELECTION_PENALTY = 0.02
DEFAULT_PROBE_COST_PENALTY = 0.03
PROBE_VALUE_MAX = 0.032


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--replay", type=Path, default=DEFAULT_REPLAY)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    analysis = analyze_counterexamples(replay_path=args.replay)
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(analysis, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(analysis), encoding="utf-8")
    print(
        json.dumps(
            {
                "counterexample_count": analysis["summary"]["counterexample_count"],
                "json_output": str(args.json_output),
                "report_output": str(args.report_output),
                "selected_label_best_hypothesis": analysis["selected_repair_hypotheses"][0]["hypothesis_id"],
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def analyze_counterexamples(*, replay_path: Path) -> dict[str, object]:
    replay = json.loads(replay_path.read_text(encoding="utf-8"))
    rows = _list_of_dicts(replay.get("row_diagnostics"))
    hypotheses = _hypotheses()
    selected_repair_hypotheses = [
        _score_hypothesis(rows, hypothesis=hypothesis, label_key="label", lift_key="repair_lift_vs_trajectory")
        for hypothesis in hypotheses
    ]
    oracle_hypotheses = [
        _score_hypothesis(rows, hypothesis=hypothesis, label_key="oracle_label", lift_key="oracle_lift_vs_trajectory")
        for hypothesis in hypotheses
    ]
    selected_repair_hypotheses.sort(key=_hypothesis_sort_key)
    oracle_hypotheses.sort(key=_hypothesis_sort_key)
    return {
        "counterexample_rows": _counterexample_rows(rows),
        "generated_by": "experiments/analyze_diffusion_denoise_phase_realization_v13_counterexamples.py",
        "inputs": {"replay": str(replay_path)},
        "oracle_hypotheses": oracle_hypotheses,
        "schema": "diffusion_denoise_phase_realization_v13_counterexamples.v1",
        "selected_repair_hypotheses": selected_repair_hypotheses,
        "summary": {
            "broad_trigger_no_lift_task_ids": _task_ids(
                [
                    row
                    for row in rows
                    if bool(row.get("label_pass_denoise_trigger")) and not bool(row.get("label"))
                ]
            ),
            "counterexample_count": len(_counterexample_rows(rows)),
            "oracle_positive_count": sum(1 for row in rows if bool(row.get("oracle_label"))),
            "oracle_positive_task_ids": _task_ids([row for row in rows if bool(row.get("oracle_label"))]),
            "selected_repair_positive_count": sum(1 for row in rows if bool(row.get("label"))),
            "selected_repair_positive_task_ids": _task_ids([row for row in rows if bool(row.get("label"))]),
            "target_count": len(rows),
            "top_oracle_hypothesis": oracle_hypotheses[0]["hypothesis_id"] if oracle_hypotheses else None,
            "top_selected_hypothesis": selected_repair_hypotheses[0]["hypothesis_id"]
            if selected_repair_hypotheses
            else None,
        },
    }


