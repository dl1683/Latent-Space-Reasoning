"""Fit a tiny interpretable selector from composite diffusion target rows."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_TARGETS = Path("eval_results/diffusion_language/diffusion_composite_selector_targets.json")
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/diffusion_composite_selector_fit.json")
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_COMPOSITE_SELECTOR_FIT.md")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--targets", type=Path, default=DEFAULT_TARGETS)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    fit = fit_composite_selector(targets_path=args.targets)
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(fit, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(fit), encoding="utf-8")
    print(
        json.dumps(
            {
                "json_output": str(args.json_output),
                "report_output": str(args.report_output),
                "selected_heads": {
                    "realization": _dict(fit.get("realization_head")).get("rule_id", ""),
                    "retention": _dict(fit.get("retention_head")).get("rule_id", ""),
                    "source": _dict(fit.get("source_head")).get("rule_id", ""),
                    "spend": _dict(fit.get("spend_head")).get("rule_id", ""),
                },
                "training_error": _dict(fit.get("summary")).get("total_training_error", 0),
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def fit_composite_selector(*, targets_path: Path) -> dict[str, object]:
    dataset = json.loads(targets_path.read_text(encoding="utf-8"))
    task_rows = _list_of_dicts(dataset.get("task_targets"))
    realization_rows = _list_of_dicts(dataset.get("realization_policy_targets"))
    spend_head = _fit_binary_head(
        _spend_rules(task_rows),
        task_rows,
        label_field="spend_repair_label",
        unlabeled_value=None,
    )
    source_head = _fit_binary_head(
        _source_rules(task_rows),
        task_rows,
        label_field="source_trust_history_label",
        unlabeled_value=None,
    )
    retention_head = _fit_binary_head(
        _retention_rules(task_rows),
        task_rows,
        label_field="retention_safe_history_label",
        unlabeled_value=None,
    )
    realization_head = _fit_realization_head(realization_rows)
    return {
        "generated_by": "experiments/fit_diffusion_composite_selector.py",
        "inputs": {"targets": str(targets_path)},
        "realization_head": realization_head,
        "retention_head": retention_head,
        "schema": "diffusion_composite_selector_fit.v1",
        "source_head": source_head,
        "spend_head": spend_head,
        "summary": _summary(spend_head, source_head, retention_head, realization_head),
    }


def render_markdown(fit: dict[str, object]) -> str:
    summary = _dict(fit.get("summary"))
    lines = [
        "# Diffusion Composite Selector Fit",
        "",
        "This file is generated by `experiments/fit_diffusion_composite_selector.py`.",
        (
            "It fits a tiny CPU-safe interpretable selector over the four-term target "
            "surface: repair value, source trust, retention safety, and anchor realization."
        ),
        "",
        "## Summary",
        "",
        f"- Targets: `{_dict(fit.get('inputs')).get('targets', '')}`",
        f"- Total training error: `{summary.get('total_training_error', 0)}`",
        f"- Spend head: `{_dict(fit.get('spend_head')).get('rule_id', '')}`",
        f"- Source head: `{_dict(fit.get('source_head')).get('rule_id', '')}`",
        f"- Retention head: `{_dict(fit.get('retention_head')).get('rule_id', '')}`",
        f"- Realization head: `{_dict(fit.get('realization_head')).get('rule_id', '')}`",
        "",
        "## Head Fits",
        "",
        "| Head | Rule | Error | TP | FP | TN | FN | Prediction Surface |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for head_name in ("spend_head", "source_head", "retention_head"):
        head = _dict(fit.get(head_name))
        lines.append(
            "| "
            f"{head_name.replace('_head', '')} | "
            f"`{head.get('rule_id', '')}` | "
            f"{head.get('error_count', 0)} | "
            f"{head.get('true_positive_count', 0)} | "
            f"{head.get('false_positive_count', 0)} | "
            f"{head.get('true_negative_count', 0)} | "
            f"{head.get('false_negative_count', 0)} | "
            f"{_prediction_surface(head)} |"
        )
    realization = _dict(fit.get("realization_head"))
    lines.extend(
        [
            "",
            "## Realization Head",
            "",
            f"- Rule: `{realization.get('rule_id', '')}`",
            f"- Selected policy: `{realization.get('selected_policy_id', '')}`",
            f"- Error count: `{realization.get('error_count', 0)}`",
            "",
            "## Reading",
            "",
            (
                "This is intentionally small. It is a floor, not the final controller. "
                "A learned selector must beat this rule fit on held-out diffusion target "
                "surfaces before it is worth wiring into GPU runs."
            ),
        ]
    )
    return "\n".join(lines) + "\n"


def _fit_binary_head(
    rules: list[dict[str, object]],
    rows: list[dict[str, object]],
    *,
    label_field: str,
    unlabeled_value: object,
) -> dict[str, object]:
    scored = [_score_binary_rule(rule, rows, label_field, unlabeled_value) for rule in rules]
    return min(
        scored,
        key=lambda row: (
            int(row.get("error_count", 0)),
            int(row.get("false_positive_count", 0)),
            int(row.get("false_negative_count", 0)),
            int(row.get("complexity", 99)),
            str(row.get("rule_id", "")),
        ),
    )


def _score_binary_rule(
    rule: dict[str, object],
    rows: list[dict[str, object]],
    label_field: str,
    unlabeled_value: object,
) -> dict[str, object]:
    true_positive = false_positive = true_negative = false_negative = 0
    predictions = {}
    for row in rows:
        label = row.get(label_field)
        if label is unlabeled_value:
            continue
        predicted = _predict_rule(rule, row)
        predictions[str(row.get("task_id", ""))] = predicted
        if predicted and bool(label):
            true_positive += 1
        elif predicted and not bool(label):
            false_positive += 1
        elif not predicted and not bool(label):
            true_negative += 1
        else:
            false_negative += 1
    return {
        **rule,
        "error_count": false_positive + false_negative,
        "false_negative_count": false_negative,
        "false_positive_count": false_positive,
        "predictions": predictions,
        "true_negative_count": true_negative,
        "true_positive_count": true_positive,
    }


def _fit_realization_head(rows: list[dict[str, object]]) -> dict[str, object]:
    rules = [
        {"complexity": 0, "field": "realization_policy_error", "rule_id": "min_realization_policy_error"},
        {"complexity": 1, "field": "mean_realization_quality_loss", "rule_id": "min_realization_quality_loss"},
        {"complexity": 1, "field": "mean_meta_penalty", "rule_id": "min_meta_penalty"},
        {"complexity": 1, "field": "mean_seed_objective_score", "reverse": True, "rule_id": "max_seed_objective"},
        {"complexity": 1, "field": "mean_task_score", "reverse": True, "rule_id": "max_task_score"},
    ]
    scored = [_score_realization_rule(rule, rows) for rule in rules]
    return min(
        scored,
        key=lambda row: (
            int(row.get("error_count", 0)),
            _float(row.get("selected_policy_error")),
            int(row.get("complexity", 99)),
            str(row.get("rule_id", "")),
        ),
    )


def _score_realization_rule(rule: dict[str, object], rows: list[dict[str, object]]) -> dict[str, object]:
    reverse = bool(rule.get("reverse", False))
    field = str(rule.get("field", ""))
    selected = sorted(
        rows,
        key=lambda row: (
            -_float(row.get(field)) if reverse else _float(row.get(field)),
            str(row.get("policy_id", "")),
        ),
    )[0]
    selected_policy = str(selected.get("policy_id", ""))
    target_policy = next((str(row.get("policy_id", "")) for row in rows if row.get("selected")), "")
    return {
        **rule,
        "error_count": 0 if selected_policy == target_policy else 1,
        "selected_policy_error": _float(selected.get("realization_policy_error")),
        "selected_policy_id": selected_policy,
        "target_policy_id": target_policy,
    }


def _spend_rules(rows: list[dict[str, object]]) -> list[dict[str, object]]:
    rules = [
        {"complexity": 0, "rule_id": "spend_none", "type": "constant", "value": False},
        {"complexity": 1, "rule_id": "first_repairable_exists", "type": "exists", "field": "first_repairable_step"},
    ]
    for gap in _thresholds(rows, "prompt_gap_count"):
        rules.append(
            {
                "complexity": 2,
                "field": "prompt_gap_count",
                "max_value": gap,
                "requires_first_repairable": True,
                "rule_id": f"first_repairable_prompt_gap_le_{_slug(gap)}",
                "type": "max_threshold",
            }
        )
    for quality in _thresholds(rows, "source_quality"):
        rules.append(
            {
                "complexity": 2,
                "field": "source_quality",
                "max_value": quality,
                "requires_first_repairable": True,
                "rule_id": f"first_repairable_source_quality_le_{_slug(quality)}",
                "type": "max_threshold",
            }
        )
    for gap in _thresholds(rows, "prompt_gap_count"):
        for quality in _thresholds(rows, "source_quality"):
            rules.append(
                {
                    "complexity": 3,
                    "max_prompt_gap_count": gap,
                    "max_source_quality": quality,
                    "requires_first_repairable": True,
                    "rule_id": f"first_repairable_gap_le_{_slug(gap)}_source_quality_le_{_slug(quality)}",
                    "type": "gap_and_source_quality",
                }
            )
    return rules


def _source_rules(rows: list[dict[str, object]]) -> list[dict[str, object]]:
    labeled = [row for row in rows if row.get("source_trust_history_label") is not None]
    rules = [
        {"complexity": 0, "rule_id": "trust_none", "type": "constant", "value": False},
        {"complexity": 1, "field": "retention_safe_history_label", "rule_id": "retention_safe_history", "type": "bool_field"},
    ]
    for target_similarity in _thresholds(labeled, "target_similarity"):
        rules.append(
            {
                "complexity": 1,
                "field": "target_similarity",
                "min_value": target_similarity,
                "rule_id": f"target_similarity_ge_{_slug(target_similarity)}",
                "type": "min_threshold",
            }
        )
    for target_similarity in _thresholds(labeled, "target_similarity"):
        for text_similarity in _thresholds(labeled, "text_similarity"):
            rules.append(
                {
                    "complexity": 3,
                    "min_target_similarity": target_similarity,
                    "min_text_similarity": text_similarity,
                    "requires_retention_safe": True,
                    "rule_id": (
                        f"retention_safe_target_ge_{_slug(target_similarity)}_"
                        f"text_ge_{_slug(text_similarity)}"
                    ),
                    "type": "safe_similarity",
                }
            )
    return rules


def _retention_rules(rows: list[dict[str, object]]) -> list[dict[str, object]]:
    rules = [
        {"complexity": 0, "rule_id": "retention_safe_none", "type": "constant", "value": False},
        {
            "class_value": "safe_history_anchor",
            "complexity": 1,
            "field": "retention_classification",
            "rule_id": "classification_safe_history_anchor",
            "type": "class_equals",
        },
    ]
    for loss in _thresholds(rows, "constraint_retention_loss"):
        rules.append(
            {
                "complexity": 1,
                "field": "constraint_retention_loss",
                "max_value": loss,
                "rule_id": f"retention_loss_le_{_slug(loss)}",
                "type": "max_threshold",
            }
        )
    return rules


def _predict_rule(rule: dict[str, object], row: dict[str, object]) -> bool:
    rule_type = str(rule.get("type", ""))
    if bool(rule.get("requires_first_repairable")) and row.get("first_repairable_step") is None:
        return False
    if rule_type == "constant":
        return bool(rule.get("value", False))
    if rule_type == "exists":
        return row.get(str(rule.get("field", ""))) is not None
    if rule_type == "bool_field":
        return bool(row.get(str(rule.get("field", "")), False))
    if rule_type == "class_equals":
        return row.get(str(rule.get("field", ""))) == rule.get("class_value")
    if rule_type == "max_threshold":
        value = row.get(str(rule.get("field", "")))
        return value is not None and _float(value) <= _float(rule.get("max_value"))
    if rule_type == "min_threshold":
        value = row.get(str(rule.get("field", "")))
        return value is not None and _float(value) >= _float(rule.get("min_value"))
    if rule_type == "gap_and_source_quality":
        return (
            row.get("prompt_gap_count") is not None
            and row.get("source_quality") is not None
            and _float(row.get("prompt_gap_count")) <= _float(rule.get("max_prompt_gap_count"))
            and _float(row.get("source_quality")) <= _float(rule.get("max_source_quality"))
        )
    if rule_type == "safe_similarity":
        return (
            bool(row.get("retention_safe_history_label", False))
            and row.get("target_similarity") is not None
            and row.get("text_similarity") is not None
            and _float(row.get("target_similarity")) >= _float(rule.get("min_target_similarity"))
            and _float(row.get("text_similarity")) >= _float(rule.get("min_text_similarity"))
        )
    raise ValueError(f"unsupported rule type: {rule_type}")


def _summary(*heads: dict[str, object]) -> dict[str, object]:
    return {"total_training_error": sum(int(head.get("error_count", 0)) for head in heads)}


def _thresholds(rows: list[dict[str, object]], field: str) -> list[float]:
    return sorted({_float(row.get(field)) for row in rows if row.get(field) is not None})


def _prediction_surface(head: dict[str, object]) -> str:
    predictions = _dict(head.get("predictions"))
    positive = [task_id for task_id, predicted in predictions.items() if predicted]
    return ", ".join(f"`{task_id}`" for task_id in positive) if positive else "`none`"


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    return [row for row in value if isinstance(row, dict)] if isinstance(value, list) else []


def _float(value: object) -> float:
    if value is None:
        return 0.0
    return float(value)


def _slug(value: float) -> str:
    return f"{value:.6f}".rstrip("0").rstrip(".").replace(".", "p")


if __name__ == "__main__":
    raise SystemExit(main())
