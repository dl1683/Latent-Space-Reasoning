"""Fit Stage 1 rules that require valid counterfactual probe diagnostics."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_TARGETS = Path("eval_results/diffusion_language/diffusion_counterfactual_probe_targets_v1.json")
DEFAULT_SCORES = Path("eval_results/diffusion_language/counterfactual_micro_probe_tomography_all_v1_scores.json")
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/counterfactual_validated_probe_stage1_gate_v1.json")
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_COUNTERFACTUAL_VALIDATED_PROBE_STAGE1_GATE_V1.md")

MEASURED_FEATURES = (
    "measured_probe_value_prediction",
    "measured_expected_gap_visibility_gain",
    "measured_expected_realization_defect_visibility",
    "measured_expected_span_evidence_gain",
    "measured_expected_retention_risk_visibility",
)
TEXT_FEATURES = (
    "counterfactual_probe_text_slot_count",
    "counterfactual_probe_text_valid_for_stage1",
    "counterfactual_probe_text_placeholder_slot",
    "counterfactual_probe_text_generic_slot",
    "counterfactual_probe_text_weird_punctuation",
)
PREPROBE_FEATURES = (
    "prompt_gap_count",
    "source_quality",
    "would_probe_score",
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--targets", type=Path, default=DEFAULT_TARGETS)
    parser.add_argument("--scores", type=Path, default=DEFAULT_SCORES)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    fit = fit_validated_probe_stage1_gate(scores_path=args.scores, targets_path=args.targets)
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(fit, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(fit), encoding="utf-8")
    print(
        json.dumps(
            {
                "best_validated_rule": fit["summary"]["best_validated_rule_name"],
                "best_validated_errors": fit["summary"]["best_validated_error_count"],
                "gate_decision": fit["summary"]["gate_decision"],
                "invalid_positive_count": fit["summary"]["invalid_positive_count"],
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def fit_validated_probe_stage1_gate(*, scores_path: Path, targets_path: Path) -> dict[str, object]:
    scores = json.loads(scores_path.read_text(encoding="utf-8"))
    targets = json.loads(targets_path.read_text(encoding="utf-8"))
    target_rows = {
        str(row.get("task_id", "")): row
        for row in _list_of_dicts(targets.get("rows"))
    }
    rows = [
        _row_from_gate_row(row, target_rows.get(str(row.get("task_id", "")), {}))
        for row in _list_of_dicts(scores.get("repair_spend_gate_rows"))
        if row.get("counterfactual_probe_observation") == "measured_generation"
    ]
    rows.sort(key=lambda row: str(row.get("task_id", "")))
    validated_rules = _rank_rules(rows, MEASURED_FEATURES, require_valid_probe=True)
    all_feature_rules = _rank_rules(
        rows,
        (*MEASURED_FEATURES, *TEXT_FEATURES, *PREPROBE_FEATURES),
        require_valid_probe=False,
    )
    validated_best = validated_rules[0] if validated_rules else _empty_rule()
    all_best = all_feature_rules[0] if all_feature_rules else _empty_rule()
    return {
        "generated_by": "experiments/fit_diffusion_validated_probe_stage1_gate.py",
        "inputs": {
            "scores": str(scores_path),
            "targets": str(targets_path),
        },
        "rows": _rows_with_decisions(rows, validated_best, all_best),
        "schema": "diffusion_counterfactual_validated_probe_stage1_gate.v1",
        "summary": _summary(rows, validated_best, all_best, scores),
        "top_all_feature_rules": all_feature_rules[:20],
        "top_validated_rules": validated_rules[:20],
    }


