"""Build first counterfactual-probe target rows for diffusion spend control."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_WORKBENCH = Path("eval_results/diffusion_language/diffusion_spend_counterexample_workbench.json")
DEFAULT_EDGE_PROXY = Path("eval_results/diffusion_language/diffusion_pre_repair_edge_proxy_v1.json")
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/diffusion_counterfactual_probe_targets_v1.json")
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_COUNTERFACTUAL_PROBE_TARGETS_V1.md")
DEFAULT_PROBE_POLICY = "deterministic_missing_constraint_probe_v1"
DEFAULT_PROBE_COST_RELATIVE = 0.125

PRE_PROBE_FEATURES = (
    "source_quality",
    "source_task_delta_vs_trajectory",
    "prompt_gap_count",
    "first_repairable_step",
    "degeneracy_score",
    "max_span_target_score",
    "min_span_source_relative_preservation",
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workbench", type=Path, default=DEFAULT_WORKBENCH)
    parser.add_argument("--edge-proxy", type=Path, default=DEFAULT_EDGE_PROXY)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    parser.add_argument("--probe-cost-relative", type=float, default=DEFAULT_PROBE_COST_RELATIVE)
    parser.add_argument("--probe-policy", default=DEFAULT_PROBE_POLICY)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    targets = build_counterfactual_probe_targets(
        edge_proxy_path=args.edge_proxy,
        probe_cost_relative=args.probe_cost_relative,
        probe_policy=args.probe_policy,
        workbench_path=args.workbench,
    )
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(targets, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(targets), encoding="utf-8")
    print(
        json.dumps(
            {
                "gate_decision": targets["summary"]["gate_decision"],
                "json_output": str(args.json_output),
                "probe_row_count": targets["summary"]["probe_row_count"],
                "report_output": str(args.report_output),
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def build_counterfactual_probe_targets(
    *,
    edge_proxy_path: Path,
    probe_cost_relative: float,
    probe_policy: str,
    workbench_path: Path,
) -> dict[str, object]:
    workbench = json.loads(workbench_path.read_text(encoding="utf-8"))
    edge_proxy = json.loads(edge_proxy_path.read_text(encoding="utf-8"))
    edge_rows = {str(row.get("task_id", "")): row for row in _list_of_dicts(edge_proxy.get("rows"))}
    counterexamples = _list_of_dicts(workbench.get("counterexamples"))
    rows = []
    for counterexample in counterexamples:
        task_id = str(counterexample.get("task_id", ""))
        edge = edge_rows.get(task_id, {})
        rows.append(
            _probe_row(
                counterexample=counterexample,
                edge=edge,
                probe_cost_relative=probe_cost_relative,
                probe_policy=probe_policy,
            )
        )
    rows.sort(key=lambda row: (str(row.get("counterexample_type", "")), str(row.get("task_id", ""))))
    return {
        "generated_by": "experiments/build_diffusion_counterfactual_probe_targets.py",
        "inputs": {
            "edge_proxy": str(edge_proxy_path),
            "workbench": str(workbench_path),
        },
        "probe_policy": probe_policy,
        "rows": rows,
        "schema": "diffusion_counterfactual_probe_targets.v1",
        "summary": _summary(rows, probe_cost_relative=probe_cost_relative),
    }


def render_markdown(targets: dict[str, object]) -> str:
    summary = _dict(targets.get("summary"))
    lines = [
        "# Diffusion Counterfactual Probe Targets V1",
        "",
        "This file is generated by `experiments/build_diffusion_counterfactual_probe_targets.py`.",
        (
            "It creates the first replayable probe-target sheet for the named v5-v9 "
            "spend counterexamples. The probe rows are deterministic scaffolds, not "
            "a promoted GPU probe result."
        ),
        "",
        "## Summary",
        "",
        f"- Probe rows: `{summary.get('probe_row_count', 0)}`",
        f"- Positive labels: `{summary.get('positive_label_count', 0)}`",
        f"- Negative labels: `{summary.get('negative_label_count', 0)}`",
        f"- Probe policy: `{targets.get('probe_policy', '')}`",
        f"- Probe cost relative: `{_format_float(summary.get('probe_cost_relative'))}`",
        f"- Total positive lift: `{_format_float(summary.get('total_positive_lift'))}`",
        f"- Gate decision: `{summary.get('gate_decision', '')}`",
        "",
        "## Rows",
        "",
        (
            "| Task | Type | Promote | Lift | Probe Score | Would Probe | Gap | Source Quality | "
            "Degeneration | Span Score | Probe Text |"
        ),
        "| --- | --- | --- | ---: | ---: | --- | ---: | ---: | ---: | ---: | --- |",
    ]
    for row in _list_of_dicts(targets.get("rows")):
        pre = _dict(row.get("pre_probe_features"))
        labels = _dict(row.get("labels"))
        lines.append(
            "| "
            f"`{row.get('task_id', '')}` | "
            f"`{row.get('counterexample_type', '')}` | "
            f"{bool(labels.get('promote_vs_trajectory'))} | "
            f"{_format_float(labels.get('candidate_lift_vs_trajectory'))} | "
            f"{_format_float(row.get('probe_value_prediction'))} | "
            f"{bool(row.get('would_probe'))} | "
            f"{int(_float(pre.get('prompt_gap_count')))} | "
            f"{_format_float(pre.get('source_quality'))} | "
            f"{_format_float(pre.get('degeneracy_score'))} | "
            f"{_format_float(pre.get('max_span_target_score'))} | "
            f"{_short_text(row.get('probe_text'))} |"
        )
    lines.extend(
        [
            "",
            "## Reading",
            "",
            (
                "This artifact is the target surface for the next micro-probe harness. "
                "It keeps labels separate from pre-probe features and gives every "
                "named counterexample a replayable probe row. It does not authorize "
                "a live spend gate; it only defines what the first cheap probe run "
                "must replace with measured probe deltas."
            ),
        ]
    )
    return "\n".join(lines) + "\n"


def _probe_row(
    *,
    counterexample: dict[str, object],
    edge: dict[str, object],
    probe_cost_relative: float,
    probe_policy: str,
) -> dict[str, object]:
    task_id = str(counterexample.get("task_id", ""))
    pre_probe_features = {
        feature: _float(edge.get(feature, counterexample.get(feature))) for feature in PRE_PROBE_FEATURES
    }
    probe_feature_delta = _probe_feature_delta(pre_probe_features)
    probe_value_prediction = _probe_value_prediction(pre_probe_features, probe_feature_delta)
    return {
        "counterexample_type": str(counterexample.get("error_type", "")),
        "labels": {
            "candidate_lift_vs_trajectory": _float(edge.get("candidate_lift_vs_trajectory", counterexample.get("repair_lift"))),
            "promote_vs_trajectory": bool(edge.get("label", counterexample.get("repair_lift", 0.0))),
            "repair_lift": _float(counterexample.get("repair_lift")),
            "repair_selector_edge": _float(counterexample.get("repair_selector_edge")),
        },
        "pre_probe_features": pre_probe_features,
        "probe_cost_relative": probe_cost_relative,
        "probe_feature_delta": probe_feature_delta,
        "probe_policy": probe_policy,
        "probe_text": _probe_text(task_id, pre_probe_features),
        "probe_value_prediction": probe_value_prediction,
        "task_id": task_id,
        "would_probe": probe_value_prediction >= probe_cost_relative * 0.08,
    }


def _probe_feature_delta(features: dict[str, float]) -> dict[str, float]:
    gap = _float(features.get("prompt_gap_count"))
    degeneration = _float(features.get("degeneracy_score"))
    span = _float(features.get("max_span_target_score"))
    preservation = _float(features.get("min_span_source_relative_preservation"))
    return {
        "expected_gap_visibility_gain": min(1.0, gap / 12.0),
        "expected_realization_defect_visibility": min(1.0, degeneration / 0.75),
        "expected_span_evidence_gain": min(1.0, span / 2.5),
        "expected_retention_risk_visibility": 1.0 - min(1.0, preservation),
    }


def _probe_value_prediction(features: dict[str, float], delta: dict[str, float]) -> float:
    source_quality = _float(features.get("source_quality"))
    source_delta = _float(features.get("source_task_delta_vs_trajectory"))
    gap_visibility = _float(delta.get("expected_gap_visibility_gain"))
    span_gain = _float(delta.get("expected_span_evidence_gain"))
    defect_visibility = _float(delta.get("expected_realization_defect_visibility"))
    retention_risk = _float(delta.get("expected_retention_risk_visibility"))
    raw = (
        0.035 * gap_visibility
        + 0.030 * span_gain
        + 0.020 * defect_visibility
        - 0.020 * retention_risk
        - 0.015 * max(0.0, source_quality - 0.30)
        + 0.010 * max(0.0, source_delta)
    )
    return max(0.0, raw)


def _probe_text(task_id: str, features: dict[str, float]) -> str:
    return (
        f"Probe {task_id}: expose missing constraints before repair; "
        f"gap={int(_float(features.get('prompt_gap_count')))}, "
        f"source_quality={_format_float(features.get('source_quality'))}, "
        f"degeneration={_format_float(features.get('degeneracy_score'))}, "
        f"span_score={_format_float(features.get('max_span_target_score'))}."
    )


def _summary(rows: list[dict[str, object]], *, probe_cost_relative: float) -> dict[str, object]:
    positives = [row for row in rows if bool(_dict(row.get("labels")).get("promote_vs_trajectory"))]
    negatives = [row for row in rows if not bool(_dict(row.get("labels")).get("promote_vs_trajectory"))]
    return {
        "gate_decision": "diagnostic_only",
        "negative_label_count": len(negatives),
        "positive_label_count": len(positives),
        "probe_cost_relative": probe_cost_relative,
        "probe_row_count": len(rows),
        "total_positive_lift": sum(
            _float(_dict(row.get("labels")).get("candidate_lift_vs_trajectory")) for row in positives
        ),
        "would_probe_count": sum(1 for row in rows if bool(row.get("would_probe"))),
    }


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    if not isinstance(value, list):
        return []
    return [item for item in value if isinstance(item, dict)]


def _float(value: object) -> float:
    if value is None:
        return 0.0
    try:
        return float(value)
    except (TypeError, ValueError):
        return 0.0


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


def _short_text(value: object, limit: int = 90) -> str:
    text = " ".join(str(value or "").split())
    text = text.replace("|", "\\|")
    if len(text) <= limit:
        return text
    return text[: limit - 3] + "..."


if __name__ == "__main__":
    raise SystemExit(main())
