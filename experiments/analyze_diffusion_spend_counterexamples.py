"""Analyze spend-gate counterexamples for the next diffusion controller."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_SPEND_GATE_FIT = Path("eval_results/diffusion_language/diffusion_spend_gate_v9_fit.json")
DEFAULT_PROMOTION_TARGETS = Path(
    "eval_results/diffusion_language/diffusion_candidate_promotion_targets_v9.json"
)
DEFAULT_JSON_OUTPUT = Path(
    "eval_results/diffusion_language/diffusion_spend_counterexample_workbench.json"
)
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_SPEND_COUNTEREXAMPLE_WORKBENCH.md")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spend-gate-fit", type=Path, default=DEFAULT_SPEND_GATE_FIT)
    parser.add_argument("--promotion-targets", type=Path, default=DEFAULT_PROMOTION_TARGETS)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    workbench = build_counterexample_workbench(
        promotion_targets_path=args.promotion_targets,
        spend_gate_fit_path=args.spend_gate_fit,
    )
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(workbench, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(workbench), encoding="utf-8")
    print(
        json.dumps(
            {
                "active_question_count": len(_list_of_dicts(workbench.get("active_questions"))),
                "counterexample_count": len(_list_of_dicts(workbench.get("counterexamples"))),
                "json_output": str(args.json_output),
                "report_output": str(args.report_output),
                "rule_id": _dict(workbench.get("best_rule")).get("rule_id", ""),
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def build_counterexample_workbench(
    *,
    promotion_targets_path: Path,
    spend_gate_fit_path: Path,
) -> dict[str, object]:
    spend_fit = json.loads(spend_gate_fit_path.read_text(encoding="utf-8"))
    promotion_targets = json.loads(promotion_targets_path.read_text(encoding="utf-8"))
    best_rule = _dict(_dict(spend_fit.get("summary")).get("best_rule"))
    rows = _list_of_dicts(spend_fit.get("rows"))
    predictions = {str(k): bool(v) for k, v in _dict(best_rule.get("predictions")).items()}
    promotion_by_task = {
        str(row.get("task_id", "")): row for row in _list_of_dicts(promotion_targets.get("rows"))
    }
    counterexamples = [
        _counterexample_row(row, predictions=predictions, promotion_by_task=promotion_by_task)
        for row in rows
        if bool(row.get("profitable")) != bool(predictions.get(str(row.get("task_id", ""))))
    ]
    counterexamples.sort(
        key=lambda row: (
            str(row.get("error_type", "")),
            -float(row.get("repair_lift", 0.0)),
            str(row.get("task_id", "")),
        )
    )
    clusters = _clusters(counterexamples)
    active_questions = _active_questions(counterexamples, clusters)
    return {
        "active_questions": active_questions,
        "best_rule": {
            "conditions": best_rule.get("conditions", []),
            "error_count": best_rule.get("error_count", 0),
            "false_negative_count": best_rule.get("false_negative_count", 0),
            "false_positive_count": best_rule.get("false_positive_count", 0),
            "missed_profitable_tasks": best_rule.get("missed_profitable_tasks", []),
            "no_lift_selected_tasks": best_rule.get("no_lift_selected_tasks", []),
            "positive_lift_covered": best_rule.get("positive_lift_covered", 0.0),
            "rule_id": best_rule.get("rule_id", ""),
        },
        "clusters": clusters,
        "counterexamples": counterexamples,
        "generated_by": "experiments/analyze_diffusion_spend_counterexamples.py",
        "inputs": {
            "promotion_targets": str(promotion_targets_path),
            "spend_gate_fit": str(spend_gate_fit_path),
        },
        "next_controller_contract": _next_controller_contract(counterexamples),
        "schema": "diffusion_spend_counterexample_workbench.v1",
        "summary": _summary(spend_fit, promotion_targets, counterexamples),
    }


def render_markdown(workbench: dict[str, object]) -> str:
    summary = _dict(workbench.get("summary"))
    best_rule = _dict(workbench.get("best_rule"))
    contract = _dict(workbench.get("next_controller_contract"))
    lines = [
        "# Diffusion Spend Counterexample Workbench",
        "",
        "This file is generated by `experiments/analyze_diffusion_spend_counterexamples.py`.",
        (
            "It converts the accumulated failed spend-gate fit into controller design "
            "questions. The goal is not to promote another threshold; it is to "
            "identify what a next-generation spend controller must know before "
            "using GPU repair budget."
        ),
        "",
        "## Summary",
        "",
        f"- Spend rows: `{summary.get('target_count', 0)}`",
        f"- Profitable rows: `{summary.get('profitable_count', 0)}`",
        f"- Best simple rule: `{best_rule.get('rule_id', '')}`",
        f"- Best simple rule errors: `{best_rule.get('error_count', 0)}`",
        f"- False positives: `{best_rule.get('false_positive_count', 0)}`",
        f"- False negatives: `{best_rule.get('false_negative_count', 0)}`",
        f"- Promotion errors: `{summary.get('promotion_error_count', 0)}`",
        f"- Promotion positives: {_join_tasks(summary.get('promotion_positive_tasks'))}",
        "",
        "## Counterexamples",
        "",
        "| Task | Type | Lesson | Repair Lift | Gap | Source Quality | Source Delta | Selector Edge |",
        "| --- | --- | --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for row in _list_of_dicts(workbench.get("counterexamples")):
        lines.append(
            "| "
            f"`{row.get('task_id', '')}` | "
            f"`{row.get('error_type', '')}` | "
            f"{row.get('lesson', '')} | "
            f"{_format_float(row.get('repair_lift'))} | "
            f"{int(_float(row.get('prompt_gap_count')))} | "
            f"{_format_float(row.get('source_quality'))} | "
            f"{_format_float(row.get('source_task_delta_vs_trajectory'))} | "
            f"{_format_float(row.get('repair_selector_edge'))} |"
        )
    lines.extend(["", "## Clusters", ""])
    for cluster in _list_of_dicts(workbench.get("clusters")):
        lines.append(
            "- "
            f"`{cluster.get('cluster_id', '')}`: "
            f"{_join_tasks(cluster.get('tasks'))}; "
            f"{cluster.get('reading', '')}"
        )
    lines.extend(["", "## Active Questions", ""])
    for question in _list_of_dicts(workbench.get("active_questions")):
        lines.append(
            "- "
            f"`{question.get('question_id', '')}`: "
            f"{question.get('question', '')} "
            f"Evidence: {_join_tasks(question.get('evidence_tasks'))}. "
            f"Next measurement: {question.get('next_measurement', '')}"
        )
    lines.extend(
        [
            "",
            "## Next Controller Contract",
            "",
            f"- Required data: {contract.get('required_data', '')}",
            f"- Promotion invariant: {contract.get('promotion_invariant', '')}",
            f"- Spend invariant: {contract.get('spend_invariant', '')}",
            f"- GPU gate: {contract.get('gpu_gate', '')}",
            "",
            "## Reading",
            "",
            (
                "The accumulated transfer results make the controller split concrete. Post-repair "
                "promotion is stable on the generated candidates, but pre-repair "
                "spend is not separable by a small conjunction of source quality, "
                "prompt gap, denoise phase, and trajectory-relative delta. The next "
                "architecture should therefore use counterexample-driven active "
                "data collection or a richer value model before attempting another "
                "live spend gate."
            ),
        ]
    )
    return "\n".join(lines) + "\n"


def _counterexample_row(
    row: dict[str, object],
    *,
    predictions: dict[str, bool],
    promotion_by_task: dict[str, dict[str, object]],
) -> dict[str, object]:
    task_id = str(row.get("task_id", ""))
    prediction = bool(predictions.get(task_id))
    profitable = bool(row.get("profitable"))
    promotion = _dict(promotion_by_task.get(task_id))
    error_type = "false_positive" if prediction and not profitable else "false_negative"
    return {
        "error_type": error_type,
        "lesson": _lesson(row, error_type=error_type, promotion=promotion),
        "prompt_gap_count": _float(row.get("prompt_gap_count")),
        "repair_lift": _float(row.get("repair_lift")),
        "repair_selector_edge": _float(promotion.get("repair_selector_edge")),
        "source_quality": _float(row.get("source_quality")),
        "source_task_delta_vs_trajectory": _float(row.get("source_task_delta_vs_trajectory")),
        "task_id": task_id,
    }


def _lesson(
    row: dict[str, object],
    *,
    error_type: str,
    promotion: dict[str, object],
) -> str:
    gap = _float(row.get("prompt_gap_count"))
    delta = _float(row.get("source_task_delta_vs_trajectory"))
    edge = _float(promotion.get("repair_selector_edge"))
    if error_type == "false_negative" and gap < 8:
        return "low-gap profitable repair; prompt-gap floor is too brittle"
    if error_type == "false_negative" and delta > 0.03:
        return "source already beats trajectory but repair is still profitable"
    if error_type == "false_positive" and gap >= 8:
        return "high-gap no-lift repair; missing terms alone overpredict value"
    if error_type == "false_positive" and edge <= 0.0:
        return "repair candidate has no promotion edge despite repairable phase"
    return "threshold conjunction cannot separate this row"


def _clusters(counterexamples: list[dict[str, object]]) -> list[dict[str, object]]:
    cluster_specs = [
        (
            "low_gap_profitable_false_negatives",
            lambda row: row.get("error_type") == "false_negative"
            and _float(row.get("prompt_gap_count")) < 8,
            "Profitable repairs can appear outside the best rule's prompt-gap floor.",
        ),
        (
            "high_gap_no_lift_false_positives",
            lambda row: row.get("error_type") == "false_positive"
            and _float(row.get("prompt_gap_count")) >= 8,
            "High prompt-gap rows can still be no-lift, so gap is not repair value.",
        ),
        (
            "positive_source_delta_false_negatives",
            lambda row: row.get("error_type") == "false_negative"
            and _float(row.get("source_task_delta_vs_trajectory")) > 0.03,
            "A source that already beats trajectory can still deserve repair.",
        ),
        (
            "zero_edge_false_positives",
            lambda row: row.get("error_type") == "false_positive"
            and _float(row.get("repair_selector_edge")) <= 0.0,
            "Some repairable states produce candidates with no post-repair promotion edge.",
        ),
    ]
    clusters = []
    for cluster_id, predicate, reading in cluster_specs:
        tasks = [str(row.get("task_id", "")) for row in counterexamples if predicate(row)]
        if tasks:
            clusters.append({"cluster_id": cluster_id, "reading": reading, "tasks": tasks})
    return clusters


def _active_questions(
    counterexamples: list[dict[str, object]],
    clusters: list[dict[str, object]],
) -> list[dict[str, object]]:
    cluster_tasks = {str(c.get("cluster_id")): list(c.get("tasks", [])) for c in clusters}
    questions = [
        {
            "evidence_tasks": cluster_tasks.get("low_gap_profitable_false_negatives", []),
            "next_measurement": (
                "Collect fresh low-gap repairable rows and check candidate lift before "
                "raising any prompt-gap threshold."
            ),
            "question": (
                "When prompt gap is low, which denoise/source features distinguish a "
                "hidden profitable repair from a true no-lift row?"
            ),
            "question_id": "low_gap_value_probe",
        },
        {
            "evidence_tasks": cluster_tasks.get("high_gap_no_lift_false_positives", []),
            "next_measurement": (
                "Add post-repair edge prediction or source-retention features before "
                "spending on high-gap rows."
            ),
            "question": (
                "Which high-gap rows are actually repair-value rows rather than "
                "keyword-missing rows?"
            ),
            "question_id": "high_gap_waste_probe",
        },
        {
            "evidence_tasks": cluster_tasks.get("zero_edge_false_positives", []),
            "next_measurement": (
                "Estimate candidate realization or promotion edge before live repair "
                "using only frozen source and span diagnostics."
            ),
            "question": (
                "Can the controller predict candidate promotion edge before generating "
                "the repair candidate?"
            ),
            "question_id": "pre_repair_edge_proxy",
        },
    ]
    return [question for question in questions if question["evidence_tasks"]] or [
        {
            "evidence_tasks": [str(row.get("task_id", "")) for row in counterexamples],
            "next_measurement": "Run another all-repairable slice and inspect threshold errors.",
            "question": "Which counterexample family dominates the next slice?",
            "question_id": "counterexample_family_probe",
        }
    ]


def _next_controller_contract(counterexamples: list[dict[str, object]]) -> dict[str, str]:
    return {
        "gpu_gate": (
            "Do not run a live spend-gated policy until offline evaluation preserves "
            "all profitable rows or explicitly trades a named lift amount for cost."
        ),
        "promotion_invariant": (
            "Keep `candidate_aware_promotion_v1` fixed until a challenger beats its "
            "zero-error generated-candidate record."
        ),
        "required_data": (
            "All-repairable raw generations, spend labels, generated-candidate "
            "promotion labels, and per-task cost/lift rows."
        ),
        "spend_invariant": (
            "A spend controller must report false positives and false negatives "
            "separately; average score alone is not enough."
        ),
    }


def _summary(
    spend_fit: dict[str, object],
    promotion_targets: dict[str, object],
    counterexamples: list[dict[str, object]],
) -> dict[str, object]:
    spend_summary = _dict(spend_fit.get("summary"))
    promotion_summary = _dict(promotion_targets.get("summary"))
    return {
        "counterexample_count": len(counterexamples),
        "profitable_count": spend_summary.get("profitable_count", 0),
        "promotion_error_count": promotion_summary.get("candidate_aware_promotion_error_count", 0),
        "promotion_positive_tasks": promotion_summary.get("positive_tasks", []),
        "target_count": spend_summary.get("target_count", 0),
    }


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    return [row for row in value if isinstance(row, dict)] if isinstance(value, list) else []


def _float(value: object) -> float:
    if value is None:
        return 0.0
    return float(value)


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


def _join_tasks(value: object) -> str:
    tasks = [str(task) for task in value] if isinstance(value, list) else []
    return "`none`" if not tasks else ", ".join(f"`{task}`" for task in tasks)


