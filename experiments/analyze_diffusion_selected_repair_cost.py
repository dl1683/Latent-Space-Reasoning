"""Compare selected-repair policies under explicit selected-output cost."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_HOOK_SCORES = Path("eval_results/diffusion_language/generated_repair_value_hook_v19_label_scores.json")
DEFAULT_CONTROL_SCORES = Path(
    "eval_results/diffusion_language/generated_repair_value_hook_v19_broad_denoise_control_scores.json"
)
DEFAULT_TARGETS = Path("eval_results/diffusion_language/generated_repair_value_hook_v19_targets.json")
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/generated_repair_value_hook_v19_selected_cost_audit.json")
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_GENERATED_REPAIR_VALUE_HOOK_V19_SELECTED_COST_AUDIT.md")
DEFAULT_SUBSTANTIAL_LIFT = 0.02


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--hook-scores", type=Path, default=DEFAULT_HOOK_SCORES)
    parser.add_argument("--control-scores", type=Path, default=DEFAULT_CONTROL_SCORES)
    parser.add_argument("--targets", type=Path, default=DEFAULT_TARGETS)
    parser.add_argument("--substantial-lift", type=float, default=DEFAULT_SUBSTANTIAL_LIFT)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    audit = build_selected_repair_cost_audit(
        hook_scores_path=args.hook_scores,
        control_scores_path=args.control_scores,
        targets_path=args.targets,
        substantial_lift=args.substantial_lift,
    )
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(audit, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(audit), encoding="utf-8")
    print(
        json.dumps(
            {
                "json_output": str(args.json_output),
                "policy_count": len(_list_of_dicts(audit.get("policies"))),
                "report_output": str(args.report_output),
                "selected_policy": _dict(audit.get("selected_policy")).get("policy_id", ""),
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def build_selected_repair_cost_audit(
    *,
    hook_scores_path: Path,
    control_scores_path: Path,
    targets_path: Path,
    substantial_lift: float = DEFAULT_SUBSTANTIAL_LIFT,
) -> dict[str, object]:
    targets = json.loads(targets_path.read_text(encoding="utf-8"))
    target_by_task = {
        str(row.get("task_id", "")): row for row in _list_of_dicts(targets.get("rows"))
    }
    policies = [
        _policy_row(
            policy_id="generated_repair_value_v1",
            scores_path=hook_scores_path,
            target_by_task=target_by_task,
            substantial_lift=substantial_lift,
        ),
        _policy_row(
            policy_id="planning_quality_zero_margin",
            scores_path=control_scores_path,
            target_by_task=target_by_task,
            substantial_lift=substantial_lift,
        ),
    ]
    selected = max(
        policies,
        key=lambda row: (
            _float(row.get("substantial_selected_count")),
            -_float(row.get("waste_selected_count")),
            _float(row.get("repair_task_delta_vs_evolved")),
            -_float(row.get("selected_repair_pool_count")),
        ),
    )
    return {
        "generated_by": "experiments/analyze_diffusion_selected_repair_cost.py",
        "inputs": {
            "control_scores": str(control_scores_path),
            "hook_scores": str(hook_scores_path),
            "targets": str(targets_path),
        },
        "policies": policies,
        "schema": "diffusion_selected_repair_cost_audit.v1",
        "selected_policy": selected,
        "substantial_lift": substantial_lift,
        "summary": _summary(policies, substantial_lift=substantial_lift),
    }


def render_markdown(audit: dict[str, object]) -> str:
    summary = _dict(audit.get("summary"))
    selected = _dict(audit.get("selected_policy"))
    lines = [
        "# Diffusion Selected-Repair Cost Audit",
        "",
        "This file is generated by `experiments/analyze_diffusion_selected_repair_cost.py`.",
        (
            "It charges policies for selected repair-pool outputs, not just generated "
            "candidates. This separates aggregate task utility from allocation precision."
        ),
        "",
        "## Summary",
        "",
        f"- Targets: `{_dict(audit.get('inputs')).get('targets', '')}`",
        f"- Substantial-lift threshold: `{_format_float(audit.get('substantial_lift'))}`",
        f"- Selected precision policy: `{selected.get('policy_id', '')}`",
        f"- Hook selected tasks: {_join_tasks(summary.get('hook_selected_tasks'))}",
        f"- Control selected tasks: {_join_tasks(summary.get('control_selected_tasks'))}",
        f"- Control-only selected tasks: {_join_tasks(summary.get('control_only_selected_tasks'))}",
        f"- Control-only waste tasks: {_join_tasks(summary.get('control_only_waste_tasks'))}",
        f"- Aggregate utility parity: `{bool(summary.get('aggregate_utility_parity'))}`",
        "",
        "## Policy Comparison",
        "",
        (
            "| Policy | Run | Selector | Margin | Selected | Substantial | Tiny | No-Lift | "
            "Waste | Missed Positives | Delta vs Evolved | Delta/Extra Gen |"
        ),
        "| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | --- | ---: | ---: |",
    ]
    for row in _list_of_dicts(audit.get("policies")):
        lines.append(
            "| "
            f"`{row.get('policy_id', '')}` | "
            f"`{row.get('run_id', '')}` | "
            f"`{row.get('repair_selector', '')}` | "
            f"{_format_float(row.get('repair_promotion_margin'))} | "
            f"{row.get('selected_repair_pool_count', 0)} | "
            f"{row.get('substantial_selected_count', 0)} | "
            f"{row.get('tiny_selected_count', 0)} | "
            f"{row.get('no_lift_selected_count', 0)} | "
            f"{row.get('waste_selected_count', 0)} | "
            f"{_join_tasks(row.get('missed_positive_tasks'))} | "
            f"{_format_float(row.get('repair_task_delta_vs_evolved'))} | "
            f"{_format_float(row.get('repair_task_delta_per_extra_generation_vs_evolved'))} |"
        )
    lines.extend(
        [
            "",
            "## Cost Sweep",
            "",
            (
                "Scores below subtract `selected_cost / repair_covered_task` from the "
                "repair task delta versus evolved. Because the policies have equal task "
                "delta, any positive selected-output cost favors the hook."
            ),
            "",
            "| Selected Cost | Hook Net | Control Net | Hook Advantage |",
            "| ---: | ---: | ---: | ---: |",
        ]
    )
    for row in _list_of_dicts(summary.get("cost_sweep")):
        lines.append(
            "| "
            f"{_format_float(row.get('selected_cost'))} | "
            f"{_format_float(row.get('hook_net'))} | "
            f"{_format_float(row.get('control_net'))} | "
            f"{_format_float(row.get('hook_advantage'))} |"
        )
    lines.extend(
        [
            "",
            "## Reading",
            "",
            (
                "The permissive control matches the hook on aggregate task utility, but it "
                "requires two extra selected repair-pool decisions: no-lift `plan_150` and "
                "tiny-lift `plan_151`. With zero selected-output cost the policies tie; with "
                "any positive selected-output cost the hook is the better allocation policy. "
                "This supports precision, not broad promotion."
            ),
        ]
    )
    return "\n".join(lines) + "\n"


def _policy_row(
    *,
    policy_id: str,
    scores_path: Path,
    target_by_task: dict[str, dict[str, object]],
    substantial_lift: float,
) -> dict[str, object]:
    scores = json.loads(scores_path.read_text(encoding="utf-8"))
    selected_rows = [
        row
        for row in _list_of_dicts(scores.get("comparison_rows"))
        if _selected_repair_pool(row)
    ]
    selected_tasks = [str(row.get("task_id", "")) for row in selected_rows]
    selected_targets = [_dict(target_by_task.get(task_id)) for task_id in selected_tasks]
    positive_tasks = [
        task_id
        for task_id, target in target_by_task.items()
        if _float(target.get("candidate_lift_vs_trajectory")) > 0.0
    ]
    substantial = [
        str(target.get("task_id", ""))
        for target in selected_targets
        if _float(target.get("candidate_lift_vs_trajectory")) >= substantial_lift
    ]
    tiny = [
        str(target.get("task_id", ""))
        for target in selected_targets
        if 0.0 < _float(target.get("candidate_lift_vs_trajectory")) < substantial_lift
    ]
    no_lift = [
        str(target.get("task_id", ""))
        for target in selected_targets
        if _float(target.get("candidate_lift_vs_trajectory")) <= 0.0
    ]
    missed = [task_id for task_id in positive_tasks if task_id not in selected_tasks]
    return {
        "gross_selected_candidate_lift": sum(
            max(0.0, _float(target.get("candidate_lift_vs_trajectory")))
            for target in selected_targets
        ),
        "missed_positive_tasks": missed,
        "no_lift_selected_count": len(no_lift),
        "no_lift_selected_tasks": no_lift,
        "policy_id": policy_id,
        "repair_promotion_margin": _float(scores.get("repair_promotion_margin")),
        "repair_selector": str(scores.get("repair_selector", "")),
        "repair_task_delta_per_extra_generation_vs_evolved": _float(
            scores.get("repair_task_delta_per_extra_generation_vs_evolved")
        ),
        "repair_task_delta_vs_evolved": _float(scores.get("repair_task_delta_vs_evolved")),
        "repair_covered_count": int(_float(_dict(_dict(scores.get("arms")).get("repair_selected")).get("count"))),
        "run_id": str(scores.get("run_id", "")),
        "scores_path": str(scores_path),
        "selected_repair_pool_count": len(selected_tasks),
        "selected_repair_pool_tasks": selected_tasks,
        "substantial_selected_count": len(substantial),
        "substantial_selected_tasks": substantial,
        "tiny_selected_count": len(tiny),
        "tiny_selected_tasks": tiny,
        "waste_selected_count": len(tiny) + len(no_lift),
        "waste_selected_tasks": no_lift + tiny,
    }


def _summary(policies: list[dict[str, object]], *, substantial_lift: float) -> dict[str, object]:
    by_id = {str(row.get("policy_id", "")): row for row in policies}
    hook = _dict(by_id.get("generated_repair_value_v1"))
    control = _dict(by_id.get("planning_quality_zero_margin"))
    hook_tasks = set(_string_list(hook.get("selected_repair_pool_tasks")))
    control_tasks = set(_string_list(control.get("selected_repair_pool_tasks")))
    control_only = sorted(control_tasks - hook_tasks)
    control_waste = set(_string_list(control.get("waste_selected_tasks")))
    return {
        "aggregate_utility_parity": _float(hook.get("repair_task_delta_vs_evolved")) == _float(
            control.get("repair_task_delta_vs_evolved")
        ),
        "control_only_selected_tasks": control_only,
        "control_only_waste_tasks": [task_id for task_id in control_only if task_id in control_waste],
        "control_selected_tasks": _string_list(control.get("selected_repair_pool_tasks")),
        "cost_sweep": _cost_sweep(hook, control),
        "hook_selected_tasks": _string_list(hook.get("selected_repair_pool_tasks")),
        "substantial_lift": substantial_lift,
    }


def _cost_sweep(hook: dict[str, object], control: dict[str, object]) -> list[dict[str, object]]:
    rows = []
    for selected_cost in (0.0, 0.001, 0.005, 0.01, 0.02):
        hook_net = _net_delta(hook, selected_cost=selected_cost)
        control_net = _net_delta(control, selected_cost=selected_cost)
        rows.append(
            {
                "control_net": control_net,
                "hook_advantage": hook_net - control_net,
                "hook_net": hook_net,
                "selected_cost": selected_cost,
            }
        )
    return rows


def _net_delta(row: dict[str, object], *, selected_cost: float) -> float:
    covered = max(1.0, _float(row.get("repair_covered_count")))
    selection_penalty = selected_cost * _float(row.get("selected_repair_pool_count")) / covered
    return _float(row.get("repair_task_delta_vs_evolved")) - selection_penalty


def _selected_repair_pool(row: dict[str, object]) -> bool:
    reason = str(row.get("repair_selection_reason", ""))
    return reason.startswith("max_") and reason.endswith("_repair_pool")


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    if not isinstance(value, list):
        return []
    return [item for item in value if isinstance(item, dict)]


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _string_list(value: object) -> list[str]:
    if not isinstance(value, list):
        return []
    return [str(item) for item in value]


def _float(value: object) -> float:
    if value is None:
        return 0.0
    return float(value)


def _format_float(value: object) -> str:
    try:
        return f"{float(value):.6f}"
    except (TypeError, ValueError):
        return str(value)


def _join_tasks(value: object) -> str:
    tasks = _string_list(value)
    if not tasks:
        return "`none`"
    return ", ".join(f"`{task}`" for task in tasks)


if __name__ == "__main__":
    raise SystemExit(main())
