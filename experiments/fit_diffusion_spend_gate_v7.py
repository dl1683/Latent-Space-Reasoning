"""Fit simple pre-repair spend gates over v5/v6/v7 diffusion labels."""

from __future__ import annotations

import argparse
import itertools
import json
from collections.abc import Callable
from pathlib import Path

DEFAULT_EVALS = (
    Path("eval_results/diffusion_language/diffusion_independent_spend_transfer_v5_eval.json"),
    Path("eval_results/diffusion_language/diffusion_independent_spend_transfer_v6_eval.json"),
    Path("eval_results/diffusion_language/diffusion_independent_spend_transfer_v7_eval.json"),
)
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/diffusion_spend_gate_v7_fit.json")
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_SPEND_GATE_V7_FIT.md")
FEATURES = (
    "source_quality",
    "prompt_gap_count",
    "first_repairable_step",
    "source_task_delta_vs_trajectory",
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--eval",
        action="append",
        dest="evals",
        type=Path,
        help="Independent spend-transfer eval JSON. May be passed multiple times.",
    )
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    parser.add_argument("--max-conditions", type=int, default=3)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    fit = fit_spend_gate(
        eval_paths=tuple(args.evals or DEFAULT_EVALS),
        max_conditions=args.max_conditions,
    )
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(fit, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(fit), encoding="utf-8")
    print(
        json.dumps(
            {
                "best_error_count": fit["summary"]["best_error_count"],
                "best_rule_id": fit["summary"]["best_rule_id"],
                "json_output": str(args.json_output),
                "report_output": str(args.report_output),
                "target_count": fit["summary"]["target_count"],
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def fit_spend_gate(
    *,
    eval_paths: tuple[Path, ...] = DEFAULT_EVALS,
    max_conditions: int = 3,
) -> dict[str, object]:
    rows = _load_rows(eval_paths)
    conditions = _candidate_conditions(rows)
    rules = [_score_rule([], rows)]
    for condition_count in range(1, max_conditions + 1):
        for combo in itertools.combinations(conditions, condition_count):
            rules.append(_score_rule(list(combo), rows))
    ranked = sorted(
        rules,
        key=lambda rule: (
            int(rule["error_count"]),
            int(rule["false_negative_count"]),
            int(rule["false_positive_count"]),
            -float(rule["positive_lift_covered"]),
            int(rule["condition_count"]),
            str(rule["rule_id"]),
        ),
    )
    best = ranked[0]
    return {
        "generated_by": "experiments/fit_diffusion_spend_gate_v7.py",
        "inputs": {"evals": [str(path) for path in eval_paths], "max_conditions": max_conditions},
        "rows": rows,
        "schema": "diffusion_spend_gate_v7_fit.v1",
        "summary": _summary(best, rows),
        "top_rules": ranked[:20],
    }


def render_markdown(fit: dict[str, object]) -> str:
    summary = _dict(fit.get("summary"))
    best = _dict(summary.get("best_rule"))
    lines = [
        "# Diffusion Spend Gate V7 Fit",
        "",
        "This file is generated by `experiments/fit_diffusion_spend_gate_v7.py`.",
        "",
        "## Summary",
        "",
        f"- Target rows: `{summary.get('target_count', 0)}`",
        f"- Profitable rows: `{summary.get('profitable_count', 0)}`",
        f"- Best rule: `{summary.get('best_rule_id', '')}`",
        f"- Best errors: `{summary.get('best_error_count', 0)}`",
        f"- False positives: `{best.get('false_positive_count', 0)}`",
        f"- False negatives: `{best.get('false_negative_count', 0)}`",
        f"- Positive lift covered: `{_format_float(best.get('positive_lift_covered'))}`",
        f"- Missed profitable tasks: {_join_tasks(best.get('missed_profitable_tasks'))}",
        f"- No-lift selected tasks: {_join_tasks(best.get('no_lift_selected_tasks'))}",
        "",
        "## Decision",
        "",
        (
            "Do not promote this gate to the GPU runner yet. The best simple "
            "pre-repair rule reduces no-lift spending, but it still misses "
            "profitable repairs. The current executable policy should remain "
            "`denoise_phase_repairability` plus `candidate_aware_promotion_v1` "
            "until a spend gate preserves positives on this combined surface."
        ),
        "",
        "## Top Rules",
        "",
        "| Rule | Errors | FP | FN | TP | Selected | Lift Covered | Missed Profitable | No-Lift Selected |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- | --- |",
    ]
    for rule in _list_of_dicts(fit.get("top_rules"))[:10]:
        lines.append(
            "| "
            f"`{rule.get('rule_id', '')}` | "
            f"{int(rule.get('error_count', 0))} | "
            f"{int(rule.get('false_positive_count', 0))} | "
            f"{int(rule.get('false_negative_count', 0))} | "
            f"{int(rule.get('true_positive_count', 0))} | "
            f"{int(rule.get('selected_count', 0))} | "
            f"{_format_float(rule.get('positive_lift_covered'))} | "
            f"{_join_tasks(rule.get('missed_profitable_tasks'))} | "
            f"{_join_tasks(rule.get('no_lift_selected_tasks'))} |"
        )
    lines.extend(
        [
            "",
            "## Rows",
            "",
            "| Task | Label | Best | Source Quality | Gap | First Step | Source Delta | Repair Lift |",
            "| --- | --- | --- | ---: | ---: | ---: | ---: | ---: |",
        ]
    )
    predictions = _dict(best.get("predictions"))
    for row in _list_of_dicts(fit.get("rows")):
        task_id = str(row.get("task_id", ""))
        lines.append(
            "| "
            f"`{task_id}` | "
            f"{bool(row.get('profitable'))} | "
            f"{bool(predictions.get(task_id))} | "
            f"{_format_float(row.get('source_quality'))} | "
            f"{int(_float(row.get('prompt_gap_count')))} | "
            f"{_format_optional(row.get('first_repairable_step'))} | "
            f"{_format_float(row.get('source_task_delta_vs_trajectory'))} | "
            f"{_format_float(row.get('repair_lift'))} |"
        )
    return "\n".join(lines) + "\n"


Condition = tuple[str, Callable[[dict[str, object]], bool]]


def _candidate_conditions(rows: list[dict[str, object]]) -> list[Condition]:
    conditions: list[Condition] = []
    for feature in FEATURES:
        values = sorted({_feature_value(row, feature) for row in rows})
        for value in values:
            conditions.append(
                (
                    f"{feature} <= {_format_slug(value)}",
                    lambda row, feature=feature, value=value: _feature_value(row, feature) <= value,
                )
            )
            conditions.append(
                (
                    f"{feature} >= {_format_slug(value)}",
                    lambda row, feature=feature, value=value: _feature_value(row, feature) >= value,
                )
            )
    return conditions


def _score_rule(conditions: list[Condition], rows: list[dict[str, object]]) -> dict[str, object]:
    predictions: dict[str, bool] = {}
    false_positive: list[dict[str, object]] = []
    false_negative: list[dict[str, object]] = []
    true_positive: list[dict[str, object]] = []
    true_negative: list[dict[str, object]] = []
    for row in rows:
        prediction = bool(row.get("single_repairability_prediction")) and all(
            condition(row) for _, condition in conditions
        )
        label = bool(row.get("profitable"))
        predictions[str(row.get("task_id", ""))] = prediction
        if prediction and label:
            true_positive.append(row)
        elif prediction and not label:
            false_positive.append(row)
        elif not prediction and label:
            false_negative.append(row)
        else:
            true_negative.append(row)
    condition_names = [name for name, _ in conditions]
    return {
        "condition_count": len(conditions),
        "conditions": condition_names,
        "error_count": len(false_positive) + len(false_negative),
        "false_negative_count": len(false_negative),
        "false_positive_count": len(false_positive),
        "missed_profitable_tasks": _task_ids(false_negative),
        "no_lift_selected_tasks": _task_ids(false_positive),
        "positive_lift_covered": sum(_float(row.get("repair_lift")) for row in true_positive),
        "predictions": predictions,
        "rule_id": "repairable_denoise_spend"
        if not condition_names
        else "repairable_if_" + "_and_".join(_slug(name) for name in condition_names),
        "selected_count": len(true_positive) + len(false_positive),
        "selected_tasks": _task_ids(true_positive + false_positive),
        "true_negative_count": len(true_negative),
        "true_positive_count": len(true_positive),
    }


def _summary(best: dict[str, object], rows: list[dict[str, object]]) -> dict[str, object]:
    return {
        "best_error_count": best["error_count"],
        "best_rule": best,
        "best_rule_id": best["rule_id"],
        "profitable_count": sum(int(row.get("profitable", False)) for row in rows),
        "target_count": len(rows),
    }


def _load_rows(paths: tuple[Path, ...]) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    for path in paths:
        payload = json.loads(path.read_text(encoding="utf-8"))
        for row in _list_of_dicts(payload.get("rows")):
            current = dict(row)
            current["source_eval"] = str(path)
            rows.append(current)
    return rows


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    return [row for row in value if isinstance(row, dict)] if isinstance(value, list) else []


def _feature_value(row: dict[str, object], feature: str) -> float:
    value = row.get(feature)
    if value is None and feature == "first_repairable_step":
        return 999.0
    return _float(value)


def _float(value: object) -> float:
    if value is None:
        return 0.0
    return float(value)


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


def _format_optional(value: object) -> str:
    if value is None:
        return ""
    return _format_float(value)


def _format_slug(value: float) -> str:
    return f"{value:.6f}"


def _join_tasks(value: object) -> str:
    values = [str(item) for item in value] if isinstance(value, list) else []
    return ", ".join(f"`{item}`" for item in values) if values else "`none`"


def _slug(value: str) -> str:
    return (
        value.replace(" ", "_")
        .replace(".", "p")
        .replace("-", "m")
        .replace("<=", "le")
        .replace(">=", "ge")
    )


def _task_ids(rows: list[dict[str, object]]) -> list[str]:
    return [str(row.get("task_id", "")) for row in rows]


if __name__ == "__main__":
    raise SystemExit(main())
