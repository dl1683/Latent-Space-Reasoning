"""Analyze why the held-out multi-aspect v2 replay missed full promotion."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_REPLAY = Path("eval_results/diffusion_language/latent_aggregation_multi_aspect_v2_replay.json")
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/latent_aggregation_multi_aspect_v2_failure.json")
DEFAULT_REPORT_OUTPUT = Path("docs/reports/diffusion/LATENT_AGGREGATION_MULTI_ASPECT_V2_FAILURE.md")
NON_RUBRIC_THRESHOLD = 0.03


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--replay", type=Path, default=DEFAULT_REPLAY)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    result = analyze_failure(replay_path=args.replay)
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(result, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(result), encoding="utf-8")
    print(
        json.dumps(
            {
                "complement_task_mean_non_rubric_lift": result["summary"][
                    "complement_task_mean_non_rubric_lift"
                ],
                "json_output": str(args.json_output),
                "report_output": str(args.report_output),
                "task_count": result["summary"]["task_count"],
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def analyze_failure(*, replay_path: Path) -> dict[str, object]:
    replay = json.loads(replay_path.read_text(encoding="utf-8"))
    tasks = _list_of_dicts(replay.get("tasks"))
    complement_tasks = [task for task in tasks if int(_float(task.get("selected_complement_count"))) > 0]
    no_complement_tasks = [
        task for task in tasks if int(_float(task.get("selected_complement_count"))) <= 0
    ]
    return {
        "evidence_boundary": {
            "reason": "Post-replay diagnostic over held-out v2 outputs; explains a failed frozen gate, not a new promotion.",
            "status": "held_out_multi_aspect_v2_failure_analysis",
        },
        "generated_by": "experiments/analyze_latent_aggregation_multi_aspect_v2_failure.py",
        "inputs": {"replay": str(replay_path)},
        "schema": "latent_aggregation_multi_aspect_v2_failure.v1",
        "summary": {
            "complement_task_count": len(complement_tasks),
            "complement_task_mean_non_rubric_lift": _mean(
                _float(task.get("non_rubric_lift")) for task in complement_tasks
            ),
            "complement_task_mean_score_lift": _mean(
                _float(task.get("score_lift")) for task in complement_tasks
            ),
            "dimension_only_promoted_count": sum(
                1
                for task in complement_tasks
                if int(_float(task.get("dimension_gain_count"))) > 0
                and int(_float(task.get("rubric_gain_count"))) == 0
            ),
            "failed_gate": "minimum_mean_non_rubric_lift",
            "global_mean_non_rubric_lift": _float(
                _dict(replay.get("summary")).get("mean_non_rubric_lift")
            ),
            "global_threshold": NON_RUBRIC_THRESHOLD,
            "missing_global_lift": max(
                0.0,
                NON_RUBRIC_THRESHOLD
                - _float(_dict(replay.get("summary")).get("mean_non_rubric_lift")),
            ),
            "no_complement_task_count": len(no_complement_tasks),
            "rubric_only_promoted_count": sum(
                1
                for task in complement_tasks
                if int(_float(task.get("rubric_gain_count"))) > 0
                and int(_float(task.get("dimension_gain_count"))) == 0
            ),
            "task_count": len(tasks),
        },
        "tasks": [_task_row(task) for task in tasks],
    }


def render_markdown(result: dict[str, object]) -> str:
    summary = result["summary"]
    lines = [
        "# Latent Aggregation Multi-Aspect V2 Failure Analysis",
        "",
        "This file is generated by `experiments/analyze_latent_aggregation_multi_aspect_v2_failure.py`.",
        "It explains the failed frozen gate from the held-out v2 replay.",
        "",
        "## Evidence Boundary",
        "",
        f"- Status: `{result['evidence_boundary']['status']}`",
        f"- Reason: {result['evidence_boundary']['reason']}",
        "",
        "## Summary",
        "",
        f"- Tasks: `{summary['task_count']}`",
        f"- Complement tasks: `{summary['complement_task_count']}`",
        f"- No-complement tasks: `{summary['no_complement_task_count']}`",
        f"- Global mean non-rubric lift: `{_format_float(summary['global_mean_non_rubric_lift'])}`",
        f"- Required global mean non-rubric lift: `{_format_float(summary['global_threshold'])}`",
        f"- Missing global lift: `{_format_float(summary['missing_global_lift'])}`",
        (
            "- Complement-task mean non-rubric lift: "
            f"`{_format_float(summary['complement_task_mean_non_rubric_lift'])}`"
        ),
        f"- Complement-task mean score lift: `{_format_float(summary['complement_task_mean_score_lift'])}`",
        f"- Dimension-only promoted tasks: `{summary['dimension_only_promoted_count']}`",
        f"- Rubric-only promoted tasks: `{summary['rubric_only_promoted_count']}`",
        "",
        "## Interpretation",
        "",
        (
            "The v2 replay did not fail because selected complements were weak. It failed "
            "because complement material appeared on only 9 of 24 tasks, so strong lift on "
            "those tasks diluted below the all-task mean non-rubric gate."
        ),
        "",
        "## Next Experiment",
        "",
        (
            "The next freeze should either improve complement discovery coverage or split the "
            "promotion gates into coverage and conditional-quality gates. Reusing the same "
            "held-out slice to lower the all-task threshold would be post-hoc and should not "
            "promote this run."
        ),
        "",
        "## Task Diagnostics",
        "",
        "| Task | Decision | Complements | Rubric Gain | Dimension Gain | Score Lift | Non-Rubric Lift |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for task in _list_of_dicts(result.get("tasks")):
        lines.append(
            "| "
            f"`{task['task_id']}` | "
            f"`{task['decision_status']}` | "
            f"{task['selected_complement_count']} | "
            f"{task['rubric_gain_count']} | "
            f"{task['dimension_gain_count']} | "
            f"{_format_float(task['score_lift'])} | "
            f"{_format_float(task['non_rubric_lift'])} |"
        )
    return "\n".join(lines) + "\n"


def _task_row(task: dict[str, object]) -> dict[str, object]:
    return {
        "decision_status": str(_dict(task.get("decision")).get("status", "")),
        "dimension_gain_count": int(_float(task.get("dimension_gain_count"))),
        "non_rubric_lift": _float(task.get("non_rubric_lift")),
        "rubric_gain_count": int(_float(task.get("rubric_gain_count"))),
        "score_lift": _float(task.get("score_lift")),
        "selected_complement_count": int(_float(task.get("selected_complement_count"))),
        "task_id": str(task.get("task_id", "")),
    }


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    return [item for item in value if isinstance(item, dict)] if isinstance(value, list) else []


def _float(value: object) -> float:
    if value is None:
        return 0.0
    return float(value)


def _mean(values: object) -> float:
    items = list(values)
    return sum(items) / len(items) if items else 0.0


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


if __name__ == "__main__":
    raise SystemExit(main())
