def _row_from_probe_record(record: dict[str, object], target_row: dict[str, object]) -> dict[str, object]:
    labels = _dict(target_row.get("labels"))
    text = str(record.get("text", ""))
    weak_terms = _extract_weak_terms(str(record.get("prompt", "")))
    features = _probe_text_features(text=text, weak_terms=weak_terms, record=record)
    return {
        "candidate_lift_vs_trajectory": _float(labels.get("candidate_lift_vs_trajectory")),
        "features": features,
        "label": bool(labels.get("promote_vs_trajectory")),
        "probe_text": text,
        "task_id": str(_dict(record.get("task")).get("task_id", "")),
        "weak_terms": weak_terms,
    }


def _probe_text_features(
    *,
    text: str,
    weak_terms: list[str],
    record: dict[str, object],
) -> dict[str, float]:
    lower = text.lower()
    exact_authorization = "FULL_REPAIR_AUTHORIZED=false" in text
    has_full_repair = "FULL_REPAIR" in text
    malformed_authorization = has_full_repair and not exact_authorization
    slot_count = sum(
        int(value)
        for value in (
            bool(re.search(r"(^|[ ;])1\)", text)),
            bool(re.search(r"(^|[ ;])2\)", text)),
            bool(re.search(r"(^|[ ;])3\)", text)),
        )
    )
    has_missing = "missing" in lower or "constraint" in lower
    has_evidence = "evidence" in lower or "metric" in lower
    has_retention = "retention" in lower or "risk" in lower
    weird_punctuation = any(marker in text for marker in ("::", "..", ",AUTHORIZED", "AUTH_AUTHORIZED", "AUTHUTHORIZED"))
    word_count = len(re.findall(r"[A-Za-z0-9_]+", text))
    weak_echo_count = sum(int(term in lower) for term in weak_terms)
    weak_echo_fraction = weak_echo_count / max(len(weak_terms), 1)
    fidelity_score = (
        int(exact_authorization)
        + int(has_missing)
        + int(has_evidence)
        + int(has_retention)
        + min(slot_count, 3) / 3.0
        - int(malformed_authorization)
        - int(weird_punctuation)
    )
    return {
        "diagnostic_fidelity_score": fidelity_score,
        "diagnostic_slot_count": float(slot_count),
        "exact_authorization_false": float(exact_authorization),
        "has_evidence_slot": float(has_evidence),
        "has_missing_slot": float(has_missing),
        "has_retention_slot": float(has_retention),
        "malformed_authorization": float(malformed_authorization),
        "probe_task_score": _float(_dict(record.get("task_score")).get("score")),
        "weak_term_echo_count": float(weak_echo_count),
        "weak_term_echo_fraction": weak_echo_fraction,
        "weird_punctuation": float(weird_punctuation),
        "word_count": float(word_count),
    }


def _rank_rules(rows: list[dict[str, object]], feature_names: tuple[str, ...]) -> list[dict[str, object]]:
    rules = []
    for feature_name in feature_names:
        values = sorted({_float(_dict(row.get("features")).get(feature_name)) for row in rows})
        for threshold in values:
            for direction in ("ge", "le"):
                rules.append(_evaluate_rule(rows, feature_name, direction, threshold))
    return sorted(
        rules,
        key=lambda rule: (
            int(rule["error_count"]),
            _float(rule["missed_positive_lift"]),
            int(rule["false_positive_count"]),
            -int(rule["selected_count"]),
            str(rule["rule_name"]),
        ),
    )


def _evaluate_rule(
    rows: list[dict[str, object]],
    feature_name: str,
    direction: str,
    threshold: float,
) -> dict[str, object]:
    false_positives = []
    false_negatives = []
    selected_count = 0
    for row in rows:
        value = _float(_dict(row.get("features")).get(feature_name))
        selected = value >= threshold if direction == "ge" else value <= threshold
        label = bool(row.get("label"))
        selected_count += int(selected)
        if selected and not label:
            false_positives.append(row)
        if not selected and label:
            false_negatives.append(row)
    missed_lift = sum(_float(row.get("candidate_lift_vs_trajectory")) for row in false_negatives)
    return {
        "direction": direction,
        "error_count": len(false_positives) + len(false_negatives),
        "false_negative_count": len(false_negatives),
        "false_negative_task_ids": [str(row.get("task_id", "")) for row in false_negatives],
        "false_positive_count": len(false_positives),
        "false_positive_task_ids": [str(row.get("task_id", "")) for row in false_positives],
        "feature": feature_name,
        "missed_positive_lift": missed_lift,
        "rule_name": f"{feature_name}_{direction}_{_format_token(threshold)}",
        "selected_count": selected_count,
        "threshold": threshold,
    }


def _rows_with_decisions(rows: list[dict[str, object]], rule: dict[str, object]) -> list[dict[str, object]]:
    output = []
    for row in rows:
        row_out = dict(row)
        row_out["selected_by_best_post_probe_rule"] = _rule_selects(row, rule)
        output.append(row_out)
    return output


def _rule_selects(row: dict[str, object], rule: dict[str, object]) -> bool:
    value = _float(_dict(row.get("features")).get(str(rule.get("feature", ""))))
    threshold = _float(rule.get("threshold"))
    return value >= threshold if rule.get("direction") == "ge" else value <= threshold


def _summary(rows: list[dict[str, object]], best_rule: dict[str, object]) -> dict[str, object]:
    positives = [row for row in rows if bool(row.get("label"))]
    negatives = [row for row in rows if not bool(row.get("label"))]
    return {
        "best_post_probe_error_count": int(best_rule.get("error_count", 0)),
        "best_post_probe_false_negative_count": int(best_rule.get("false_negative_count", 0)),
        "best_post_probe_false_positive_count": int(best_rule.get("false_positive_count", 0)),
        "best_post_probe_rule_name": str(best_rule.get("rule_name", "")),
        "gate_decision": "diagnostic_only",
        "malformed_authorization_count": sum(
            int(_float(_dict(row.get("features")).get("malformed_authorization")) > 0.0)
            for row in rows
        ),
        "negative_label_count": len(negatives),
        "positive_label_count": len(positives),
        "row_count": len(rows),
        "weird_punctuation_count": sum(
            int(_float(_dict(row.get("features")).get("weird_punctuation")) > 0.0)
            for row in rows
        ),
    }


def _load_jsonl(path: Path) -> list[dict[str, object]]:
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        value = json.loads(line)
        if isinstance(value, dict):
            rows.append(value)
    return rows


def _extract_weak_terms(prompt: str) -> list[str]:
    match = re.search(r"Missing or weak task terms: (.*)\n", prompt)
    if not match:
        return []
    return [term.strip().lower() for term in match.group(1).split(",") if term.strip()]


def _rule_row(rule: dict[str, object]) -> str:
    return (
        "| "
        f"`{rule.get('rule_name', '')}` | "
        f"{int(rule.get('error_count', 0))} | "
        f"{int(rule.get('false_positive_count', 0))} | "
        f"{int(rule.get('false_negative_count', 0))} | "
        f"{_format_float(rule.get('missed_positive_lift'))} | "
        f"{int(rule.get('selected_count', 0))} |"
    )


def _empty_rule() -> dict[str, object]:
    return {
        "direction": "ge",
        "error_count": 0,
        "false_negative_count": 0,
        "false_positive_count": 0,
        "feature": "",
        "missed_positive_lift": 0.0,
        "rule_name": "",
        "selected_count": 0,
        "threshold": 0.0,
    }


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    if not isinstance(value, list):
        return []
    return [item for item in value if isinstance(item, dict)]


def _float(value: object) -> float:
    if value is None:
        return 0.0
    try:
        return float(value)
    except (TypeError, ValueError):
        return 0.0


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


def _format_token(value: float) -> str:
    return _format_float(value).replace("-", "neg_").replace(".", "p")


def _markdown_escape(value: str) -> str:
    return value.replace("|", "\\|")


