"""Audit measured counterfactual micro-probe text as a Stage 1 signal."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

DEFAULT_RAW = Path("eval_results/diffusion_language/counterfactual_micro_probe_counterexamples_all_v1_raw.jsonl")
DEFAULT_TARGETS = Path("eval_results/diffusion_language/diffusion_counterfactual_probe_targets_v1.json")
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/counterfactual_probe_text_fidelity_v1.json")
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_COUNTERFACTUAL_PROBE_TEXT_FIDELITY_V1.md")

POST_PROBE_FEATURES = (
    "probe_task_score",
    "diagnostic_slot_count",
    "has_missing_slot",
    "has_evidence_slot",
    "has_retention_slot",
    "exact_authorization_false",
    "malformed_authorization",
    "weird_punctuation",
    "word_count",
    "weak_term_echo_count",
    "weak_term_echo_fraction",
    "diagnostic_fidelity_score",
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--raw", type=Path, default=DEFAULT_RAW)
    parser.add_argument("--targets", type=Path, default=DEFAULT_TARGETS)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    audit = analyze_probe_text_fidelity(raw_path=args.raw, targets_path=args.targets)
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(audit, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(audit), encoding="utf-8")
    print(
        json.dumps(
            {
                "best_post_probe_errors": audit["summary"]["best_post_probe_error_count"],
                "best_post_probe_rule": audit["summary"]["best_post_probe_rule_name"],
                "gate_decision": audit["summary"]["gate_decision"],
                "malformed_authorization_count": audit["summary"]["malformed_authorization_count"],
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def analyze_probe_text_fidelity(*, raw_path: Path, targets_path: Path) -> dict[str, object]:
    targets = json.loads(targets_path.read_text(encoding="utf-8"))
    target_rows = {
        str(row.get("task_id", "")): row
        for row in _list_of_dicts(targets.get("rows"))
    }
    rows = []
    for record in _load_jsonl(raw_path):
        if record.get("generation_stage") != "counterfactual_probe":
            continue
        task = _dict(record.get("task"))
        task_id = str(task.get("task_id", ""))
        target_row = target_rows.get(task_id, {})
        rows.append(_row_from_probe_record(record, target_row))
    rows.sort(key=lambda row: str(row.get("task_id", "")))
    rules = _rank_rules(rows, POST_PROBE_FEATURES)
    best_rule = rules[0] if rules else _empty_rule()
    return {
        "generated_by": "experiments/analyze_diffusion_counterfactual_probe_text_fidelity.py",
        "inputs": {
            "raw": str(raw_path),
            "targets": str(targets_path),
        },
        "rows": _rows_with_decisions(rows, best_rule),
        "schema": "diffusion_counterfactual_probe_text_fidelity.v1",
        "summary": _summary(rows, best_rule),
        "top_post_probe_rules": rules[:20],
    }


