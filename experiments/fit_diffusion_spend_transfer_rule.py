"""Fit an interpretable spend rule across original and independent diffusion rows."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_TARGETS = Path("eval_results/diffusion_language/diffusion_composite_selector_targets.json")
DEFAULT_INDEPENDENT_EVAL = Path(
    "eval_results/diffusion_language/diffusion_independent_spend_transfer_eval.json"
)
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/diffusion_spend_transfer_rule_fit.json")
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_SPEND_TRANSFER_RULE_FIT.md")
DEFAULT_SOURCE_QUALITY_MAX = 0.301429
DEFAULT_PROMPT_GAP_MAX = 9


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--targets", type=Path, default=DEFAULT_TARGETS)
    parser.add_argument("--independent-eval", type=Path, default=DEFAULT_INDEPENDENT_EVAL)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    fit = fit_spend_transfer_rule(
        targets_path=args.targets,
        independent_eval_path=args.independent_eval,
    )
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(fit, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(fit), encoding="utf-8")
    print(
        json.dumps(
            {
                "best_error_count": _dict(fit.get("best_rule")).get("error_count", 0),
                "best_rule_id": _dict(fit.get("best_rule")).get("rule_id", ""),
                "json_output": str(args.json_output),
                "report_output": str(args.report_output),
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def fit_spend_transfer_rule(
    *,
    targets_path: Path,
    independent_eval_path: Path,
) -> dict[str, object]:
    rows = _combined_rows(targets_path=targets_path, independent_eval_path=independent_eval_path)
    current_rule = {
        "complexity": 3,
        "max_prompt_gap_count": DEFAULT_PROMPT_GAP_MAX,
        "max_source_quality": DEFAULT_SOURCE_QUALITY_MAX,
        "requires_first_repairable": True,
        "rule_id": "current_decomposed_spend",
        "type": "current",
    }
    candidates = [current_rule, *_score_floor_rules(rows)]
    scored = [_score_rule(rule, rows) for rule in candidates]
    best_rule = min(
        scored,
        key=lambda rule: (
            int(rule.get("error_count", 0)),
            int(rule.get("false_positive_count", 0)),
            int(rule.get("false_negative_count", 0)),
            int(rule.get("complexity", 99)),
            str(rule.get("rule_id", "")),
        ),
    )
    return {
        "best_rule": best_rule,
        "candidate_rules": scored,
        "generated_by": "experiments/fit_diffusion_spend_transfer_rule.py",
        "inputs": {
            "independent_eval": str(independent_eval_path),
            "targets": str(targets_path),
        },
        "rows": rows,
        "schema": "diffusion_spend_transfer_rule_fit.v1",
        "summary": _summary(best_rule, rows),
    }


def render_markdown(fit: dict[str, object]) -> str:
    best = _dict(fit.get("best_rule"))
    summary = _dict(fit.get("summary"))
    lines = [
        "# Diffusion Spend Transfer Rule Fit",
        "",
        "This file is generated by `experiments/fit_diffusion_spend_transfer_rule.py`.",
        (
            "It fits a richer interpretable repair-spend rule over the original "
            "target rows plus the independent transfer rows."
        ),
        "",
        "## Summary",
        "",
        f"- Best rule: `{best.get('rule_id', '')}`",
        f"- Error count: `{best.get('error_count', 0)}`",
        f"- False positives: `{best.get('false_positive_count', 0)}`",
        f"- False negatives: `{best.get('false_negative_count', 0)}`",
        f"- Selected tasks: {_join_tasks(best.get('selected_tasks'))}",
        f"- Profitable tasks: {_join_tasks(summary.get('profitable_tasks'))}",
        "",
        "## Rule Comparison",
        "",
        "| Rule | Error | FP | FN | Selected Tasks |",
        "| --- | ---: | ---: | ---: | --- |",
    ]
    for rule in _list_of_dicts(fit.get("candidate_rules")):
        lines.append(
            "| "
            f"`{rule.get('rule_id', '')}` | "
            f"{rule.get('error_count', 0)} | "
            f"{rule.get('false_positive_count', 0)} | "
            f"{rule.get('false_negative_count', 0)} | "
            f"{_join_tasks(rule.get('selected_tasks'))} |"
        )
    lines.extend(
        [
            "",
            "## Training Rows",
            "",
            (
                "| Split | Task | Label | Current | Best | Source Quality | "
                "Source Task | Gap | First Step |"
            ),
            "| --- | --- | --- | --- | --- | ---: | ---: | ---: | ---: |",
        ]
    )
    best_predictions = _dict(best.get("predictions"))
    current = next(
        (
            rule
            for rule in _list_of_dicts(fit.get("candidate_rules"))
            if rule.get("rule_id") == "current_decomposed_spend"
        ),
        {},
    )
    current_predictions = _dict(current.get("predictions"))
    for row in _list_of_dicts(fit.get("rows")):
        task_id = str(row.get("task_id", ""))
        lines.append(
            "| "
            f"`{row.get('split', '')}` | "
            f"`{task_id}` | "
            f"{bool(row.get('label'))} | "
            f"{bool(current_predictions.get(task_id))} | "
            f"{bool(best_predictions.get(task_id))} | "
            f"{_format_float(row.get('source_quality'))} | "
            f"{_format_float(row.get('source_task_score'))} | "
            f"{_format_float(row.get('prompt_gap_count'))} | "
            f"{_format_optional(row.get('first_repairable_step'))} |"
        )
    lines.extend(
        [
            "",
            "## Reading",
            "",
            _reading(best),
        ]
    )
    return "\n".join(lines) + "\n"


def _reading(best_rule: dict[str, object]) -> str:
    if best_rule.get("rule_id") == "current_decomposed_spend":
        return (
            "With labels derived from repair-oracle lift, `plan_012` becomes a "
            "positive low-margin repair case rather than a false positive. The "
            "current decomposed spend rule is therefore the best availability "
            "predictor on this surface. Higher source-task floors are useful only "
            "as cost-conservative margin policies; at `0.3075` they create a false "
            "negative by skipping `plan_012`."
        )
    return (
        "The fitted source-task floor removes transfer false positives while "
        "preserving the currently known profitable repairs. Treat this as a "
        "threshold candidate until it survives a larger independent slice."
    )


def _combined_rows(*, targets_path: Path, independent_eval_path: Path) -> list[dict[str, object]]:
    targets = json.loads(targets_path.read_text(encoding="utf-8"))
    independent = json.loads(independent_eval_path.read_text(encoding="utf-8"))
    rows = []
    for row in _list_of_dicts(targets.get("task_targets")):
        rows.append(
            {
                "first_repairable_step": row.get("first_repairable_step"),
                "label": bool(row.get("spend_repair_label")),
                "prompt_gap_count": _float(row.get("prompt_gap_count")),
                "source_quality": _float(row.get("source_quality")),
                "source_task_score": _float(row.get("trajectory_score")),
                "split": "original",
                "task_id": str(row.get("task_id", "")),
            }
        )
    for row in _list_of_dicts(independent.get("rows")):
        rows.append(
            {
                "first_repairable_step": row.get("first_repairable_step"),
                "label": bool(row.get("profitable")),
                "prompt_gap_count": _float(row.get("prompt_gap_count")),
                "source_quality": _float(row.get("source_quality")),
                "source_task_score": _float(row.get("source_task_score")),
                "split": "independent",
                "task_id": str(row.get("task_id", "")),
            }
        )
    return rows


def _score_floor_rules(rows: list[dict[str, object]]) -> list[dict[str, object]]:
    thresholds = sorted(
        {
            _float(row.get("source_task_score"))
            for row in rows
            if row.get("first_repairable_step") is not None
        }
    )
    return [
        {
            "complexity": 4,
            "max_prompt_gap_count": DEFAULT_PROMPT_GAP_MAX,
            "max_source_quality": DEFAULT_SOURCE_QUALITY_MAX,
            "min_source_task_score": threshold,
            "requires_first_repairable": True,
            "rule_id": (
                "current_decomposed_spend_source_task_ge_"
                f"{_slug(threshold)}"
            ),
            "type": "source_task_floor",
        }
        for threshold in thresholds
    ]


def _score_rule(rule: dict[str, object], rows: list[dict[str, object]]) -> dict[str, object]:
    false_positive = false_negative = true_positive = true_negative = 0
    predictions = {}
    for row in rows:
        prediction = _predict_rule(rule, row)
        label = bool(row.get("label"))
        predictions[str(row.get("task_id", ""))] = prediction
        if prediction and label:
            true_positive += 1
        elif prediction and not label:
            false_positive += 1
        elif not prediction and label:
            false_negative += 1
        else:
            true_negative += 1
    return {
        **rule,
        "error_count": false_positive + false_negative,
        "false_negative_count": false_negative,
        "false_positive_count": false_positive,
        "predictions": predictions,
        "selected_tasks": [task_id for task_id, selected in predictions.items() if selected],
        "true_negative_count": true_negative,
        "true_positive_count": true_positive,
    }


def _predict_rule(rule: dict[str, object], row: dict[str, object]) -> bool:
    if bool(rule.get("requires_first_repairable")) and row.get("first_repairable_step") is None:
        return False
    if _float(row.get("prompt_gap_count")) > _float(rule.get("max_prompt_gap_count")):
        return False
    if _float(row.get("source_quality")) > _float(rule.get("max_source_quality")):
        return False
    if rule.get("type") == "source_task_floor":
        return _float(row.get("source_task_score")) >= _float(rule.get("min_source_task_score"))
    return True


def _summary(best_rule: dict[str, object], rows: list[dict[str, object]]) -> dict[str, object]:
    return {
        "profitable_tasks": [str(row.get("task_id", "")) for row in rows if row.get("label")],
        "row_count": len(rows),
        "selected_tasks": _list_of_strings(best_rule.get("selected_tasks")),
    }


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    return [row for row in value if isinstance(row, dict)] if isinstance(value, list) else []


def _list_of_strings(value: object) -> list[str]:
    return [str(item) for item in value] if isinstance(value, list) else []


def _float(value: object) -> float:
    if value is None:
        return 0.0
    return float(value)


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


def _format_optional(value: object) -> str:
    if value is None:
        return ""
    return _format_float(value)


def _join_tasks(value: object) -> str:
    values = _list_of_strings(value)
    return ", ".join(f"`{item}`" for item in values) if values else "`none`"


def _slug(value: float) -> str:
    return f"{value:.6f}".rstrip("0").rstrip(".").replace(".", "p")


if __name__ == "__main__":
    raise SystemExit(main())
