"""Build independent transfer target rows for counterfactual probe gates."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_SCORES = Path(
    "eval_results/diffusion_language/llada_moe_planning_compact_span_score_max_v1_scores.json"
)
DEFAULT_JSON_OUTPUT = Path(
    "eval_results/diffusion_language/diffusion_counterfactual_probe_transfer_targets_v1.json"
)
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_COUNTERFACTUAL_PROBE_TRANSFER_TARGETS_V1.md")
DEFAULT_LIFT_MIN = 1e-9
DEFAULT_PROBE_POLICY = "span_tomography_probe_v4"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scores", type=Path, default=DEFAULT_SCORES)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--lift-min", type=float, default=DEFAULT_LIFT_MIN)
    parser.add_argument("--probe-policy", default=DEFAULT_PROBE_POLICY)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    targets = build_counterfactual_probe_transfer_targets(
        lift_min=args.lift_min,
        probe_policy=args.probe_policy,
        scores_path=args.scores,
    )
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(targets, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(targets), encoding="utf-8")
    print(
        json.dumps(
            {
                "json_output": str(args.json_output),
                "positive_count": targets["summary"]["positive_label_count"],
                "report_output": str(args.report_output),
                "target_count": targets["summary"]["target_count"],
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def build_counterfactual_probe_transfer_targets(
    *,
    lift_min: float,
    probe_policy: str,
    scores_path: Path,
) -> dict[str, object]:
    scores = json.loads(scores_path.read_text(encoding="utf-8"))
    rows = [
        _target_row(row, lift_min=lift_min, probe_policy=probe_policy)
        for row in _list_of_dicts(scores.get("comparison_rows"))
        if str(row.get("task_id", "")).startswith("plan_")
    ]
    rows.sort(key=lambda row: str(row.get("task_id", "")))
    return {
        "generated_by": "experiments/build_diffusion_counterfactual_probe_transfer_targets.py",
        "inputs": {
            "scores": str(scores_path),
            "scores_content_hash": str(scores.get("content_hash", "")),
        },
        "lift_min": lift_min,
        "probe_policy": probe_policy,
        "rows": rows,
        "schema": "diffusion_counterfactual_probe_transfer_targets.v1",
        "summary": _summary(rows),
    }


def render_markdown(targets: dict[str, object]) -> str:
    summary = _dict(targets.get("summary"))
    inputs = _dict(targets.get("inputs"))
    lines = [
        "# Diffusion Counterfactual Probe Transfer Targets V1",
        "",
        "This file is generated by `experiments/build_diffusion_counterfactual_probe_transfer_targets.py`.",
        (
            "It adapts an independent planning score sheet into the target schema "
            "used by counterfactual probe text-fidelity and Stage 1 gate audits. "
            "The rows are labels for transfer validation; they are not a new "
            "promotion authorization."
        ),
        "",
        "## Summary",
        "",
        f"- Scores: `{inputs.get('scores', '')}`",
        f"- Scores content hash: `{inputs.get('scores_content_hash', '')}`",
        f"- Probe policy under test: `{targets.get('probe_policy', '')}`",
        f"- Target rows: `{summary.get('target_count', 0)}`",
        f"- Positive labels: `{summary.get('positive_label_count', 0)}`",
        f"- Negative labels: `{summary.get('negative_label_count', 0)}`",
        f"- Positive tasks: {_join_tasks(summary.get('positive_task_ids'))}",
        f"- Negative tasks: {_join_tasks(summary.get('negative_task_ids'))}",
        f"- Total positive lift: `{_format_float(summary.get('total_positive_lift'))}`",
        f"- Gate decision: `{summary.get('gate_decision', '')}`",
        "",
        "## Rows",
        "",
        (
            "| Task | Promote | Lift | Repair Score | Trajectory Score | "
            "Repair Control | Repair Selector Edge | Source Control |"
        ),
        "| --- | --- | ---: | ---: | ---: | --- | ---: | --- |",
    ]
    for row in _list_of_dicts(targets.get("rows")):
        labels = _dict(row.get("labels"))
        pre = _dict(row.get("pre_probe_features"))
        lines.append(
            "| "
            f"`{row.get('task_id', '')}` | "
            f"{bool(labels.get('promote_vs_trajectory'))} | "
            f"{_format_float(labels.get('candidate_lift_vs_trajectory'))} | "
            f"{_format_float(pre.get('repair_task_score'))} | "
            f"{_format_float(pre.get('trajectory_task_score'))} | "
            f"`{row.get('repair_control', '')}` | "
            f"{_format_float(pre.get('repair_selector_edge'))} | "
            f"`{row.get('repair_source_control', '')}` |"
        )
    lines.extend(
        [
            "",
            "## Reading",
            "",
            (
                "This target sheet intentionally uses a planning-only fresh slice "
                "with task IDs outside the named v5-v9 counterexample surface. A "
                "fixed probe rule must be evaluated against these labels without "
                "re-fitting the threshold on this slice."
            ),
        ]
    )
    return "\n".join(lines) + "\n"


def _target_row(
    row: dict[str, object],
    *,
    lift_min: float,
    probe_policy: str,
) -> dict[str, object]:
    repair_task_score = _float(row.get("repair_task_score"))
    trajectory_task_score = _float(row.get("trajectory_task_score"))
    lift = repair_task_score - trajectory_task_score
    return {
        "counterexample_type": "fresh_planning_transfer",
        "labels": {
            "candidate_lift_vs_trajectory": lift,
            "promote_vs_trajectory": lift > lift_min,
            "repair_lift": lift,
            "repair_selector_edge": _float(row.get("repair_selector_edge")),
        },
        "pre_probe_features": {
            "evolved_task_score": _float(row.get("evolved_task_score")),
            "repair_selector_edge": _float(row.get("repair_selector_edge")),
            "repair_task_score": repair_task_score,
            "source_quality": _float(row.get("trajectory_task_score")),
            "trajectory_task_score": trajectory_task_score,
        },
        "probe_policy": probe_policy,
        "repair_control": str(row.get("repair_control", "")),
        "repair_source_control": str(row.get("repair_source_control", "")),
        "task_id": str(row.get("task_id", "")),
    }


def _summary(rows: list[dict[str, object]]) -> dict[str, object]:
    positives = [row for row in rows if bool(_dict(row.get("labels")).get("promote_vs_trajectory"))]
    negatives = [row for row in rows if not bool(_dict(row.get("labels")).get("promote_vs_trajectory"))]
    return {
        "gate_decision": "diagnostic_only",
        "negative_label_count": len(negatives),
        "negative_task_ids": [str(row.get("task_id", "")) for row in negatives],
        "positive_label_count": len(positives),
        "positive_task_ids": [str(row.get("task_id", "")) for row in positives],
        "target_count": len(rows),
        "total_positive_lift": sum(
            _float(_dict(row.get("labels")).get("candidate_lift_vs_trajectory"))
            for row in positives
        ),
    }


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    if not isinstance(value, list):
        return []
    return [item for item in value if isinstance(item, dict)]


def _float(value: object) -> float:
    if value is None:
        return 0.0
    try:
        return float(value)
    except (TypeError, ValueError):
        return 0.0


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


def _join_tasks(value: object) -> str:
    tasks = [str(item) for item in value] if isinstance(value, list) else []
    return ", ".join(f"`{task}`" for task in tasks) if tasks else "_none_"


if __name__ == "__main__":
    raise SystemExit(main())
