"""Fit offline value-of-information rules over counterfactual probe targets."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_TARGETS = Path("eval_results/diffusion_language/diffusion_counterfactual_probe_targets_v1.json")
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/diffusion_counterfactual_probe_policy_fit_v1.json")
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_COUNTERFACTUAL_PROBE_POLICY_FIT_V1.md")

FEATURE_PATHS = {
    "probe_value_prediction": ("probe_value_prediction",),
    "expected_gap_visibility_gain": ("probe_feature_delta", "expected_gap_visibility_gain"),
    "expected_realization_defect_visibility": (
        "probe_feature_delta",
        "expected_realization_defect_visibility",
    ),
    "expected_retention_risk_visibility": ("probe_feature_delta", "expected_retention_risk_visibility"),
    "expected_span_evidence_gain": ("probe_feature_delta", "expected_span_evidence_gain"),
    "prompt_gap_count": ("pre_probe_features", "prompt_gap_count"),
    "source_quality": ("pre_probe_features", "source_quality"),
    "source_task_delta_vs_trajectory": ("pre_probe_features", "source_task_delta_vs_trajectory"),
    "degeneracy_score": ("pre_probe_features", "degeneracy_score"),
    "max_span_target_score": ("pre_probe_features", "max_span_target_score"),
    "min_span_source_relative_preservation": (
        "pre_probe_features",
        "min_span_source_relative_preservation",
    ),
    "first_repairable_step": ("pre_probe_features", "first_repairable_step"),
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--targets", type=Path, default=DEFAULT_TARGETS)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    fit = fit_counterfactual_probe_policy(args.targets)
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(fit, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(fit), encoding="utf-8")
    print(
        json.dumps(
            {
                "best_rule": fit["summary"]["best_rule_name"],
                "error_count": fit["summary"]["best_error_count"],
                "gate_decision": fit["summary"]["gate_decision"],
                "json_output": str(args.json_output),
                "report_output": str(args.report_output),
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def fit_counterfactual_probe_policy(target_path: Path) -> dict[str, object]:
    targets = json.loads(target_path.read_text(encoding="utf-8"))
    rows = _list_of_dicts(targets.get("rows"))
    evaluated_rows = [_evaluated_row(row) for row in rows]
    rules = sorted(
        _candidate_rules(evaluated_rows),
        key=lambda rule: (
            int(rule["error_count"]),
            _float(rule["missed_positive_lift"]),
            int(rule["false_positive_count"]),
            -int(rule["selected_count"]),
            str(rule["rule_name"]),
        ),
    )
    best_rule = rules[0] if rules else _empty_rule()
    return {
        "generated_by": "experiments/fit_diffusion_counterfactual_probe_policy.py",
        "inputs": {"targets": str(target_path)},
        "rows": _rows_with_best_decision(evaluated_rows, best_rule),
        "schema": "diffusion_counterfactual_probe_policy_fit.v1",
        "summary": _summary(evaluated_rows, best_rule),
        "top_rules": rules[:20],
    }


