def _candidate_rules(rows: list[dict[str, object]]) -> list[dict[str, object]]:
    rules = []
    for feature_name in FEATURE_PATHS:
        values = sorted({_float(_dict(row.get("features")).get(feature_name)) for row in rows})
        for threshold in values:
            for direction in ("ge", "le"):
                rules.append(_evaluate_rule(rows, feature_name, direction, threshold))
    return rules


def _evaluate_rule(
    rows: list[dict[str, object]], feature_name: str, direction: str, threshold: float
) -> dict[str, object]:
    false_positives = []
    false_negatives = []
    selected_count = 0
    negative_count = sum(1 for row in rows if not bool(row.get("label")))
    for row in rows:
        value = _float(_dict(row.get("features")).get(feature_name))
        selected = value >= threshold if direction == "ge" else value <= threshold
        label = bool(row.get("label"))
        selected_count += int(selected)
        if selected and not label:
            false_positives.append(row)
        if not selected and label:
            false_negatives.append(row)
    missed_positive_lift = sum(_float(row.get("candidate_lift_vs_trajectory")) for row in false_negatives)
    rule_name = f"{feature_name}_{direction}_{_format_token(threshold)}"
    return {
        "direction": direction,
        "error_count": len(false_positives) + len(false_negatives),
        "false_negative_count": len(false_negatives),
        "false_negative_task_ids": [str(row.get("task_id", "")) for row in false_negatives],
        "false_positive_count": len(false_positives),
        "false_positive_task_ids": [str(row.get("task_id", "")) for row in false_positives],
        "feature": feature_name,
        "missed_positive_lift": missed_positive_lift,
        "removed_negative_count": negative_count - len(false_positives),
        "rule_name": rule_name,
        "selected_count": selected_count,
        "threshold": threshold,
    }


def _evaluated_row(row: dict[str, object]) -> dict[str, object]:
    labels = _dict(row.get("labels"))
    features = {name: _value_at_path(row, path) for name, path in FEATURE_PATHS.items()}
    return {
        "candidate_lift_vs_trajectory": _float(labels.get("candidate_lift_vs_trajectory")),
        "counterexample_type": str(row.get("counterexample_type", "")),
        "features": features,
        "label": bool(labels.get("promote_vs_trajectory")),
        "task_id": str(row.get("task_id", "")),
    }


def _rows_with_best_decision(rows: list[dict[str, object]], rule: dict[str, object]) -> list[dict[str, object]]:
    feature = str(rule.get("feature", ""))
    direction = str(rule.get("direction", "ge"))
    threshold = _float(rule.get("threshold"))
    output = []
    for row in rows:
        value = _float(_dict(row.get("features")).get(feature))
        selected = value >= threshold if direction == "ge" else value <= threshold
        row_out = dict(row)
        row_out["best_rule_error"] = selected != bool(row.get("label"))
        row_out["selected_by_best_rule"] = selected
        output.append(row_out)
    return output


def _summary(rows: list[dict[str, object]], best_rule: dict[str, object]) -> dict[str, object]:
    positives = [row for row in rows if bool(row.get("label"))]
    negatives = [row for row in rows if not bool(row.get("label"))]
    return {
        "best_error_count": int(best_rule.get("error_count", 0)),
        "best_false_negative_count": int(best_rule.get("false_negative_count", 0)),
        "best_false_positive_count": int(best_rule.get("false_positive_count", 0)),
        "best_missed_positive_lift": _float(best_rule.get("missed_positive_lift")),
        "best_removed_negative_count": int(best_rule.get("removed_negative_count", 0)),
        "best_rule_name": str(best_rule.get("rule_name", "")),
        "best_selected_count": int(best_rule.get("selected_count", 0)),
        "gate_decision": "diagnostic_only",
        "negative_label_count": len(negatives),
        "positive_label_count": len(positives),
        "row_count": len(rows),
        "total_positive_lift": sum(_float(row.get("candidate_lift_vs_trajectory")) for row in positives),
    }


def _empty_rule() -> dict[str, object]:
    return {
        "direction": "ge",
        "error_count": 0,
        "false_negative_count": 0,
        "false_positive_count": 0,
        "feature": "",
        "missed_positive_lift": 0.0,
        "removed_negative_count": 0,
        "rule_name": "",
        "selected_count": 0,
        "threshold": 0.0,
    }


def _value_at_path(row: dict[str, object], path: tuple[str, ...]) -> float:
    value: object = row
    for key in path:
        value = _dict(value).get(key)
    return _float(value)


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    if not isinstance(value, list):
        return []
    return [item for item in value if isinstance(item, dict)]


def _float(value: object) -> float:
    if value is None:
        return 0.0
    try:
        return float(value)
    except (TypeError, ValueError):
        return 0.0


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


def _format_token(value: float) -> str:
    return _format_float(value).replace("-", "neg_").replace(".", "p")


