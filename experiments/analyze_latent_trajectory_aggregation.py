"""Analyze whether component aggregation beats best-single trajectory selection."""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

DEFAULT_COMPONENTS = Path("experiments/latent_trajectory_aggregation_scout_components.jsonl")
DEFAULT_JSON_OUTPUT = Path("eval_results/latent_trajectory_aggregation_scout.json")
DEFAULT_REPORT_OUTPUT = Path("docs/reports/diffusion/LATENT_TRAJECTORY_AGGREGATION_SCOUT.md")
EPSILON = 1e-9


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--components", type=Path, default=DEFAULT_COMPONENTS)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    result = build_aggregation_scout(component_path=args.components)
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(result, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(result), encoding="utf-8")
    print(
        json.dumps(
            {
                "aggregate_win_count": _dict(result.get("summary")).get("aggregate_win_count", 0),
                "json_output": str(args.json_output),
                "promoted_task_count": _dict(result.get("summary")).get("promoted_task_count", 0),
                "report_output": str(args.report_output),
                "task_count": _dict(result.get("summary")).get("task_count", 0),
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def build_aggregation_scout(*, component_path: Path) -> dict[str, object]:
    rows = _read_jsonl(component_path)
    return build_aggregation_scout_from_rows(
        rows=rows,
        input_label=str(component_path),
    )


def build_aggregation_scout_from_rows(
    *,
    rows: list[dict[str, object]],
    input_label: str,
) -> dict[str, object]:
    task_rows: dict[str, list[dict[str, object]]] = defaultdict(list)
    for row in rows:
        task_id = str(row.get("task_id", ""))
        if task_id:
            task_rows[task_id].append(row)

    task_summaries = [
        _aggregate_task(task_id=task_id, rows=task_rows[task_id]) for task_id in sorted(task_rows)
    ]
    return {
        "generated_by": "experiments/analyze_latent_trajectory_aggregation.py",
        "inputs": {"components": input_label},
        "schema": "latent_trajectory_aggregation_scout.v1",
        "summary": _summary(task_summaries),
        "tasks": task_summaries,
    }


