def _aggregate_task(*, task_id: str, rows: list[dict[str, object]]) -> dict[str, object]:
    expected_components = sorted({str(row.get("component_id", "")) for row in rows if row.get("component_id")})
    expected_weight = sum(_max_component_weight(component_id, rows) for component_id in expected_components)
    by_trajectory = _supported_components_by_trajectory(rows)
    best_trajectory_id, best_single_score = _best_single(by_trajectory, expected_weight)

    selected = _select_components(rows)
    selected_weight = sum(_float(row.get("component_weight")) for row in selected)
    aggregate_score = selected_weight / expected_weight if expected_weight > 0.0 else 0.0
    best_components = set(by_trajectory.get(best_trajectory_id, {}))
    selected_components = {str(row.get("component_id", "")) for row in selected}
    unsupported_addition_count = sum(1 for row in rows if _bool(row.get("unsupported_addition")))
    unresolved_contradiction_count = _unresolved_contradiction_count(rows)
    contradiction_count = unresolved_contradiction_count + sum(
        1 for row in selected if _bool(row.get("hard_contradiction"))
    )

    component_gain_ids = sorted(selected_components - best_components)
    component_loss_ids = sorted(best_components - selected_components)
    decision = _decision(
        aggregate_score=aggregate_score,
        best_single_score=best_single_score,
        component_gain=len(component_gain_ids),
        component_loss=len(component_loss_ids),
        contradiction_count=contradiction_count,
        unsupported_addition_count=unsupported_addition_count,
    )
    return {
        "aggregate_score": aggregate_score,
        "best_single_score": best_single_score,
        "best_single_trajectory_id": best_trajectory_id,
        "component_gain": len(component_gain_ids),
        "component_gain_ids": component_gain_ids,
        "component_loss": len(component_loss_ids),
        "component_loss_ids": component_loss_ids,
        "contradiction_count": contradiction_count,
        "decision": decision,
        "expected_component_count": len(expected_components),
        "expected_component_weight": expected_weight,
        "selected_components": [_slim_component(row) for row in selected],
        "source_diversity": len({str(row.get("trajectory_id", "")) for row in selected}),
        "task_id": task_id,
        "unsupported_addition_count": unsupported_addition_count,
    }


def _select_components(rows: list[dict[str, object]]) -> list[dict[str, object]]:
    eligible = [
        row
        for row in rows
        if _bool(row.get("supported"))
        and not _bool(row.get("unsupported_addition"))
        and not _bool(row.get("hard_contradiction"))
    ]
    best_by_component: dict[str, dict[str, object]] = {}
    for row in eligible:
        component_id = str(row.get("component_id", ""))
        if not component_id:
            continue
        current = best_by_component.get(component_id)
        if current is None or _component_sort_key(row) > _component_sort_key(current):
            best_by_component[component_id] = row

    selected: list[dict[str, object]] = []
    contradiction_groups: dict[str, list[dict[str, object]]] = defaultdict(list)
    for row in best_by_component.values():
        group = str(row.get("contradiction_group", ""))
        if group:
            contradiction_groups[group].append(row)
        else:
            selected.append(row)
    for group_rows in contradiction_groups.values():
        selected.append(max(group_rows, key=_component_sort_key))
    return sorted(selected, key=lambda row: str(row.get("component_id", "")))


def _supported_components_by_trajectory(
    rows: list[dict[str, object]],
) -> dict[str, dict[str, float]]:
    by_trajectory: dict[str, dict[str, float]] = defaultdict(dict)
    for row in rows:
        if not _bool(row.get("supported")) or _bool(row.get("unsupported_addition")):
            continue
        if _bool(row.get("hard_contradiction")):
            continue
        trajectory_id = str(row.get("trajectory_id", ""))
        component_id = str(row.get("component_id", ""))
        if not trajectory_id or not component_id:
            continue
        by_trajectory[trajectory_id][component_id] = max(
            by_trajectory[trajectory_id].get(component_id, 0.0),
            _float(row.get("component_weight")),
        )
    return by_trajectory


def _best_single(
    by_trajectory: dict[str, dict[str, float]],
    expected_weight: float,
) -> tuple[str, float]:
    best_id = ""
    best_score = 0.0
    for trajectory_id in sorted(by_trajectory):
        weight = sum(by_trajectory[trajectory_id].values())
        score = weight / expected_weight if expected_weight > 0.0 else 0.0
        if score > best_score + EPSILON:
            best_id = trajectory_id
            best_score = score
    return best_id, best_score


def _unresolved_contradiction_count(rows: list[dict[str, object]]) -> int:
    groups: dict[str, set[str]] = defaultdict(set)
    for row in rows:
        if not _bool(row.get("supported")):
            continue
        group = str(row.get("contradiction_group", ""))
        label = str(row.get("contradiction_label", ""))
        if group and label:
            groups[group].add(label)
    return sum(1 for labels in groups.values() if len(labels) > 1)


def _decision(
    *,
    aggregate_score: float,
    best_single_score: float,
    component_gain: int,
    component_loss: int,
    contradiction_count: int,
    unsupported_addition_count: int,
) -> dict[str, object]:
    if contradiction_count > 0:
        return {
            "reason": "Fusion left a hard or unresolved contradiction group.",
            "status": "blocked_contradiction",
        }
    if unsupported_addition_count > 0:
        return {
            "reason": "At least one proposed component was not supported by trajectory evidence.",
            "status": "blocked_unsupported",
        }
    if aggregate_score <= best_single_score + EPSILON:
        return {
            "reason": "Aggregate did not beat the best individual trajectory.",
            "status": "blocked_no_score_lift",
        }
    if component_gain <= component_loss:
        return {
            "reason": "Component gain did not exceed component loss versus the best single.",
            "status": "blocked_no_component_gain",
        }
    return {
        "reason": "Aggregate beats best single with net component gain and no hard safety failures.",
        "status": "promoted_local_scout",
    }


def _summary(tasks: list[dict[str, object]]) -> dict[str, object]:
    promoted = [
        task
        for task in tasks
        if _dict(task.get("decision")).get("status") == "promoted_local_scout"
    ]
    aggregate_wins = [
        task for task in tasks if _float(task.get("aggregate_score")) > _float(task.get("best_single_score"))
    ]
    return {
        "aggregate_win_count": len(aggregate_wins),
        "blocked_task_count": len(tasks) - len(promoted),
        "mean_aggregate_score": _mean(_float(task.get("aggregate_score")) for task in tasks),
        "mean_best_single_score": _mean(_float(task.get("best_single_score")) for task in tasks),
        "mean_component_gain": _mean(_float(task.get("component_gain")) for task in tasks),
        "mean_component_loss": _mean(_float(task.get("component_loss")) for task in tasks),
        "promoted_task_count": len(promoted),
        "promoted_tasks": [str(task.get("task_id", "")) for task in promoted],
        "schema_note": "fixture scout only; not model-generated headline evidence",
        "task_count": len(tasks),
    }


def _max_component_weight(component_id: str, rows: list[dict[str, object]]) -> float:
    return max(
        (_float(row.get("component_weight")) for row in rows if str(row.get("component_id", "")) == component_id),
        default=0.0,
    )


def _component_sort_key(row: dict[str, object]) -> tuple[float, float, str]:
    return (
        _float(row.get("support_score")),
        _float(row.get("component_weight")),
        str(row.get("trajectory_id", "")),
    )


def _slim_component(row: dict[str, object]) -> dict[str, object]:
    return {
        "component_id": str(row.get("component_id", "")),
        "component_type": str(row.get("component_type", "")),
        "component_weight": _float(row.get("component_weight")),
        "source_span": str(row.get("source_span", "")),
        "support_score": _float(row.get("support_score")),
        "trajectory_family": str(row.get("trajectory_family", "")),
        "trajectory_id": str(row.get("trajectory_id", "")),
    }


def _read_jsonl(path: Path) -> list[dict[str, object]]:
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        row = json.loads(line)
        if isinstance(row, dict):
            rows.append(row)
    return rows


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    return [row for row in value if isinstance(row, dict)] if isinstance(value, list) else []


def _float(value: object) -> float:
    if value is None:
        return 0.0
    return float(value)


def _bool(value: object) -> bool:
    return bool(value)


def _mean(values: object) -> float:
    items = list(values)
    return sum(items) / len(items) if items else 0.0


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


