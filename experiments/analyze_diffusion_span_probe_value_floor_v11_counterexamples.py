        f"- Counterexamples: `{summary.get('counterexample_count')}`",
        f"- Source-divergent rows: `{summary.get('source_divergent_count')}`",
        f"- Selected-repair positives: `{summary.get('selected_repair_positive_count')}`",
        f"- Oracle positives: `{summary.get('oracle_positive_count')}`",
        "",
