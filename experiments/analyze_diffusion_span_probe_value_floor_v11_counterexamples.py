"""Analyze source-aware counterexamples from the v11 value-floor replay."""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

if str(Path(__file__).resolve().parents[1]) not in sys.path:
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

DEFAULT_REPLAY = Path(
    "eval_results/diffusion_language/span_probe_value_floor_v11_random_source_replay.json"
)
DEFAULT_JSON_OUTPUT = Path(
    "eval_results/diffusion_language/span_probe_value_floor_v11_counterexample_analysis.json"
)
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_COUNTERFACTUAL_SPAN_PROBE_VALUE_FLOOR_V11_COUNTEREXAMPLES.md")
DEFAULT_SELECTION_PENALTY = 0.02
DEFAULT_PROBE_COST_PENALTY = 0.03


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--replay", type=Path, default=DEFAULT_REPLAY)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    analysis = analyze_counterexamples(replay_path=args.replay)
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(analysis, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(analysis), encoding="utf-8")
    print(
        json.dumps(
            {
                "counterexample_count": analysis["summary"]["counterexample_count"],
                "json_output": str(args.json_output),
                "report_output": str(args.report_output),
                "selected_label_best_hypothesis": analysis["selected_repair_hypotheses"][0]["hypothesis_id"],
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def analyze_counterexamples(*, replay_path: Path) -> dict[str, object]:
    replay = json.loads(replay_path.read_text(encoding="utf-8"))
    rows = _list_of_dicts(replay.get("row_diagnostics"))
    hypotheses = _hypotheses()
    selected_repair_hypotheses = [
        _score_hypothesis(rows, hypothesis=hypothesis, label_key="label") for hypothesis in hypotheses
    ]
    oracle_hypotheses = [
        _score_hypothesis(rows, hypothesis=hypothesis, label_key="oracle_label") for hypothesis in hypotheses
    ]
    selected_repair_hypotheses.sort(key=_hypothesis_sort_key)
    oracle_hypotheses.sort(key=_hypothesis_sort_key)
    return {
        "counterexample_rows": _counterexample_rows(rows),
        "generated_by": "experiments/analyze_diffusion_span_probe_value_floor_v11_counterexamples.py",
        "inputs": {"replay": str(replay_path)},
        "oracle_hypotheses": oracle_hypotheses,
        "schema": "diffusion_span_probe_value_floor_v11_counterexamples.v1",
        "selected_repair_hypotheses": selected_repair_hypotheses,
        "summary": {
            "counterexample_count": len(_counterexample_rows(rows)),
            "oracle_positive_count": sum(1 for row in rows if bool(row.get("oracle_label"))),
            "selected_repair_positive_count": sum(1 for row in rows if bool(row.get("label"))),
            "source_divergent_count": sum(1 for row in rows if _float(row.get("source_task_delta_vs_trajectory")) < 0.0),
            "target_count": len(rows),
        },
    }


