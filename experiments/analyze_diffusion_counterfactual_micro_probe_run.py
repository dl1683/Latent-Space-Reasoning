"""Summarize measured counterfactual micro-probe runs against target labels."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_TARGETS = Path("eval_results/diffusion_language/diffusion_counterfactual_probe_targets_v1.json")
DEFAULT_SCORES = Path("eval_results/diffusion_language/counterfactual_micro_probe_counterexamples_v1_scores.json")
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/counterfactual_micro_probe_counterexamples_v1_summary.json")
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_COUNTERFACTUAL_MICRO_PROBE_COUNTEREXAMPLES_V1.md")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--targets", type=Path, default=DEFAULT_TARGETS)
    parser.add_argument("--scores", type=Path, default=DEFAULT_SCORES)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    summary = analyze_counterfactual_micro_probe_run(
        scores_path=args.scores,
        targets_path=args.targets,
    )
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(summary, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(summary), encoding="utf-8")
    print(
        json.dumps(
            {
                "gate_decision": summary["summary"]["gate_decision"],
                "measured_probe_count": summary["summary"]["measured_probe_count"],
                "probe_triage_error_count": summary["summary"]["probe_triage_error_count"],
                "report_output": str(args.report_output),
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def analyze_counterfactual_micro_probe_run(
    *,
    scores_path: Path,
    targets_path: Path,
) -> dict[str, object]:
    scores = json.loads(scores_path.read_text(encoding="utf-8"))
    targets = json.loads(targets_path.read_text(encoding="utf-8"))
    target_rows = {
        str(row.get("task_id", "")): row
        for row in _list_of_dicts(targets.get("rows"))
    }
    rows = [
        _joined_row(row, target_rows.get(str(row.get("task_id", "")), {}))
        for row in _list_of_dicts(scores.get("repair_spend_gate_rows"))
    ]
    rows.sort(key=lambda row: str(row.get("task_id", "")))
    return {
        "generated_by": "experiments/analyze_diffusion_counterfactual_micro_probe_run.py",
        "inputs": {
            "scores": str(scores_path),
            "targets": str(targets_path),
        },
        "rows": rows,
        "schema": "diffusion_counterfactual_micro_probe_run_summary.v1",
        "summary": _summary(rows, scores),
    }


def render_markdown(summary: dict[str, object]) -> str:
    stats = _dict(summary.get("summary"))
    lines = [
        "# Diffusion Counterfactual Micro-Probe Counterexamples V1",
        "",
        "This file is generated by `experiments/analyze_diffusion_counterfactual_micro_probe_run.py`.",
        (
            "It joins the measured `counterfactual_micro_probe_v1` CUDA run to "
            "the v5-v9 counterexample target labels. It is diagnostic evidence, "
            "not a promoted spend gate."
        ),
        "",
        "## Summary",
        "",
        f"- Target rows: `{stats.get('row_count', 0)}`",
        f"- Positive labels: `{stats.get('positive_label_count', 0)}`",
        f"- Negative labels: `{stats.get('negative_label_count', 0)}`",
        f"- Measured probe generations: `{stats.get('measured_probe_count', 0)}`",
        f"- Probe triage errors: `{stats.get('probe_triage_error_count', 0)}`",
        f"- Probe false positives: `{stats.get('probe_false_positive_count', 0)}`",
        f"- Probe false negatives: `{stats.get('probe_false_negative_count', 0)}`",
        f"- Full repair authorizations: `{stats.get('should_run_count', 0)}`",
        f"- Normal arm generations: `{stats.get('all_generation_count', 0)}`",
        f"- Counterfactual probe generations: `{stats.get('counterfactual_probe_generation_count', 0)}`",
        f"- Run content hash: `{stats.get('content_hash', '')}`",
        f"- Gate decision: `{stats.get('gate_decision', '')}`",
        "",
        "## Rows",
        "",
        (
            "| Task | Label | Lift | Would Probe | Observation | Should Run | "
            "Probe Tokens | Measured Value | Prompt Gap | Source Quality | Error |"
        ),
        "| --- | --- | ---: | --- | --- | --- | ---: | ---: | ---: | ---: | --- |",
    ]
    for row in _list_of_dicts(summary.get("rows")):
        lines.append(
            "| "
            f"`{row.get('task_id', '')}` | "
            f"{bool(row.get('label'))} | "
            f"{_format_float(row.get('candidate_lift_vs_trajectory'))} | "
            f"{bool(row.get('would_probe'))} | "
            f"`{row.get('counterfactual_probe_observation', '')}` | "
            f"{bool(row.get('should_run'))} | "
            f"{int(_float(row.get('counterfactual_probe_generated_token_count')))} | "
            f"{_format_float(row.get('measured_probe_value_prediction'))} | "
            f"{int(_float(row.get('prompt_gap_count')))} | "
            f"{_format_float(row.get('source_quality'))} | "
            f"{bool(row.get('probe_triage_error'))} |"
        )
    lines.extend(
        [
            "",
            "## Reading",
            "",
            (
                "The measured hook bought cheap probe observations for all seven "
                "historically profitable target rows and skipped all five historical "
                "no-lift rows. That is a strong triage result, but it still does not "
                "authorize repair spend: every row has `should_run=false`, and the "
                "measured values now need a separate value-of-information fit before "
                "the architecture gate can be considered for promotion."
            ),
        ]
    )
    return "\n".join(lines) + "\n"


def _joined_row(gate_row: dict[str, object], target_row: dict[str, object]) -> dict[str, object]:
    labels = _dict(target_row.get("labels"))
    label = bool(labels.get("promote_vs_trajectory"))
    would_probe = bool(gate_row.get("would_probe"))
    return {
        "candidate_lift_vs_trajectory": _float(labels.get("candidate_lift_vs_trajectory")),
        "counterexample_type": str(target_row.get("counterexample_type", "")),
        "counterfactual_probe_generated_token_count": _optional_int(
            gate_row.get("counterfactual_probe_generated_token_count")
        ),
        "counterfactual_probe_observation": str(gate_row.get("counterfactual_probe_observation", "")),
        "label": label,
        "measured_probe_value_prediction": _optional_float(
            gate_row.get("measured_probe_value_prediction")
        ),
        "probe_triage_error": would_probe != label,
        "prompt_gap_count": _float(gate_row.get("prompt_gap_count")),
        "should_run": bool(gate_row.get("should_run")),
        "source_quality": _float(gate_row.get("source_quality")),
        "task_id": str(gate_row.get("task_id", "")),
        "would_probe": would_probe,
    }


def _summary(rows: list[dict[str, object]], scores: dict[str, object]) -> dict[str, object]:
    positives = [row for row in rows if bool(row.get("label"))]
    negatives = [row for row in rows if not bool(row.get("label"))]
    false_positives = [
        row for row in negatives if bool(row.get("would_probe"))
    ]
    false_negatives = [
        row for row in positives if not bool(row.get("would_probe"))
    ]
    return {
        "all_generation_count": int(_float(scores.get("all_generation_count"))),
        "content_hash": str(scores.get("content_hash", "")),
        "counterfactual_probe_generation_count": int(
            _float(scores.get("counterfactual_probe_generation_count"))
        ),
        "gate_decision": "diagnostic_only",
        "measured_probe_count": sum(
            1 for row in rows if row.get("counterfactual_probe_observation") == "measured_generation"
        ),
        "negative_label_count": len(negatives),
        "positive_label_count": len(positives),
        "probe_false_negative_count": len(false_negatives),
        "probe_false_negative_task_ids": [str(row.get("task_id", "")) for row in false_negatives],
        "probe_false_positive_count": len(false_positives),
        "probe_false_positive_task_ids": [str(row.get("task_id", "")) for row in false_positives],
        "probe_triage_error_count": len(false_positives) + len(false_negatives),
        "row_count": len(rows),
        "should_run_count": sum(1 for row in rows if bool(row.get("should_run"))),
    }


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    if not isinstance(value, list):
        return []
    return [item for item in value if isinstance(item, dict)]


def _float(value: object) -> float:
    if value is None:
        return 0.0
    try:
        return float(value)
    except (TypeError, ValueError):
        return 0.0


def _optional_float(value: object) -> float | None:
    if value is None:
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def _optional_int(value: object) -> int | None:
    if value is None:
        return None
    try:
        return int(value)
    except (TypeError, ValueError):
        return None


def _format_float(value: object) -> str:
    optional = _optional_float(value)
    if optional is None:
        return ""
    return f"{optional:.6f}"


if __name__ == "__main__":
    raise SystemExit(main())
