"""Analyze score dimensions hidden by rubric-only component gain."""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from experiments.run_latent_aggregation_inference_replay import _record_task_id, _trajectory_id

DEFAULT_REPLAY = Path("eval_results/diffusion_language/latent_aggregation_inference_v1_threshold01_replay.json")
DEFAULT_RAW = Path("eval_results/diffusion_language/latent_aggregation_inference_v1_raw.jsonl")
DEFAULT_REALIZED = Path("eval_results/diffusion_language/latent_aggregation_inference_v1_threshold01_realized.jsonl")
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/latent_aggregation_score_dimension_gap_threshold01.json")
DEFAULT_REPORT_OUTPUT = Path("docs/reports/diffusion/LATENT_AGGREGATION_SCORE_DIMENSION_GAP_THRESHOLD01.md")
DIMENSIONS = (
    "completion",
    "causal_diagnosis",
    "specificity",
    "constraint_handling",
    "risk_awareness",
    "rubric_coverage",
)
NON_RUBRIC_DIMENSIONS = DIMENSIONS[:-1]
EPSILON = 1e-9


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--replay", type=Path, default=DEFAULT_REPLAY)
    parser.add_argument("--raw", type=Path, default=DEFAULT_RAW)
    parser.add_argument("--realized", type=Path, default=DEFAULT_REALIZED)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    result = analyze_score_dimension_gap(
        replay_path=args.replay,
        raw_path=args.raw,
        realized_path=args.realized,
    )
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(result, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(result), encoding="utf-8")
    print(
        json.dumps(
            {
                "best_full_rubric_score_lift_without_gain_task_count": result["summary"][
                    "best_full_rubric_score_lift_without_gain_task_count"
                ],
                "json_output": str(args.json_output),
                "report_output": str(args.report_output),
                "task_count": result["summary"]["task_count"],
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def analyze_score_dimension_gap(
    *,
    replay_path: Path,
    raw_path: Path,
    realized_path: Path,
) -> dict[str, object]:
    replay = json.loads(replay_path.read_text(encoding="utf-8"))
    raw_records = _read_jsonl(raw_path)
    realized_rows = {str(row.get("task_id", "")): row for row in _read_jsonl(realized_path)}
    raw_by_task: dict[str, list[dict[str, object]]] = defaultdict(list)
    for record in raw_records:
        task_id = _record_task_id(record)
        if task_id:
            raw_by_task[task_id].append(record)

    tasks = []
    for task in _list_of_dicts(replay.get("tasks")):
        task_id = str(task.get("task_id", ""))
        best_record = _best_record(raw_by_task.get(task_id, []))
        tasks.append(_analyze_task(task, best_record, realized_rows.get(task_id, {})))

    return {
        "evidence_boundary": {
            "reason": "Diagnostic over post-hoc threshold replay score details; use to define richer predeclared components.",
            "status": "post_hoc_score_dimension_gap_diagnostic",
        },
        "generated_by": "experiments/analyze_latent_aggregation_score_dimension_gap.py",
        "inputs": {"raw": str(raw_path), "realized": str(realized_path), "replay": str(replay_path)},
        "schema": "latent_aggregation_score_dimension_gap.v1",
        "summary": _summary(tasks),
        "tasks": tasks,
    }


