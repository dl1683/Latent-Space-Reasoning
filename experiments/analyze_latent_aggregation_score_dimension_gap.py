def _analyze_task(
    replay_task: dict[str, object],
    best_record: dict[str, object],
    realized_row: dict[str, object],
) -> dict[str, object]:
    task_id = str(replay_task.get("task_id", ""))
    best_score = _float(_dict(best_record.get("task_score")).get("score"))
    realized_score = _float(_dict(realized_row.get("task_score")).get("score"))
    best_details = _dimension_details(_dict(_dict(best_record.get("task_score")).get("details")))
    realized_details = _dimension_details(_dict(_dict(realized_row.get("task_score")).get("details")))
    dimension_delta = {
        dimension: realized_details[dimension] - best_details[dimension] for dimension in DIMENSIONS
    }
    component_gain = int(_float(replay_task.get("component_gain")))
    score_lift = realized_score - best_score
    best_full_rubric = best_details["rubric_coverage"] >= 1.0 - EPSILON
    return {
        "best_details": best_details,
        "best_full_rubric": best_full_rubric,
        "best_non_rubric_score": _non_rubric_score(best_details),
        "best_score": best_score,
        "best_single_trajectory_id": _trajectory_id(best_record, 0, stable=True) if best_record else "",
        "component_gain": component_gain,
        "decision_status": str(_dict(replay_task.get("decision")).get("status", "")),
        "diagnosis": _diagnosis(
            best_full_rubric=best_full_rubric,
            component_gain=component_gain,
            non_rubric_lift=_non_rubric_score(realized_details) - _non_rubric_score(best_details),
            score_lift=score_lift,
        ),
        "dimension_delta": dimension_delta,
        "largest_dimension_lift": _largest_positive_dimension(dimension_delta),
        "non_rubric_lift": _non_rubric_score(realized_details) - _non_rubric_score(best_details),
        "realized_details": realized_details,
        "realized_non_rubric_score": _non_rubric_score(realized_details),
        "realized_score": realized_score,
        "score_lift": score_lift,
        "score_lift_without_component_gain": score_lift > EPSILON and component_gain <= 0,
        "task_id": task_id,
    }


def _summary(tasks: list[dict[str, object]]) -> dict[str, object]:
    score_lift_without_gain = [
        task for task in tasks if task.get("score_lift_without_component_gain")
    ]
    best_full_rubric_score_lift_without_gain = [
        task for task in score_lift_without_gain if task.get("best_full_rubric")
    ]
    return {
        "best_full_rubric_score_lift_without_gain_task_count": len(
            best_full_rubric_score_lift_without_gain
        ),
        "best_full_rubric_task_count": sum(1 for task in tasks if task.get("best_full_rubric")),
        "diagnosis_counts": _counts(str(task.get("diagnosis", "")) for task in tasks),
        "mean_best_non_rubric_score": _mean(_float(task.get("best_non_rubric_score")) for task in tasks),
        "mean_dimension_delta": {
            dimension: _mean(_float(_dict(task.get("dimension_delta")).get(dimension)) for task in tasks)
            for dimension in DIMENSIONS
        },
        "mean_non_rubric_lift": _mean(_float(task.get("non_rubric_lift")) for task in tasks),
        "mean_realized_non_rubric_score": _mean(
            _float(task.get("realized_non_rubric_score")) for task in tasks
        ),
        "score_lift_without_component_gain_task_count": len(score_lift_without_gain),
        "task_count": len(tasks),
    }


def _dimension_details(details: dict[str, object]) -> dict[str, float]:
    return {dimension: _float(details.get(dimension)) for dimension in DIMENSIONS}


def _non_rubric_score(details: dict[str, float]) -> float:
    return (
        0.18 * details["completion"]
        + 0.20 * details["causal_diagnosis"]
        + 0.20 * details["specificity"]
        + 0.17 * details["constraint_handling"]
        + 0.15 * details["risk_awareness"]
    )


def _largest_positive_dimension(deltas: dict[str, float]) -> str:
    dimension, value = max(deltas.items(), key=lambda item: item[1])
    return dimension if value > EPSILON else "none"


def _diagnosis(
    *,
    best_full_rubric: bool,
    component_gain: int,
    non_rubric_lift: float,
    score_lift: float,
) -> str:
    if component_gain > 0:
        return "rubric_component_gain"
    if score_lift > EPSILON and best_full_rubric and non_rubric_lift > EPSILON:
        return "score_lift_hidden_by_rubric_saturation"
    if score_lift > EPSILON and non_rubric_lift > EPSILON:
        return "score_lift_from_non_rubric_dimensions"
    if score_lift > EPSILON:
        return "score_lift_not_explained_by_dimension_delta"
    return "no_score_lift"


def _best_record(records: list[dict[str, object]]) -> dict[str, object]:
    if not records:
        return {}
    return max(records, key=lambda record: _float(_dict(record.get("task_score")).get("score")))


def _read_jsonl(path: Path) -> list[dict[str, object]]:
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            row = json.loads(line)
            if isinstance(row, dict):
                rows.append(row)
    return rows


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    return [item for item in value if isinstance(item, dict)] if isinstance(value, list) else []


def _float(value: object) -> float:
    if value is None:
        return 0.0
    return float(value)


def _mean(values: object) -> float:
    items = list(values)
    return sum(items) / len(items) if items else 0.0


def _counts(values: object) -> dict[str, int]:
    counts: dict[str, int] = {}
    for value in values:
        counts[value] = counts.get(value, 0) + 1
    return dict(sorted(counts.items()))


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


def _format_counts(value: object) -> str:
    if not isinstance(value, dict) or not value:
        return "none"
    return ", ".join(f"{key}={_format_float(value[key])}" for key in sorted(value))


