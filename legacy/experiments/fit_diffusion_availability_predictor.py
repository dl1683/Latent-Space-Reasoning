"""Fit an interpretable diffusion repair-availability predictor."""

from __future__ import annotations

import argparse
import json
import math
from itertools import combinations
from pathlib import Path

DEFAULT_AVAILABILITY_EVAL = Path(
    "eval_results/diffusion_language/diffusion_independent_spend_transfer_v3_eval.json"
)
DEFAULT_JSON_OUTPUT = Path(
    "eval_results/diffusion_language/diffusion_availability_predictor_fit.json"
)
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_AVAILABILITY_PREDICTOR_FIT.md")
DEFAULT_POLICY_SCORES = Path(
    "eval_results/diffusion_language/"
    "llada_moe_mixed_transfer_v3_learned_availability_transfer_promotion_v1_scores.json"
)
FEATURES = (
    "has_repairable_denoise_skeleton",
    "prompt_gap_count",
    "source_quality",
    "source_task_delta_vs_trajectory",
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--availability-eval", type=Path, default=DEFAULT_AVAILABILITY_EVAL)
    parser.add_argument("--policy-scores", type=Path, default=DEFAULT_POLICY_SCORES)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    fit = fit_availability_predictor(args.availability_eval, policy_scores_path=args.policy_scores)
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(fit, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(fit), encoding="utf-8")
    print(
        json.dumps(
            {
                "error_count": _dict(fit.get("best_rule")).get("error_count", 0),
                "json_output": str(args.json_output),
                "loo_error_count": _dict(fit.get("leave_one_out")).get("error_count", 0),
                "report_output": str(args.report_output),
                "rule_id": _dict(fit.get("best_rule")).get("rule_id", ""),
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def fit_availability_predictor(
    path: Path,
    *,
    policy_scores_path: Path | None = None,
) -> dict[str, object]:
    source = json.loads(path.read_text(encoding="utf-8"))
    rows = [_feature_row(row) for row in _list_of_dicts(source.get("rows"))]
    rules = _candidate_rules(rows)
    scored_rules = [_score_rule(rule, rows) for rule in rules]
    best_rule = min(
        scored_rules,
        key=lambda rule: (
            int(rule.get("error_count", 0)),
            int(rule.get("predicate_count", 0)),
            -float(rule.get("true_positive_count", 0)),
            str(rule.get("rule_id", "")),
        ),
    )
    leave_one_out = _leave_one_out(rows)
    baselines = _baselines(rows)
    return {
        "availability_eval": str(path),
        "baselines": baselines,
        "best_rule": best_rule,
        "cuda_policy": _cuda_policy(policy_scores_path),
        "features": list(FEATURES),
        "generated_by": "experiments/fit_diffusion_availability_predictor.py",
        "leave_one_out": leave_one_out,
        "rows": rows,
        "schema": "diffusion_availability_predictor_fit.v1",
        "summary": {
            "best_rule_error_count": int(best_rule.get("error_count", 0)),
            "best_rule_id": str(best_rule.get("rule_id", "")),
            "positive_count": sum(int(row.get("label", False)) for row in rows),
            "row_count": len(rows),
        },
    }


def render_markdown(fit: dict[str, object]) -> str:
    summary = _dict(fit.get("summary"))
    best = _dict(fit.get("best_rule"))
    loo = _dict(fit.get("leave_one_out"))
    cuda = _dict(fit.get("cuda_policy"))
    lines = [
        "# Diffusion Availability Predictor Fit",
        "",
        "This file is generated by `experiments/fit_diffusion_availability_predictor.py`.",
        (
            "It fits a small interpretable repair-availability predictor over the "
            "larger v3 transfer rows, using only denoise/source geometry available "
            "before the repair is generated."
        ),
        "",
        "## Summary",
        "",
        f"- Input availability eval: `{fit.get('availability_eval', '')}`",
        f"- Rows: `{summary.get('row_count', 0)}`",
        f"- Positive rows: `{summary.get('positive_count', 0)}`",
        f"- Best rule: `{summary.get('best_rule_id', '')}`",
        f"- Best rule errors: `{summary.get('best_rule_error_count', 0)}`",
        f"- Leave-one-out errors: `{loo.get('error_count', 0)}`",
        f"- Leave-one-out selected tasks: {_join_tasks(loo.get('selected_tasks'))}",
        f"- CUDA policy run: `{cuda.get('run_id', 'not-run')}`",
        f"- CUDA repair-covered planning score: `{_format_float(cuda.get('repair_planning_task_score'))}`",
        f"- CUDA oracle headroom vs repair: `{_format_float(cuda.get('oracle_headroom_vs_repair'))}`",
        "",
        "## Baselines",
        "",
        "| Rule | Errors | Selected Tasks |",
        "| --- | ---: | --- |",
    ]
    for baseline in _list_of_dicts(fit.get("baselines")):
        lines.append(
            "| "
            f"`{baseline.get('rule_id', '')}` | "
            f"{baseline.get('error_count', 0)} | "
            f"{_join_tasks(baseline.get('selected_tasks'))} |"
        )
    lines.extend(
        [
            "",
            "## Best Rule",
            "",
            "| Predicate |",
            "| --- |",
        ]
    )
    for predicate in _list_of_dicts(best.get("predicates")):
        lines.append(f"| `{_predicate_text(predicate)}` |")
    lines.extend(
        [
            "",
            "## Rows",
            "",
            (
                "| Task | Label | Prediction | First Step | Gap | Source Quality | "
                "Source-Selected Delta |"
            ),
            "| --- | --- | --- | ---: | ---: | ---: | ---: |",
        ]
    )
    predictions = _dict(best.get("predictions"))
    for row in _list_of_dicts(fit.get("rows")):
        task_id = str(row.get("task_id", ""))
        lines.append(
            "| "
            f"`{task_id}` | "
            f"{bool(row.get('label'))} | "
            f"{bool(predictions.get(task_id))} | "
            f"{_format_optional(row.get('first_repairable_step'))} | "
            f"{_format_float(row.get('prompt_gap_count'))} | "
            f"{_format_float(row.get('source_quality'))} | "
            f"{_format_float(row.get('source_task_delta_vs_trajectory'))} |"
        )
    lines.extend(
        [
            "",
            "## Reading",
            "",
            (
                "The corrected repair-only labels make the v3 fit a boundary rather "
                "than a solved availability head. Pre-repair denoise/source geometry "
                "is still useful, but it cannot see whether the generated repair "
                "candidate will actually deserve promotion. The useful information "
                "channels are: a repairable denoise skeleton exists, the prompt-gap "
                "count remains inside the productive repair band, source quality is "
                "not globally stable across slices, and the chosen repair source must "
                "be compared with the already selected trajectory state."
            ),
            "",
            (
                "The stale CUDA policy run listed above is preserved as historical "
                "evidence for the older v3 rule; it should not be treated as the "
                "current best availability head after the repair-only label fix. "
                "`DIFFUSION_CANDIDATE_PROMOTION_TARGETS_V5.md` is now the sharper "
                "next target: use pre-repair geometry for spend gating and "
                "post-repair diagnostics for promotion."
            ),
        ]
    )
    return "\n".join(lines) + "\n"


def _feature_row(row: dict[str, object]) -> dict[str, object]:
    first_step = row.get("first_repairable_step")
    return {
        "first_repairable_step": first_step,
        "decomposed_prediction": bool(row.get("decomposed_prediction")),
        "has_repairable_denoise_skeleton": first_step is not None,
        "label": bool(row.get("profitable")),
        "prompt_gap_count": _float(row.get("prompt_gap_count")),
        "single_repairability_prediction": bool(row.get("single_repairability_prediction")),
        "source_quality": _float(row.get("source_quality")),
        "source_task_delta_vs_trajectory": _float(row.get("source_task_delta_vs_trajectory")),
        "task_id": str(row.get("task_id", "")),
        "trajectory_relative_prediction": bool(row.get("trajectory_relative_prediction")),
    }


def _candidate_rules(rows: list[dict[str, object]]) -> list[dict[str, object]]:
    atomic = _atomic_predicates(rows)
    candidates = [rule for size in range(1, 5) for rule in _rule_combinations(atomic, size)]
    return _dedupe_rules(candidates)


def _atomic_predicates(rows: list[dict[str, object]]) -> list[dict[str, object]]:
    predicates = [{"feature": "has_repairable_denoise_skeleton", "op": "is_true"}]
    for feature in ("prompt_gap_count", "source_quality", "source_task_delta_vs_trajectory"):
        values = sorted({_float(row.get(feature)) for row in rows})
        for threshold in values:
            predicates.append({"feature": feature, "op": "<=", "threshold": threshold})
            predicates.append({"feature": feature, "op": ">=", "threshold": threshold})
    return predicates


def _rule_combinations(predicates: list[dict[str, object]], size: int) -> list[dict[str, object]]:
    rules = []
    for combo in combinations(predicates, size):
        features = [str(predicate.get("feature", "")) for predicate in combo]
        if len(set(features)) != len(features):
            continue
        rules.append({"predicates": list(combo)})
    return rules


def _dedupe_rules(rules: list[dict[str, object]]) -> list[dict[str, object]]:
    seen = set()
    deduped = []
    for rule in rules:
        key = tuple(sorted(_predicate_text(predicate) for predicate in _list_of_dicts(rule.get("predicates"))))
        if key in seen:
            continue
        seen.add(key)
        deduped.append(rule)
    return deduped


def _score_rule(rule: dict[str, object], rows: list[dict[str, object]]) -> dict[str, object]:
    predictions = {
        str(row.get("task_id", "")): _predict_rule(rule, row)
        for row in rows
    }
    confusion = _confusion(rows, predictions)
    predicates = _list_of_dicts(rule.get("predicates"))
    return {
        **rule,
        **confusion,
        "predicate_count": len(predicates),
        "predictions": predictions,
        "rule_id": _rule_id(predicates),
        "selected_tasks": [
            str(row.get("task_id", ""))
            for row in rows
            if predictions.get(str(row.get("task_id", "")))
        ],
    }


def _leave_one_out(rows: list[dict[str, object]]) -> dict[str, object]:
    predictions = {}
    selected_rules = {}
    for held_out in rows:
        train = [row for row in rows if row is not held_out]
        best = min(
            (_score_rule(rule, train) for rule in _candidate_rules(train)),
            key=lambda rule: (
                int(rule.get("error_count", 0)),
                int(rule.get("predicate_count", 0)),
                -float(rule.get("true_positive_count", 0)),
                str(rule.get("rule_id", "")),
            ),
        )
        task_id = str(held_out.get("task_id", ""))
        predictions[task_id] = _predict_rule(best, held_out)
        selected_rules[task_id] = str(best.get("rule_id", ""))
    confusion = _confusion(rows, predictions)
    return {
        **confusion,
        "predictions": predictions,
        "selected_rules": selected_rules,
        "selected_tasks": [
            str(row.get("task_id", ""))
            for row in rows
            if predictions.get(str(row.get("task_id", "")))
        ],
    }


def _baselines(rows: list[dict[str, object]]) -> list[dict[str, object]]:
    baseline_keys = (
        "single_repairability_prediction",
        "decomposed_prediction",
        "trajectory_relative_prediction",
    )
    baselines = []
    for key in baseline_keys:
        predictions = {str(row.get("task_id", "")): bool(row.get(key, False)) for row in rows}
        confusion = _confusion(rows, predictions)
        baselines.append(
            {
                **confusion,
                "rule_id": key,
                "selected_tasks": [
                    str(row.get("task_id", ""))
                    for row in rows
                    if predictions.get(str(row.get("task_id", "")))
                ],
            }
        )
    return baselines


def _cuda_policy(path: Path | None) -> dict[str, object]:
    if path is None or not path.exists():
        return {}
    scores = json.loads(path.read_text(encoding="utf-8"))
    planning_repair = _dict(_dict(scores.get("by_family_arm")).get("planning")).get(
        "repair_selected"
    )
    return {
        "all_generation_count": int(scores.get("all_generation_count", 0)),
        "oracle_headroom_vs_repair": _float(scores.get("oracle_headroom_vs_repair")),
        "repair_generation_budget_delta_vs_evolved": _float(
            scores.get("repair_generation_budget_delta_vs_evolved")
        ),
        "repair_planning_task_score": _float(
            _dict(planning_repair).get("mean_task_score")
        ),
        "repair_task_delta_vs_fixed": _float(scores.get("repair_task_delta_vs_fixed")),
        "repair_task_delta_vs_random": _float(scores.get("repair_task_delta_vs_random")),
        "run_id": str(scores.get("run_id", "")),
        "scores": str(path),
    }


def _predict_rule(rule: dict[str, object], row: dict[str, object]) -> bool:
    return all(_predicate_matches(predicate, row) for predicate in _list_of_dicts(rule.get("predicates")))


def _predicate_matches(predicate: dict[str, object], row: dict[str, object]) -> bool:
    feature = str(predicate.get("feature", ""))
    op = str(predicate.get("op", ""))
    if op == "is_true":
        return bool(row.get(feature))
    value = _float(row.get(feature))
    threshold = _float(predicate.get("threshold"))
    if op == "<=":
        return value <= threshold + 1e-12
    if op == ">=":
        return value >= threshold - 1e-12
    raise ValueError(f"Unsupported predicate op: {op}")


def _confusion(rows: list[dict[str, object]], predictions: dict[str, bool]) -> dict[str, int]:
    tp = tn = fp = fn = 0
    for row in rows:
        label = bool(row.get("label"))
        prediction = bool(predictions.get(str(row.get("task_id", ""))))
        if label and prediction:
            tp += 1
        elif label:
            fn += 1
        elif prediction:
            fp += 1
        else:
            tn += 1
    return {
        "error_count": fp + fn,
        "false_negative_count": fn,
        "false_positive_count": fp,
        "true_negative_count": tn,
        "true_positive_count": tp,
    }


def _rule_id(predicates: list[dict[str, object]]) -> str:
    return "and".join(_predicate_slug(predicate) for predicate in predicates)


def _predicate_slug(predicate: dict[str, object]) -> str:
    feature = str(predicate.get("feature", ""))
    op = str(predicate.get("op", ""))
    if op == "is_true":
        return feature
    threshold = _float(predicate.get("threshold"))
    sign = "le" if op == "<=" else "ge"
    return f"{feature}_{sign}_{_slug_float(threshold)}"


def _predicate_text(predicate: dict[str, object]) -> str:
    feature = str(predicate.get("feature", ""))
    op = str(predicate.get("op", ""))
    if op == "is_true":
        return feature
    return f"{feature} {op} {_format_float(predicate.get('threshold'))}"


def _slug_float(value: float) -> str:
    if math.isclose(value, round(value)):
        return str(int(round(value)))
    return f"{value:.6f}".replace("-", "neg").replace(".", "p")


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    return [row for row in value if isinstance(row, dict)] if isinstance(value, list) else []


def _float(value: object) -> float:
    if value is None:
        return 0.0
    return float(value)


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


def _format_optional(value: object) -> str:
    if value is None:
        return ""
    return _format_float(value)


def _join_tasks(value: object) -> str:
    values = [str(item) for item in value] if isinstance(value, list) else []
    return ", ".join(f"`{item}`" for item in values) if values else "`none`"


if __name__ == "__main__":
    raise SystemExit(main())
