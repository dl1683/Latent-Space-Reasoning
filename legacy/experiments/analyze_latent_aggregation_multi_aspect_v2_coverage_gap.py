def _analyze_task(task_id: str, records: list[dict[str, object]]) -> dict[str, object]:
    if not records:
        return _empty_task(task_id, "missing_raw_records")
    anchor = max(records, key=_score)
    anchor_id = _trajectory_id(anchor, 0, stable=True)
    anchor_aspects = _aspect_scores(anchor)
    non_anchor = [
        record for record in records if _trajectory_id(record, 0, stable=True) != anchor_id
    ]
    deltas = []
    selected = []
    for record in non_anchor:
        candidate_aspects = _aspect_scores(record)
        selected.extend(
            _complement_aspects(
                anchor_aspects=anchor_aspects,
                candidate_aspects=candidate_aspects,
                trajectory_id=_trajectory_id(record, 0, stable=True),
            )
        )
        deltas.extend(_aspect_deltas(anchor_aspects, candidate_aspects))
    best_by_aspect: dict[str, dict[str, object]] = {}
    for row in selected:
        aspect_id = str(row.get("aspect_id", ""))
        current = best_by_aspect.get(aspect_id)
        if current is None or _float(row.get("delta")) > _float(current.get("delta")):
            best_by_aspect[aspect_id] = row
    selected_count = len(best_by_aspect)
    positive = [row for row in deltas if _float(row.get("delta")) > EPSILON]
    near_miss = [
        row
        for row in positive
        if _float(row.get("delta")) < _float(row.get("selection_threshold")) - EPSILON
    ]
    max_dimension_delta = max(
        (_float(row.get("delta")) for row in deltas if row.get("aspect_class") == "dimension"),
        default=0.0,
    )
    max_rubric_delta = max(
        (_float(row.get("delta")) for row in deltas if row.get("aspect_class") == "rubric"),
        default=0.0,
    )
    nonempty_count = sum(1 for record in non_anchor if str(record.get("text", "")).strip())
    return {
        "anchor_score": _score(anchor),
        "anchor_trajectory_id": anchor_id,
        "coverage_blocker": _coverage_blocker(
            max_dimension_delta=max_dimension_delta,
            max_rubric_delta=max_rubric_delta,
            near_miss_count=len(near_miss),
            non_anchor_count=len(non_anchor),
            nonempty_count=nonempty_count,
            positive_count=len(positive),
            selected_count=selected_count,
        ),
        "max_dimension_delta": max_dimension_delta,
        "max_rubric_delta": max_rubric_delta,
        "near_miss_aspect_count": len(near_miss),
        "non_anchor_candidate_count": len(non_anchor),
        "nonempty_candidate_count": nonempty_count,
        "positive_delta_aspect_count": len(positive),
        "selected_complement_count": selected_count,
        "task_id": task_id,
    }


def _empty_task(task_id: str, blocker: str) -> dict[str, object]:
    return {
        "anchor_score": 0.0,
        "anchor_trajectory_id": "",
        "coverage_blocker": blocker,
        "max_dimension_delta": 0.0,
        "max_rubric_delta": 0.0,
        "near_miss_aspect_count": 0,
        "non_anchor_candidate_count": 0,
        "nonempty_candidate_count": 0,
        "positive_delta_aspect_count": 0,
        "selected_complement_count": 0,
        "task_id": task_id,
    }


def _aspect_deltas(
    anchor_aspects: dict[str, dict[str, object]],
    candidate_aspects: dict[str, dict[str, object]],
) -> list[dict[str, object]]:
    rows = []
    for aspect_id, candidate in candidate_aspects.items():
        aspect_class = str(candidate.get("aspect_class", ""))
        anchor_score = _float(_dict(anchor_aspects.get(aspect_id)).get("support_score"))
        candidate_score = _float(candidate.get("support_score"))
        threshold = 1.0 if aspect_class == "rubric" else DIMENSION_DELTA
        rows.append(
            {
                "aspect_class": aspect_class,
                "aspect_id": aspect_id,
                "aspect_type": str(candidate.get("aspect_type", "")),
                "delta": candidate_score - anchor_score,
                "selection_threshold": threshold,
            }
        )
    return rows


def _coverage_blocker(
    *,
    max_dimension_delta: float,
    max_rubric_delta: float,
    near_miss_count: int,
    non_anchor_count: int,
    nonempty_count: int,
    positive_count: int,
    selected_count: int,
) -> str:
    if selected_count > 0:
        return "has_selected_complement"
    if non_anchor_count <= 0:
        return "no_non_anchor_candidates"
    if nonempty_count <= 0:
        return "all_non_anchor_candidates_blank"
    if positive_count <= 0:
        return "anchor_dominates_candidate_aspects"
    if near_miss_count > 0:
        return "positive_but_below_threshold"
    if max_rubric_delta > EPSILON and max_dimension_delta <= EPSILON:
        return "rubric_delta_not_full_hit"
    return "unclassified_no_selected_complement"


def _summary(tasks: list[dict[str, object]]) -> dict[str, object]:
    no_complement = [
        task for task in tasks if int(_float(task.get("selected_complement_count"))) <= 0
    ]
    no_complement_max_dimension = [
        _float(task.get("max_dimension_delta")) for task in no_complement
    ]
    return {
        "max_no_complement_dimension_delta": max(no_complement_max_dimension, default=0.0),
        "mean_no_complement_max_dimension_delta": _mean(no_complement_max_dimension),
        "mean_non_anchor_candidate_count": _mean(
            _float(task.get("non_anchor_candidate_count")) for task in tasks
        ),
        "mean_nonempty_candidate_count": _mean(
            _float(task.get("nonempty_candidate_count")) for task in tasks
        ),
        "no_complement_blockers": _blocker_counts(no_complement),
        "no_complement_tasks_with_near_miss": sum(
            1 for task in no_complement if int(_float(task.get("near_miss_aspect_count"))) > 0
        ),
        "task_count": len(tasks),
        "tasks_with_selected_complement": sum(
            1 for task in tasks if int(_float(task.get("selected_complement_count"))) > 0
        ),
        "tasks_without_selected_complement": len(no_complement),
    }


def _blocker_counts(tasks: list[dict[str, object]]) -> dict[str, int]:
    return dict(sorted(Counter(str(task.get("coverage_blocker", "")) for task in tasks).items()))


def _score(record: dict[str, object]) -> float:
    return _float(_dict(record.get("task_score")).get("score"))


def _read_jsonl(path: Path) -> list[dict[str, object]]:
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            row = json.loads(line)
            if isinstance(row, dict):
                rows.append(row)
    return rows


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    return [item for item in value if isinstance(item, dict)] if isinstance(value, list) else []


def _float(value: object) -> float:
    if value is None:
        return 0.0
    return float(value)


def _mean(values: object) -> float:
    items = list(values)
    return sum(items) / len(items) if items else 0.0


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


def _format_counts(value: object) -> str:
    if not isinstance(value, dict) or not value:
        return "none"
    return ", ".join(f"{key}={value[key]}" for key in sorted(value))


