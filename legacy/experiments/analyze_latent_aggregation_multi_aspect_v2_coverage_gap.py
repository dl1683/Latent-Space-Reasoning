"""Diagnose complement coverage blockers in the held-out multi-aspect v2 run."""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from experiments.analyze_latent_aggregation_multi_aspect_v2_headroom import (
    DIMENSION_DELTA,
    _aspect_scores,
    _complement_aspects,
)
from experiments.run_latent_aggregation_inference_replay import _record_task_id, _trajectory_id

DEFAULT_RAW = Path("eval_results/diffusion_language/latent_aggregation_multi_aspect_v2_raw.jsonl")
DEFAULT_FREEZE = Path("eval_results/diffusion_language/latent_aggregation_multi_aspect_v2_freeze.json")
DEFAULT_JSON_OUTPUT = Path(
    "eval_results/diffusion_language/latent_aggregation_multi_aspect_v2_coverage_gap.json"
)
DEFAULT_REPORT_OUTPUT = Path(
    "docs/reports/diffusion/LATENT_AGGREGATION_MULTI_ASPECT_V2_COVERAGE_GAP.md"
)
EPSILON = 1e-9


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--raw", type=Path, default=DEFAULT_RAW)
    parser.add_argument("--freeze", type=Path, default=DEFAULT_FREEZE)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    result = analyze_coverage_gap(raw_path=args.raw, freeze_path=args.freeze)
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(result, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(result), encoding="utf-8")
    print(
        json.dumps(
            {
                "json_output": str(args.json_output),
                "no_complement_blockers": result["summary"]["no_complement_blockers"],
                "report_output": str(args.report_output),
                "task_count": result["summary"]["task_count"],
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def analyze_coverage_gap(*, raw_path: Path, freeze_path: Path) -> dict[str, object]:
    freeze = json.loads(freeze_path.read_text(encoding="utf-8"))
    frozen_task_ids = [str(task_id) for task_id in freeze.get("task_ids", [])]
    rows_by_task: dict[str, list[dict[str, object]]] = defaultdict(list)
    for record in _read_jsonl(raw_path):
        task_id = _record_task_id(record)
        if task_id in frozen_task_ids and _dict(record.get("task_score")).get("details"):
            rows_by_task[task_id].append(record)
    tasks = [_analyze_task(task_id, rows_by_task.get(task_id, [])) for task_id in frozen_task_ids]
    return {
        "evidence_boundary": {
            "reason": (
                "Post-replay coverage diagnostic over held-out v2 candidate rows; "
                "used to design the next freeze, not to promote v2."
            ),
            "status": "held_out_multi_aspect_v2_coverage_gap",
        },
        "generated_by": "experiments/analyze_latent_aggregation_multi_aspect_v2_coverage_gap.py",
        "inputs": {"freeze": str(freeze_path), "raw": str(raw_path)},
        "schema": "latent_aggregation_multi_aspect_v2_coverage_gap.v1",
        "summary": _summary(tasks),
        "tasks": tasks,
    }


