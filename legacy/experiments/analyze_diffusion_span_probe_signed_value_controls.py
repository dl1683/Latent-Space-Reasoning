"""Analyze feature-family controls for the span-v4 signed-value head."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_SIGNED_VALUE = Path(
    "eval_results/diffusion_language/counterfactual_span_probe_signed_value_v4.json"
)
DEFAULT_JSON_OUTPUT = Path(
    "eval_results/diffusion_language/counterfactual_span_probe_signed_value_controls_v4.json"
)
DEFAULT_REPORT_OUTPUT = Path(
    "DIFFUSION_COUNTERFACTUAL_SPAN_PROBE_SIGNED_VALUE_CONTROLS_V4.md"
)
CONTROL_GROUPS = ("no_text", "no_source", "no_gap_span", "no_retention")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--signed-value", type=Path, default=DEFAULT_SIGNED_VALUE)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    result = analyze_signed_value_controls(signed_value_path=args.signed_value)
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(result, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(result), encoding="utf-8")
    print(
        json.dumps(
            {
                "control_count": len(result["matched_k_controls"]),
                "json_output": str(args.json_output),
                "report_output": str(args.report_output),
                "selected_model": result["selected_model"]["model_id"],
                "worst_matched_k_utility_delta": result["summary"][
                    "worst_matched_k_utility_delta"
                ],
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def analyze_signed_value_controls(*, signed_value_path: Path) -> dict[str, object]:
    payload = json.loads(signed_value_path.read_text(encoding="utf-8"))
    selected = _dict(payload.get("selected_model"))
    model_results = _list_of_dicts(payload.get("model_results"))
    selected_k = int(_float(selected.get("neighbor_count")))
    matched = []
    best_withheld = []
    for group_id in CONTROL_GROUPS:
        group_rows = [row for row in model_results if row.get("feature_group_id") == group_id]
        matched_row = _find_model(group_rows, neighbor_count=selected_k)
        if matched_row:
            matched.append(_control_row(group_id, "matched_k", matched_row, selected))
        if group_rows:
            best_row = max(
                group_rows,
                key=lambda row: (
                    _float(row.get("policy_utility")),
                    -_float(row.get("false_negative_count")),
                    -_float(row.get("false_positive_count")),
                ),
            )
            best_withheld.append(_control_row(group_id, "best_withheld", best_row, selected))
    return {
        "best_withheld_controls": best_withheld,
        "generated_by": "experiments/analyze_diffusion_span_probe_signed_value_controls.py",
        "inputs": {"signed_value": str(signed_value_path)},
        "matched_k_controls": matched,
        "schema": "diffusion_counterfactual_span_probe_signed_value_controls.v1",
        "selected_model": selected,
        "summary": _summary(matched=matched, best_withheld=best_withheld),
    }


def render_markdown(result: dict[str, object]) -> str:
    selected = _dict(result.get("selected_model"))
    summary = _dict(result.get("summary"))
    lines = [
        "# Diffusion Counterfactual Span Probe Signed Value Controls V4",
        "",
        (
            "This file is generated by "
            "`experiments/analyze_diffusion_span_probe_signed_value_controls.py`."
        ),
        (
            "It tests M2 from `archive/docs/DIFFUSION_MOONSHOT_REASONING_ARCHITECTURE_V1.md`: "
            "whether the selected signed-value head depends on the measured probe "
            "feature families rather than a slice artifact."
        ),
        "",
        "## Summary",
        "",
        f"- Selected model: `{selected.get('model_id', '')}`",
        f"- Selected utility: `{_format_float(selected.get('policy_utility'))}`",
        f"- Matched-k controls degraded: `{summary.get('matched_k_degraded_count', 0)}` / `{summary.get('matched_k_control_count', 0)}`",
        f"- Best withheld controls degraded: `{summary.get('best_withheld_degraded_count', 0)}` / `{summary.get('best_withheld_control_count', 0)}`",
        f"- Worst matched-k utility delta: `{_format_float(summary.get('worst_matched_k_utility_delta'))}`",
        "",
        "## Decision",
        "",
        (
            "M2 passes as a negative-control audit but does not promote the controller. "
            "Every feature-family removal degrades signed utility, and the best "
            "withheld-family alternatives also stay below the selected full-signature "
            "model. The signed-value improvement is therefore not explained by a "
            "single removable feature family, but M1 remains below its promotion bar."
        ),
        "",
        "## Matched-k Controls",
        "",
        "| Removed Feature Family | Model | Selected | FP | FN | Utility | Delta vs Selected | Verdict |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for row in _list_of_dicts(result.get("matched_k_controls")):
        lines.append(_control_table_row(row))
    lines.extend(
        [
            "",
            "## Best-Withheld Controls",
            "",
            "| Removed Feature Family | Model | Selected | FP | FN | Utility | Delta vs Selected | Verdict |",
            "| --- | --- | ---: | ---: | ---: | ---: | ---: | --- |",
        ]
    )
    for row in _list_of_dicts(result.get("best_withheld_controls")):
        lines.append(_control_table_row(row))
    lines.extend(
        [
            "",
            "## Reading",
            "",
            (
                "The selected full-signature model is still a boundary result, but "
                "the ablations are informative. Removing text features costs recall, "
                "removing source or retention admits additional false positives and "
                "misses positives, and removing gap/span weakens utility. That is the "
                "shape expected if the controller is using a distributed behavior "
                "signature rather than one brittle scalar."
            ),
        ]
    )
    return "\n".join(lines) + "\n"


def _control_row(
    group_id: str,
    control_type: str,
    row: dict[str, object],
    selected: dict[str, object],
) -> dict[str, object]:
    delta = _float(row.get("policy_utility")) - _float(selected.get("policy_utility"))
    return {
        "control_type": control_type,
        "feature_group_id": group_id,
        "false_negative_count": row.get("false_negative_count", 0),
        "false_positive_count": row.get("false_positive_count", 0),
        "model_id": row.get("model_id", ""),
        "neighbor_count": row.get("neighbor_count", 0),
        "policy_utility": row.get("policy_utility", 0.0),
        "selected_count": row.get("selected_count", 0),
        "utility_delta_vs_selected": delta,
        "verdict": "degraded" if delta < 0.0 else "not_degraded",
    }


def _summary(*, matched: list[dict[str, object]], best_withheld: list[dict[str, object]]) -> dict[str, object]:
    return {
        "best_withheld_control_count": len(best_withheld),
        "best_withheld_degraded_count": sum(
            1 for row in best_withheld if row.get("verdict") == "degraded"
        ),
        "matched_k_control_count": len(matched),
        "matched_k_degraded_count": sum(1 for row in matched if row.get("verdict") == "degraded"),
        "worst_matched_k_utility_delta": min(
            (_float(row.get("utility_delta_vs_selected")) for row in matched),
            default=0.0,
        ),
    }


def _find_model(rows: list[dict[str, object]], *, neighbor_count: int) -> dict[str, object]:
    for row in rows:
        if int(_float(row.get("neighbor_count"))) == neighbor_count:
            return row
    return {}


def _control_table_row(row: dict[str, object]) -> str:
    return (
        "| "
        f"`{row.get('feature_group_id', '')}` | "
        f"`{row.get('model_id', '')}` | "
        f"{int(_float(row.get('selected_count')))} | "
        f"{int(_float(row.get('false_positive_count')))} | "
        f"{int(_float(row.get('false_negative_count')))} | "
        f"{_format_float(row.get('policy_utility'))} | "
        f"{_format_float(row.get('utility_delta_vs_selected'))} | "
        f"`{row.get('verdict', '')}` |"
    )


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    if not isinstance(value, list):
        return []
    return [item for item in value if isinstance(item, dict)]


def _float(value: object) -> float:
    if value is None or value == "":
        return 0.0
    try:
        return float(value)
    except (TypeError, ValueError):
        return 0.0


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


if __name__ == "__main__":
    raise SystemExit(main())
