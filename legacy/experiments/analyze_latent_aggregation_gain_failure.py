def _analyze_task(task: dict[str, object], rows: list[dict[str, object]]) -> dict[str, object]:
    task_id = str(task.get("task_id", ""))
    best_single_trajectory_id = str(task.get("best_single_trajectory_id", ""))
    selected = _select_components(rows)
    selected_component_ids = {str(row.get("component_id", "")) for row in selected}
    best_component_ids = {
        str(row.get("component_id", ""))
        for row in rows
        if _is_best_single_source(str(row.get("trajectory_id", "")), best_single_trajectory_id)
        and _bool(row.get("supported"))
    }
    selected_from_best = selected_component_ids & best_component_ids
    selected_outside_best = selected_component_ids - best_component_ids
    outside_best_sources = {
        str(row.get("trajectory_id", ""))
        for row in selected
        if not _is_best_single_source(str(row.get("trajectory_id", "")), best_single_trajectory_id)
    }
    realized_score_lift = _float(task.get("realized_aggregate_score")) - _float(task.get("best_single_score"))
    component_gain = int(_float(task.get("component_gain")))
    decision_status = str(_dict(task.get("decision")).get("status", ""))
    return {
        "best_single_trajectory_id": best_single_trajectory_id,
        "component_gain": component_gain,
        "decision_status": decision_status,
        "diagnosis": _diagnosis(
            component_gain=component_gain,
            decision_status=decision_status,
            outside_best_sources=len(outside_best_sources),
            realized_score_lift=realized_score_lift,
            source_diversity=int(_float(task.get("source_diversity"))),
        ),
        "outside_best_source_count": len(outside_best_sources),
        "realized_score_lift": realized_score_lift,
        "score_lift_without_component_gain": realized_score_lift > EPSILON and component_gain <= 0,
        "selected_component_count": len(selected_component_ids),
        "selected_from_best_count": len(selected_from_best),
        "selected_outside_best_count": len(selected_outside_best),
        "source_diversity": int(_float(task.get("source_diversity"))),
        "task_id": task_id,
    }


def _diagnosis(
    *,
    component_gain: int,
    decision_status: str,
    outside_best_sources: int,
    realized_score_lift: float,
    source_diversity: int,
) -> str:
    if component_gain > 0:
        return "positive_component_gain"
    if decision_status == "online_components_good_but_realizer_failed":
        return "component_headroom_lost_in_realizer"
    if realized_score_lift > EPSILON and source_diversity > 1:
        return "score_lift_from_multi_source_but_no_new_components"
    if realized_score_lift > EPSILON:
        return "score_lift_from_best_single_reformatting"
    return "no_score_lift"


def _is_best_single_source(trajectory_id: str, best_single_trajectory_id: str) -> bool:
    return trajectory_id == best_single_trajectory_id or trajectory_id.startswith(
        f"{best_single_trajectory_id}:"
    )


def _summary(tasks: list[dict[str, object]]) -> dict[str, object]:
    score_lift_tasks = [task for task in tasks if _float(task.get("realized_score_lift")) > EPSILON]
    score_lift_without_gain = [
        task for task in score_lift_tasks if int(_float(task.get("component_gain"))) <= 0
    ]
    multi_source_without_gain = [
        task
        for task in tasks
        if int(_float(task.get("source_diversity"))) > 1 and int(_float(task.get("component_gain"))) <= 0
    ]
    return {
        "diagnosis_counts": _counts(str(task.get("diagnosis", "")) for task in tasks),
        "mean_realized_score_lift": _mean(_float(task.get("realized_score_lift")) for task in tasks),
        "multi_source_without_component_gain_task_count": len(multi_source_without_gain),
        "positive_component_gain_task_count": sum(1 for task in tasks if int(_float(task.get("component_gain"))) > 0),
        "realizer_failure_task_count": sum(
            1 for task in tasks if task.get("diagnosis") == "component_headroom_lost_in_realizer"
        ),
        "score_lift_task_count": len(score_lift_tasks),
        "score_lift_without_component_gain_task_count": len(score_lift_without_gain),
        "task_count": len(tasks),
    }


def _read_jsonl(path: Path) -> list[dict[str, object]]:
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            row = json.loads(line)
            if isinstance(row, dict):
                rows.append(row)
    return rows


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    return [item for item in value if isinstance(item, dict)] if isinstance(value, list) else []


def _float(value: object) -> float:
    if value is None:
        return 0.0
    return float(value)


def _bool(value: object) -> bool:
    return bool(value)


def _mean(values: object) -> float:
    items = list(values)
    return sum(items) / len(items) if items else 0.0


def _counts(values: object) -> dict[str, int]:
    counts: dict[str, int] = {}
    for value in values:
        counts[value] = counts.get(value, 0) + 1
    return dict(sorted(counts.items()))


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


def _format_counts(value: object) -> str:
    if not isinstance(value, dict) or not value:
        return "none"
    return ", ".join(f"{key}={value[key]}" for key in sorted(value))


