"""Analyze why aggregation score lift failed the component-gain gate."""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from experiments.analyze_latent_trajectory_aggregation import _select_components

DEFAULT_REPLAY = Path("eval_results/diffusion_language/latent_aggregation_inference_v1_threshold01_replay.json")
DEFAULT_COMPONENTS = Path("eval_results/diffusion_language/latent_aggregation_inference_v1_threshold01_components.jsonl")
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/latent_aggregation_gain_failure_threshold01.json")
DEFAULT_REPORT_OUTPUT = Path("docs/reports/diffusion/LATENT_AGGREGATION_GAIN_FAILURE_THRESHOLD01.md")
EPSILON = 1e-9


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--replay", type=Path, default=DEFAULT_REPLAY)
    parser.add_argument("--components", type=Path, default=DEFAULT_COMPONENTS)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    result = analyze_gain_failure(replay_path=args.replay, components_path=args.components)
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(result, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(result), encoding="utf-8")
    print(
        json.dumps(
            {
                "json_output": str(args.json_output),
                "report_output": str(args.report_output),
                "score_lift_without_component_gain_task_count": result["summary"][
                    "score_lift_without_component_gain_task_count"
                ],
                "task_count": result["summary"]["task_count"],
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def analyze_gain_failure(*, replay_path: Path, components_path: Path) -> dict[str, object]:
    replay = json.loads(replay_path.read_text(encoding="utf-8"))
    components = _read_jsonl(components_path)
    rows_by_task: dict[str, list[dict[str, object]]] = defaultdict(list)
    for row in components:
        task_id = str(row.get("task_id", ""))
        if task_id:
            rows_by_task[task_id].append(row)

    task_rows = [
        _analyze_task(task, rows_by_task.get(str(task.get("task_id", "")), []))
        for task in _list_of_dicts(replay.get("tasks"))
    ]
    return {
        "evidence_boundary": {
            "reason": "Diagnostic over the post-hoc threshold replay; use to design the next predeclared slice.",
            "status": "post_hoc_gain_failure_diagnostic",
        },
        "generated_by": "experiments/analyze_latent_aggregation_gain_failure.py",
        "inputs": {"components": str(components_path), "replay": str(replay_path)},
        "schema": "latent_aggregation_gain_failure.v1",
        "summary": _summary(task_rows),
        "tasks": task_rows,
    }


