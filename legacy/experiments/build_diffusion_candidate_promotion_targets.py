"""Build post-repair promotion targets for diffusion planning candidates."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_ALL_REPAIRABLE_SCORES = Path(
    "eval_results/diffusion_language/"
    "llada_moe_mixed_transfer_v5_all_repairable_frontier_v1_scores.json"
)
DEFAULT_ALL_REPAIRABLE_RAW = Path(
    "eval_results/diffusion_language/"
    "llada_moe_mixed_transfer_v5_all_repairable_frontier_v1_raw.jsonl"
)
DEFAULT_JSON_OUTPUT = Path(
    "eval_results/diffusion_language/diffusion_candidate_promotion_targets_v5.json"
)
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_CANDIDATE_PROMOTION_TARGETS_V5.md")
DEFAULT_LIFT_MIN = 1e-9


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--all-repairable-scores", type=Path, default=DEFAULT_ALL_REPAIRABLE_SCORES)
    parser.add_argument("--all-repairable-raw", type=Path, default=DEFAULT_ALL_REPAIRABLE_RAW)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--lift-min", type=float, default=DEFAULT_LIFT_MIN)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    targets = build_candidate_promotion_targets(
        raw_path=args.all_repairable_raw,
        scores_path=args.all_repairable_scores,
        lift_min=args.lift_min,
    )
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(targets, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(targets), encoding="utf-8")
    print(
        json.dumps(
            {
                "candidate_aware_promotion_error_count": _dict(targets.get("summary")).get(
                    "candidate_aware_promotion_error_count", 0
                ),
                "json_output": str(args.json_output),
                "positive_count": _dict(targets.get("summary")).get("positive_count", 0),
                "report_output": str(args.report_output),
                "target_count": _dict(targets.get("summary")).get("target_count", 0),
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def build_candidate_promotion_targets(
    *,
    raw_path: Path,
    scores_path: Path,
    lift_min: float = DEFAULT_LIFT_MIN,
) -> dict[str, object]:
    raw_rows = _read_jsonl(raw_path)
    scores = json.loads(scores_path.read_text(encoding="utf-8"))
    comparison_by_task = {
        str(row.get("task_id", "")): row for row in _list_of_dicts(scores.get("comparison_rows"))
    }
    rows = []
    for record in raw_rows:
        if str(record.get("generation_stage", "")) != "repair_candidate":
            continue
        task_id = _task_id(record)
        if not task_id.startswith("plan_"):
            continue
        comparison = comparison_by_task.get(task_id, {})
        rows.append(_target_row(record, comparison, lift_min=lift_min))
    rows.sort(key=lambda row: str(row.get("task_id", "")))
    return {
        "generated_by": "experiments/build_diffusion_candidate_promotion_targets.py",
        "inputs": {
            "all_repairable_raw": str(raw_path),
            "all_repairable_scores": str(scores_path),
        },
        "lift_min": lift_min,
        "rows": rows,
        "schema": "diffusion_candidate_promotion_targets.v1",
        "summary": _summary(rows),
    }


def render_markdown(targets: dict[str, object]) -> str:
    summary = _dict(targets.get("summary"))
    lines = [
        "# Diffusion Candidate Promotion Targets",
        "",
        "This file is generated by `experiments/build_diffusion_candidate_promotion_targets.py`.",
        (
            "It separates repair availability from post-repair promotion: labels are "
            "positive only when the generated repair candidate itself improves over "
            "the selected trajectory."
        ),
        "",
        "## Summary",
        "",
        f"- All-repairable raw: `{_dict(targets.get('inputs')).get('all_repairable_raw', '')}`",
        f"- All-repairable scores: `{_dict(targets.get('inputs')).get('all_repairable_scores', '')}`",
        f"- Target rows: `{summary.get('target_count', 0)}`",
        f"- Positive promotion rows: `{summary.get('positive_count', 0)}`",
        f"- Positive tasks: {_join_tasks(summary.get('positive_tasks'))}",
        f"- Negative tasks: {_join_tasks(summary.get('negative_tasks'))}",
        (
            "- Candidate-aware promotion errors: "
            f"`{summary.get('candidate_aware_promotion_error_count', 0)}`"
        ),
        (
            "- Candidate-aware selected tasks: "
            f"{_join_tasks(summary.get('candidate_aware_selected_tasks'))}"
        ),
        "",
        "## Rows",
        "",
        (
            "| Task | Promote | Candidate Lift | Source Lift | Planning Delta | "
            "Selector Edge | Gap Terms | Span Preservation | Span Score | Candidate-Aware | Error |"
        ),
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- | --- |",
    ]
    for row in _list_of_dicts(targets.get("rows")):
        lines.append(
            "| "
            f"`{row.get('task_id', '')}` | "
            f"{bool(row.get('promote_vs_trajectory'))} | "
            f"{_format_float(row.get('candidate_lift_vs_trajectory'))} | "
            f"{_format_float(row.get('candidate_lift_vs_source'))} | "
            f"{_format_float(row.get('planning_quality_delta_vs_source'))} | "
            f"{_format_float(row.get('repair_selector_edge'))} | "
            f"{int(row.get('prompt_gap_term_count', 0))} | "
            f"{_format_float(row.get('min_span_source_relative_preservation'))} | "
            f"{_format_float(row.get('max_span_target_score'))} | "
            f"{bool(row.get('candidate_aware_promotion_prediction'))} | "
            f"{bool(row.get('candidate_aware_promotion_error'))} |"
        )
    lines.extend(
        [
            "",
            "## Reading",
            "",
            (
                "The corrected boundary is a promotion boundary, not an "
                "availability boundary: labels are positive only when the generated "
                "repair candidate itself beats the selected trajectory. The named "
                "runner selector `candidate_aware_promotion_v1` is a post-repair "
                "policy alias for the seed-realization guarded planning score. "
                "Use this report beside the independent spend-transfer report to "
                "separate spend-gate errors from post-repair promotion errors."
            ),
        ]
    )
    return "\n".join(lines) + "\n"


def _target_row(
    record: dict[str, object],
    comparison: dict[str, object],
    *,
    lift_min: float,
) -> dict[str, object]:
    repair = _dict(record.get("repair"))
    task_id = _task_id(record)
    source_task_score = _float(repair.get("source_task_score"))
    trajectory_task_score = _float(comparison.get("trajectory_task_score"))
    repair_task_score = _float(_dict(record.get("task_score")).get("score"))
    candidate_lift_vs_trajectory = repair_task_score - trajectory_task_score
    candidate_lift_vs_source = repair_task_score - source_task_score
    selected_repair_lift = _float(comparison.get("repair_delta_vs_evolved"))
    promote = candidate_lift_vs_trajectory > lift_min
    candidate_aware_prediction = selected_repair_lift > lift_min
    span_scores = _list_of_dicts(repair.get("planning_span_target_scores"))
    return {
        "candidate_aware_promotion_error": candidate_aware_prediction != promote,
        "candidate_aware_promotion_prediction": candidate_aware_prediction,
        "candidate_lift_vs_source": candidate_lift_vs_source,
        "candidate_lift_vs_trajectory": candidate_lift_vs_trajectory,
        "candidate_task_score": repair_task_score,
        "max_span_target_score": max((_float(row.get("score")) for row in span_scores), default=0.0),
        "min_span_source_relative_preservation": min(
            (_float(row.get("source_relative_preservation")) for row in span_scores),
            default=0.0,
        ),
        "planning_quality_delta_vs_source": _float(record.get("planning_quality_score"))
        - _float(repair.get("source_planning_quality_score")),
        "planning_quality_score": _float(record.get("planning_quality_score")),
        "promote_vs_source": candidate_lift_vs_source > lift_min,
        "promote_vs_trajectory": promote,
        "prompt_gap_term_count": len(_list(repair.get("prompt_constraint_gap_terms"))),
        "repair": str(repair.get("name", "")),
        "repair_selector_edge": _float(comparison.get("repair_selector_edge")),
        "repair_selector_score": _float(comparison.get("repair_selector_score")),
        "selected_repair_lift": selected_repair_lift,
        "source_planning_quality_score": _float(repair.get("source_planning_quality_score")),
        "source_task_score": source_task_score,
        "task_id": task_id,
        "trajectory_task_score": trajectory_task_score,
    }


def _summary(rows: list[dict[str, object]]) -> dict[str, object]:
    positives = [row for row in rows if row.get("promote_vs_trajectory")]
    negatives = [row for row in rows if not row.get("promote_vs_trajectory")]
    return {
        "candidate_aware_promotion_error_count": sum(
            int(row.get("candidate_aware_promotion_error", False)) for row in rows
        ),
        "candidate_aware_selected_tasks": [
            str(row.get("task_id", ""))
            for row in rows
            if row.get("candidate_aware_promotion_prediction")
        ],
        "negative_count": len(negatives),
        "negative_tasks": [str(row.get("task_id", "")) for row in negatives],
        "positive_count": len(positives),
        "positive_tasks": [str(row.get("task_id", "")) for row in positives],
        "target_count": len(rows),
    }


def _read_jsonl(path: Path) -> list[dict[str, object]]:
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        row = json.loads(line)
        if isinstance(row, dict):
            rows.append(row)
    return rows


def _task_id(record: dict[str, object]) -> str:
    task = record.get("task")
    if isinstance(task, dict):
        task_id = task.get("task_id")
        if task_id:
            return str(task_id)
    return str(record.get("task_id", ""))


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list(value: object) -> list[object]:
    return value if isinstance(value, list) else []


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    return [row for row in value if isinstance(row, dict)] if isinstance(value, list) else []


def _float(value: object) -> float:
    if value is None:
        return 0.0
    return float(value)


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


def _join_tasks(value: object) -> str:
    values = [str(item) for item in value] if isinstance(value, list) else []
    return ", ".join(f"`{item}`" for item in values) if values else "`none`"


if __name__ == "__main__":
    raise SystemExit(main())
