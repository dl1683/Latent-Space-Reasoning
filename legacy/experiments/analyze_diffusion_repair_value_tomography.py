def _score_probe(probe: dict[str, object], targets: list[dict[str, object]]) -> dict[str, object]:
    selected = [target for target in targets if _policy_selects(target, probe)]
    oracle = [target for target in targets if _oracle_selects(target, probe)]
    selected_ids = {str(target.get("task_id", "")) for target in selected}
    oracle_ids = {str(target.get("task_id", "")) for target in oracle}
    false_positive_ids = sorted(selected_ids - oracle_ids)
    false_negative_ids = sorted(oracle_ids - selected_ids)
    regret = _oracle_utility(targets, probe) - _policy_utility(targets, probe)
    row = {
        "cost_penalty_lambda": _float(probe.get("cost_penalty_lambda")),
        "expected_behavior": str(probe.get("expected_behavior", "")),
        "false_negative_count": len(false_negative_ids),
        "false_negative_tasks": false_negative_ids,
        "false_positive_count": len(false_positive_ids),
        "false_positive_tasks": false_positive_ids,
        "oracle_tasks": sorted(oracle_ids),
        "policy_utility": _policy_utility(targets, probe),
        "probe_id": str(probe.get("probe_id", "")),
        "probe_type": str(probe.get("probe_type", "")),
        "prompt_gap_max": int(_float(probe.get("prompt_gap_max"), default=999.0)),
        "regret_vs_oracle": regret,
        "selected_tasks": sorted(selected_ids),
        "source_quality_max": _float(probe.get("source_quality_max")),
    }
    row["passed"] = _probe_passed(row)
    row["interpretation"] = _interpretation(row)
    return row


def _task_signature(target: dict[str, object], probes: list[dict[str, object]]) -> dict[str, object]:
    bits = []
    for probe in probes:
        bits.append("S" if _policy_selects(target, probe) else "-")
    return {
        "break_even_lambda": _float(target.get("break_even_lambda")),
        "first_repairable_step": _optional_int(target.get("first_repairable_step")),
        "prompt_gap_count": _optional_int(target.get("prompt_gap_count")),
        "signature": "".join(bits),
        "source_quality": _optional_float(target.get("source_quality")),
        "task_id": str(target.get("task_id", "")),
    }


def _policy_selects(target: dict[str, object], probe: dict[str, object]) -> bool:
    first_step = _optional_int(target.get("first_repairable_step"))
    if first_step is None:
        return False
    if not bool(target.get("source_needs_repair")):
        return False
    if _float(target.get("prompt_gap_count"), default=999.0) > _float(probe.get("prompt_gap_max"), default=999.0):
        return False
    return _float(target.get("source_quality"), default=1.0) <= _float(probe.get("source_quality_max"), default=0.31)


def _oracle_selects(target: dict[str, object], probe: dict[str, object]) -> bool:
    return _target_utility(target, probe) > 0.0


def _target_utility(target: dict[str, object], probe: dict[str, object]) -> float:
    return _float(target.get("aggregate_score_lift")) - _float(probe.get("cost_penalty_lambda")) * _float(
        target.get("marginal_relative_cost")
    )


def _policy_utility(targets: list[dict[str, object]], probe: dict[str, object]) -> float:
    return sum(_target_utility(target, probe) for target in targets if _policy_selects(target, probe))


def _oracle_utility(targets: list[dict[str, object]], probe: dict[str, object]) -> float:
    return sum(max(0.0, _target_utility(target, probe)) for target in targets)


def _probe_passed(row: dict[str, object]) -> bool:
    probe_type = str(row.get("probe_type", ""))
    if probe_type in {"baseline", "invariance", "implemented_controller"}:
        return _float(row.get("regret_vs_oracle")) <= 1e-9
    return bool(row.get("false_positive_count") or row.get("false_negative_count"))


def _interpretation(row: dict[str, object]) -> str:
    probe_type = str(row.get("probe_type", ""))
    fp = _list(row.get("false_positive_tasks"))
    fn = _list(row.get("false_negative_tasks"))
    if probe_type in {"baseline", "invariance"} and row.get("passed"):
        return "stable at the incumbent decision surface"
    if probe_type == "sensitivity":
        if fp:
            return "threshold loosening admits known no-lift or low-utility spends"
        if fn:
            return "threshold tightening drops a useful boundary repair"
    if probe_type == "cost_sensitivity":
        if fn:
            return "controller is too conservative for this cost regime"
        if fp:
            return "controller is too spend-happy for this cost regime"
    if probe_type == "implemented_controller" and row.get("passed"):
        return "implemented lambda-aware schedule matches the oracle surface"
    return "probe did not expose the expected behavior"


def _summary(
    probe_rows: list[dict[str, object]],
    implemented_controller_rows: list[dict[str, object]],
) -> dict[str, object]:
    worst = max(probe_rows, key=lambda row: _float(row.get("regret_vs_oracle")), default={})
    implemented_worst = max(
        implemented_controller_rows,
        key=lambda row: _float(row.get("regret_vs_oracle")),
        default={},
    )
    incumbent_stable = all(
        row.get("passed") and _float(row.get("regret_vs_oracle")) <= 1e-9
        for row in probe_rows
        if row.get("probe_type") in {"baseline", "invariance"}
    )
    implemented_controller_zero_regret = all(
        row.get("passed") and _float(row.get("regret_vs_oracle")) <= 1e-9
        for row in implemented_controller_rows
    )
    any_nonzero_probe_regret = any(_float(row.get("regret_vs_oracle")) > 1e-9 for row in probe_rows)
    return {
        "incumbent_stable": incumbent_stable,
        "implemented_controller_probe_count": len(implemented_controller_rows),
        "implemented_controller_zero_regret": implemented_controller_zero_regret,
        "implemented_controller_worst_probe_id": str(implemented_worst.get("probe_id", "")),
        "implemented_controller_worst_regret": _float(implemented_worst.get("regret_vs_oracle")),
        "next_controller_required": any_nonzero_probe_regret,
        "passed_probe_count": sum(1 for row in probe_rows if row.get("passed")),
        "probe_count": len(probe_rows),
        "worst_probe_id": str(worst.get("probe_id", "")),
        "worst_regret": _float(worst.get("regret_vs_oracle")),
    }


def _load_jsonl(path: Path) -> list[dict[str, object]]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def _dict(value) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list(value) -> list[object]:
    return value if isinstance(value, list) else []


def _list_of_dicts(value) -> list[dict[str, object]]:
    return [item for item in _list(value) if isinstance(item, dict)]


def _float(value, *, default: float = 0.0) -> float:
    if value is None:
        return default
    try:
        number = float(value)
    except (TypeError, ValueError):
        return default
    if math.isnan(number) or math.isinf(number):
        return default
    return number


def _optional_float(value) -> float | None:
    if value is None:
        return None
    return _float(value)


def _optional_int(value) -> int | None:
    if value is None:
        return None
    return int(_float(value))


def _format_float(value) -> str:
    return f"{_float(value):.6f}"


def _format_optional(value) -> str:
    if value is None:
        return ""
    if isinstance(value, int):
        return str(value)
    return _format_float(value)


def _join_tasks(value) -> str:
    tasks = [str(item) for item in _list(value)]
    return ", ".join(tasks) if tasks else "`none`"


