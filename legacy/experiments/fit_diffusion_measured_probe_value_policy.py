"""Fit Stage 1 repair rules over measured counterfactual micro-probe rows."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_TARGETS = Path("eval_results/diffusion_language/diffusion_counterfactual_probe_targets_v1.json")
DEFAULT_SCORES = Path("eval_results/diffusion_language/counterfactual_micro_probe_counterexamples_all_v1_scores.json")
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/counterfactual_measured_probe_value_policy_v1.json")
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_COUNTERFACTUAL_MEASURED_PROBE_VALUE_POLICY_V1.md")

MEASURED_FEATURES = (
    "measured_probe_value_prediction",
    "measured_expected_gap_visibility_gain",
    "measured_expected_realization_defect_visibility",
    "measured_expected_span_evidence_gain",
    "measured_expected_retention_risk_visibility",
)
PREPROBE_FEATURES = (
    "prompt_gap_count",
    "source_quality",
    "would_probe_score",
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--targets", type=Path, default=DEFAULT_TARGETS)
    parser.add_argument("--scores", type=Path, default=DEFAULT_SCORES)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    fit = fit_measured_probe_value_policy(
        scores_path=args.scores,
        targets_path=args.targets,
    )
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(fit, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(fit), encoding="utf-8")
    print(
        json.dumps(
            {
                "best_all_rule": fit["summary"]["best_all_rule_name"],
                "best_measured_only_rule": fit["summary"]["best_measured_only_rule_name"],
                "gate_decision": fit["summary"]["gate_decision"],
                "measured_only_errors": fit["summary"]["best_measured_only_error_count"],
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def fit_measured_probe_value_policy(
    *,
    scores_path: Path,
    targets_path: Path,
) -> dict[str, object]:
    scores = json.loads(scores_path.read_text(encoding="utf-8"))
    targets = json.loads(targets_path.read_text(encoding="utf-8"))
    target_rows = {
        str(row.get("task_id", "")): row
        for row in _list_of_dicts(targets.get("rows"))
    }
    rows = [
        _row_from_gate_row(row, target_rows.get(str(row.get("task_id", "")), {}))
        for row in _list_of_dicts(scores.get("repair_spend_gate_rows"))
        if row.get("counterfactual_probe_observation") == "measured_generation"
    ]
    rows.sort(key=lambda row: str(row.get("task_id", "")))
    measured_rules = _rank_rules(rows, MEASURED_FEATURES)
    all_rules = _rank_rules(rows, (*MEASURED_FEATURES, *PREPROBE_FEATURES))
    measured_best = measured_rules[0] if measured_rules else _empty_rule()
    all_best = all_rules[0] if all_rules else _empty_rule()
    return {
        "generated_by": "experiments/fit_diffusion_measured_probe_value_policy.py",
        "inputs": {
            "scores": str(scores_path),
            "targets": str(targets_path),
        },
        "rows": _rows_with_decisions(rows, measured_best, all_best),
        "schema": "diffusion_counterfactual_measured_probe_value_policy.v1",
        "summary": _summary(rows, measured_best, all_best, scores),
        "top_all_rules": all_rules[:20],
        "top_measured_only_rules": measured_rules[:20],
    }


