def _load_jsonl(path: Path) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            rows.append(json.loads(line))
    return rows


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    return [row for row in value if isinstance(row, dict)] if isinstance(value, list) else []


def _list_of_strings(value: object) -> list[str]:
    return [str(item) for item in value] if isinstance(value, list) else []


def _task_ids(rows: list[dict[str, object]]) -> list[str]:
    return [str(row.get("task_id", "")) for row in rows if row.get("task_id")]


def _float(value: object) -> float:
    if value is None:
        return 0.0
    return float(value)


def _int(value: object) -> int:
    return int(_float(value))


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


def _format_optional(value: object) -> str:
    if value is None:
        return ""
    return _format_float(value)


def _join_tasks(value: object) -> str:
    tasks = _list_of_strings(value)
    return ", ".join(f"`{task}`" for task in tasks) if tasks else "`none`"


