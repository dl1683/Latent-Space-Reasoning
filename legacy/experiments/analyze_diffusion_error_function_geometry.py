"""Derive error-function geometry assertions from diffusion repair targets."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from statistics import mean

DEFAULT_REPAIR_VALUE_GEOMETRY = Path(
    "eval_results/diffusion_language/diffusion_repair_value_geometry.json"
)
DEFAULT_PHASE_SOURCE_TARGETS = Path(
    "eval_results/diffusion_language/diffusion_phase_hybrid_loss_targets.jsonl"
)
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/diffusion_error_function_geometry.json")
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_ERROR_FUNCTION_GEOMETRY.md")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repair-value-geometry", type=Path, default=DEFAULT_REPAIR_VALUE_GEOMETRY)
    parser.add_argument("--phase-source-targets", type=Path, default=DEFAULT_PHASE_SOURCE_TARGETS)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    audit = build_error_function_geometry(
        repair_value_geometry_path=args.repair_value_geometry,
        phase_source_targets_path=args.phase_source_targets,
    )
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(audit, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(audit), encoding="utf-8")
    print(
        json.dumps(
            {
                "assertion_count": len(_list_of_dicts(audit.get("assertions"))),
                "json_output": str(args.json_output),
                "report_output": str(args.report_output),
                "repair_value_policy_regret": _float(
                    _dict(audit.get("repair_value_geometry")).get("runner_policy_regret")
                ),
                "source_naive_false_positive_count": _int(
                    _dict(audit.get("source_trust_geometry")).get(
                        "naive_repairable_history_false_positive_count"
                    )
                ),
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def build_error_function_geometry(
    *,
    repair_value_geometry_path: Path,
    phase_source_targets_path: Path,
) -> dict[str, object]:
    repair_value = json.loads(repair_value_geometry_path.read_text(encoding="utf-8"))
    value_rows = _list_of_dicts(repair_value.get("coordinate_rows"))
    source_rows = _load_jsonl(phase_source_targets_path)
    repair_summary = _repair_value_summary(repair_value, value_rows)
    source_summary = _source_trust_summary(source_rows)
    assertions = _assertions(repair_summary=repair_summary, source_summary=source_summary)
    return {
        "assertions": assertions,
        "candidate_error_functions": _candidate_error_functions(),
        "generated_by": "experiments/analyze_diffusion_error_function_geometry.py",
        "inputs": {
            "phase_source_targets": str(phase_source_targets_path),
            "repair_value_geometry": str(repair_value_geometry_path),
        },
        "repair_value_geometry": repair_summary,
        "schema": "diffusion_error_function_geometry.v1",
        "source_trust_geometry": source_summary,
    }


def render_markdown(audit: dict[str, object]) -> str:
    repair = _dict(audit.get("repair_value_geometry"))
    source = _dict(audit.get("source_trust_geometry"))
    lines = [
        "# Diffusion Error-Function Geometry",
        "",
        "This file is generated by `experiments/analyze_diffusion_error_function_geometry.py`.",
        (
            "It turns the current diffusion repair rows into explicit mathematical "
            "claims about which error functions should be optimized next."
        ),
        "",
        "## Inputs",
        "",
        f"- Repair-value geometry: `{_dict(audit.get('inputs')).get('repair_value_geometry', '')}`",
        f"- Phase-source targets: `{_dict(audit.get('inputs')).get('phase_source_targets', '')}`",
        "",
        "## Derived Assertions",
        "",
        "| ID | Assertion | Evidence | Error-Function Consequence |",
        "| --- | --- | --- | --- |",
    ]
    for row in _list_of_dicts(audit.get("assertions")):
        lines.append(
            "| "
            f"`{row.get('id', '')}` | "
            f"{row.get('assertion', '')} | "
            f"{row.get('evidence', '')} | "
            f"{row.get('consequence', '')} |"
        )
    lines.extend(
        [
            "",
            "## Repair-Value Geometry",
            "",
            f"- Cost penalty lambda: `{_format_float(repair.get('cost_penalty_lambda'))}`",
            f"- Raw positive repair targets: `{repair.get('raw_positive_repair_target_count', 0)}`",
            f"- Cost-profitable repair targets: `{repair.get('cost_profitable_repair_count', 0)}`",
            f"- Cost flips: {_join_tasks(repair.get('cost_flip_tasks'))}",
            f"- Early-step mixed-sign tasks: {_join_tasks(repair.get('early_step_mixed_sign_tasks'))}",
            f"- Runner value-policy regret: `{_format_float(repair.get('runner_policy_regret'))}`",
            f"- Runner value-policy selected tasks: {_join_tasks(repair.get('runner_selected_tasks'))}",
            "",
            "## Source-Trust Geometry",
            "",
            f"- Source-choice targets: `{source.get('target_count', 0)}`",
            f"- Trust-history positives: `{source.get('trust_history_count', 0)}`",
            f"- Preserve-final targets: `{source.get('preserve_final_count', 0)}`",
            (
                "- Naive repairable-history false positives: "
                f"`{source.get('naive_repairable_history_false_positive_count', 0)}`"
            ),
            (
                "- Any-safe-history false positives: "
                f"`{source.get('any_safe_history_false_positive_count', 0)}`"
            ),
            f"- Mean retention-safety lag: `{_format_optional(source.get('mean_retention_safety_lag'))}`",
            "",
            "## Candidate Error Functions",
            "",
        ]
    )
    for row in _list_of_dicts(audit.get("candidate_error_functions")):
        lines.extend(
            [
                f"### {row.get('name', '')}",
                "",
                f"`{row.get('formula', '')}`",
                "",
                str(row.get("purpose", "")),
                "",
                f"Current evidence: {row.get('evidence', '')}",
                "",
                f"Next test: {row.get('next_test', '')}",
                "",
            ]
        )
    return "\n".join(lines).rstrip() + "\n"


def _repair_value_summary(
    repair_value: dict[str, object],
    rows: list[dict[str, object]],
) -> dict[str, object]:
    raw_positive = [row for row in rows if _float(row.get("aggregate_score_lift")) > 0.0]
    profitable = [row for row in rows if bool(row.get("profitable"))]
    cost_flips = [
        row
        for row in rows
        if _float(row.get("aggregate_score_lift")) > 0.0 and not bool(row.get("profitable"))
    ]
    early_step = min(
        (_float(row.get("first_repairable_step")) for row in rows if row.get("first_repairable_step")),
        default=0.0,
    )
    early_rows = [
        row for row in rows if _float(row.get("first_repairable_step")) == early_step
    ]
    early_signs = {bool(row.get("profitable")) for row in early_rows}
    runner = _dict(repair_value.get("runner_policy"))
    return {
        "cost_flip_tasks": _task_ids(cost_flips),
        "cost_penalty_lambda": _float(repair_value.get("cost_penalty_lambda")),
        "cost_profitable_repair_count": len(profitable),
        "early_step": early_step,
        "early_step_has_mixed_value": len(early_signs) > 1,
        "early_step_mixed_sign_tasks": _task_ids(early_rows),
        "raw_positive_repair_target_count": len(raw_positive),
        "runner_policy_regret": _float(runner.get("regret_vs_oracle")),
        "runner_selected_tasks": _list_of_strings(runner.get("selected_tasks")),
        "source_quality_band_gap": _dict(repair_value.get("summary")).get(
            "source_quality_band_gap"
        ),
    }


def _source_trust_summary(rows: list[dict[str, object]]) -> dict[str, object]:
    trust_rows = [row for row in rows if row.get("target_action") == "trust_history_source"]
    preserve_rows = [row for row in rows if row.get("target_action") == "preserve_final_source"]
    repairable_history_false_positives = [
        row
        for row in preserve_rows
        if _float(row.get("phase_repairable_count")) > 0.0
    ]
    any_safe_false_positives = [
        row
        for row in preserve_rows
        if _float(row.get("phase_safe_repairable_count")) > 0.0
    ]
    safety_lags = [
        _float(row.get("phase_retention_safety_lag"))
        for row in rows
        if row.get("phase_retention_safety_lag") is not None
    ]
    return {
        "any_safe_history_false_positive_count": len(any_safe_false_positives),
        "any_safe_history_false_positive_tasks": _task_ids(any_safe_false_positives),
        "mean_retention_safety_lag": mean(safety_lags) if safety_lags else None,
        "naive_repairable_history_false_positive_count": len(
            repairable_history_false_positives
        ),
        "naive_repairable_history_false_positive_tasks": _task_ids(
            repairable_history_false_positives
        ),
        "preserve_final_count": len(preserve_rows),
        "target_count": len(rows),
        "trust_history_count": len(trust_rows),
        "trust_history_tasks": _task_ids(trust_rows),
    }


