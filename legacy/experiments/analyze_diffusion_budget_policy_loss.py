"""Build a cost-aware repair-budget policy loss from the phase-window map."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from statistics import mean

DEFAULT_BUDGET_MAP = Path("eval_results/diffusion_language/diffusion_phase_window_budget_map.json")
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/diffusion_budget_policy_loss.json")
DEFAULT_TARGETS_OUTPUT = Path("eval_results/diffusion_language/diffusion_budget_policy_loss_targets.jsonl")
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_BUDGET_POLICY_LOSS.md")
DEFAULT_COST_PENALTIES = (0.0, 0.05, 0.10, 0.15, 0.18, 0.20, 0.25, 0.28, 0.30)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--budget-map", type=Path, default=DEFAULT_BUDGET_MAP)
    parser.add_argument(
        "--cost-penalties",
        default=",".join(str(value) for value in DEFAULT_COST_PENALTIES),
        help="Comma-separated lambda values for score - lambda * relative_cost policy sweeps.",
    )
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--targets-output", type=Path, default=DEFAULT_TARGETS_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    cost_penalties = tuple(
        float(value.strip()) for value in args.cost_penalties.split(",") if value.strip()
    )
    audit = build_budget_policy_loss(
        budget_map_path=args.budget_map,
        cost_penalties=cost_penalties,
    )
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.targets_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(audit, indent=2, sort_keys=True), encoding="utf-8")
    args.targets_output.write_text(
        "\n".join(json.dumps(row, sort_keys=True) for row in _list_of_dicts(audit.get("target_rows"))) + "\n",
        encoding="utf-8",
    )
    args.report_output.write_text(render_markdown(audit), encoding="utf-8")
    print(
        json.dumps(
            {
                "json_output": str(args.json_output),
                "report_output": str(args.report_output),
                "target_count": len(_list_of_dicts(audit.get("target_rows"))),
                "targets_output": str(args.targets_output),
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def build_budget_policy_loss(
    *,
    budget_map_path: Path,
    cost_penalties: tuple[float, ...] = DEFAULT_COST_PENALTIES,
) -> dict[str, object]:
    budget_map = _read_json(budget_map_path)
    planning_task_count = len(_list_of_dicts(budget_map.get("task_rows")))
    repair_generation_budget = _float(budget_map.get("repair_generation_budget"), default=1.0)
    marginal_relative_cost = repair_generation_budget / planning_task_count if planning_task_count else 0.0
    target_rows = _target_rows(
        budget_map,
        planning_task_count=planning_task_count,
        marginal_relative_cost=marginal_relative_cost,
    )
    transition_rows = _transition_value_rows(budget_map)
    cap_policy_rows = _cap_policy_rows(transition_rows, cost_penalties=cost_penalties)
    task_policy_rows = _task_policy_rows(
        target_rows,
        transition_rows,
        cap_policy_rows=cap_policy_rows,
        cost_penalties=cost_penalties,
        marginal_relative_cost=marginal_relative_cost,
    )
    return {
        "budget_map_path": str(budget_map_path),
        "cap_policy_rows": cap_policy_rows,
        "cost_penalties": list(cost_penalties),
        "generated_by": "experiments/analyze_diffusion_budget_policy_loss.py",
        "marginal_relative_cost_per_repair": marginal_relative_cost,
        "planning_task_count": planning_task_count,
        "repair_generation_budget": repair_generation_budget,
        "schema": "diffusion_budget_policy_loss.v1",
        "summary": _summary(target_rows, transition_rows, task_policy_rows),
        "target_rows": target_rows,
        "task_policy_rows": task_policy_rows,
        "transition_value_rows": transition_rows,
    }


