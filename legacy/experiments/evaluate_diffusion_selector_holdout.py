"""Evaluate decomposed diffusion selector heads with leave-one-task-out tests."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

try:
    from experiments import fit_diffusion_composite_selector as fit_selector
except ModuleNotFoundError:  # pragma: no cover - direct script execution path
    import fit_diffusion_composite_selector as fit_selector

DEFAULT_TARGETS = Path("eval_results/diffusion_language/diffusion_composite_selector_targets.json")
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/diffusion_selector_holdout_eval.json")
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_SELECTOR_HOLDOUT_EVAL.md")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--targets", type=Path, default=DEFAULT_TARGETS)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    evaluation = evaluate_selector_holdout(targets_path=args.targets)
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(evaluation, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(evaluation), encoding="utf-8")
    print(
        json.dumps(
            {
                "decomposed_error_count": _dict(evaluation.get("summary")).get(
                    "decomposed_error_count", 0
                ),
                "json_output": str(args.json_output),
                "report_output": str(args.report_output),
                "single_label_error_count": _dict(evaluation.get("summary")).get(
                    "single_label_error_count", 0
                ),
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def evaluate_selector_holdout(*, targets_path: Path) -> dict[str, object]:
    dataset = json.loads(targets_path.read_text(encoding="utf-8"))
    task_rows = _list_of_dicts(dataset.get("task_targets"))
    holdout_rows = [_evaluate_holdout_row(task_rows, holdout_index=i) for i in range(len(task_rows))]
    return {
        "baseline": {
            "description": (
                "single repairability controller predicts every head from "
                "first_repairable_step existence"
            ),
            "rule_id": "single_first_repairable_exists",
        },
        "generated_by": "experiments/evaluate_diffusion_selector_holdout.py",
        "holdout_rows": holdout_rows,
        "inputs": {"targets": str(targets_path)},
        "schema": "diffusion_selector_holdout_eval.v1",
        "summary": _summary(holdout_rows),
    }


def render_markdown(evaluation: dict[str, object]) -> str:
    summary = _dict(evaluation.get("summary"))
    lines = [
        "# Diffusion Selector Holdout Evaluation",
        "",
        "This file is generated by `experiments/evaluate_diffusion_selector_holdout.py`.",
        (
            "It performs leave-one-task-out evaluation on the current composite target "
            "surface and compares the decomposed selector heads against a single "
            "repairability controller."
        ),
        "",
        "## Summary",
        "",
        f"- Holdout tasks: `{summary.get('holdout_task_count', 0)}`",
        f"- Scored labels: `{summary.get('scored_label_count', 0)}`",
        f"- Decomposed selector errors: `{summary.get('decomposed_error_count', 0)}`",
        f"- Single-label repairability errors: `{summary.get('single_label_error_count', 0)}`",
        f"- Absolute error reduction: `{summary.get('absolute_error_reduction', 0)}`",
        f"- Relative error reduction: `{_format_float(summary.get('relative_error_reduction'))}`",
        "",
        "## Holdout Rows",
        "",
        (
            "| Held-Out Task | Labels | Decomposed Errors | Single-Label Errors | "
            "Spend Rule | Source Rule | Retention Rule |"
        ),
        "| --- | ---: | ---: | ---: | --- | --- | --- |",
    ]
    for row in _list_of_dicts(evaluation.get("holdout_rows")):
        lines.append(
            "| "
            f"`{row.get('task_id', '')}` | "
            f"{row.get('scored_label_count', 0)} | "
            f"{row.get('decomposed_error_count', 0)} | "
            f"{row.get('single_label_error_count', 0)} | "
            f"`{row.get('spend_rule_id', '')}` | "
            f"`{row.get('source_rule_id', '')}` | "
            f"`{row.get('retention_rule_id', '')}` |"
        )
    lines.extend(
        [
            "",
            "## Reading",
            "",
            (
                "This is still a local transfer test, not a full benchmark. The key result "
                "is that the four-head decomposition preserves most of its advantage when "
                "each task is hidden from fitting, while the single repairability signal "
                "over-promotes source trust and retention safety."
            ),
        ]
    )
    return "\n".join(lines) + "\n"


def _evaluate_holdout_row(rows: list[dict[str, object]], *, holdout_index: int) -> dict[str, object]:
    holdout = rows[holdout_index]
    train_rows = rows[:holdout_index] + rows[holdout_index + 1 :]
    spend_head = fit_selector._fit_binary_head(  # noqa: SLF001
        fit_selector._spend_rules(train_rows),  # noqa: SLF001
        train_rows,
        label_field="spend_repair_label",
        unlabeled_value=None,
    )
    source_head = fit_selector._fit_binary_head(  # noqa: SLF001
        fit_selector._source_rules(train_rows),  # noqa: SLF001
        train_rows,
        label_field="source_trust_history_label",
        unlabeled_value=None,
    )
    retention_head = fit_selector._fit_binary_head(  # noqa: SLF001
        fit_selector._retention_rules(train_rows),  # noqa: SLF001
        train_rows,
        label_field="retention_safe_history_label",
        unlabeled_value=None,
    )
    label_results = [
        _score_label(
            holdout,
            head=spend_head,
            label_field="spend_repair_label",
            label_name="spend",
        ),
        _score_label(
            holdout,
            head=source_head,
            label_field="source_trust_history_label",
            label_name="source",
        ),
        _score_label(
            holdout,
            head=retention_head,
            label_field="retention_safe_history_label",
            label_name="retention",
        ),
    ]
    scored = [row for row in label_results if row.get("scored")]
    return {
        "decomposed_error_count": sum(int(row.get("decomposed_error", False)) for row in scored),
        "label_results": label_results,
        "retention_rule_id": str(retention_head.get("rule_id", "")),
        "schema": "diffusion_selector_holdout_task_eval.v1",
        "scored_label_count": len(scored),
        "single_label_error_count": sum(int(row.get("single_label_error", False)) for row in scored),
        "source_rule_id": str(source_head.get("rule_id", "")),
        "spend_rule_id": str(spend_head.get("rule_id", "")),
        "task_id": str(holdout.get("task_id", "")),
        "train_task_count": len(train_rows),
    }


def _score_label(
    row: dict[str, object],
    *,
    head: dict[str, object],
    label_field: str,
    label_name: str,
) -> dict[str, object]:
    label = row.get(label_field)
    if label is None:
        return {
            "label": None,
            "label_name": label_name,
            "scored": False,
        }
    target = bool(label)
    decomposed_prediction = fit_selector._predict_rule(head, row)  # noqa: SLF001
    single_prediction = row.get("first_repairable_step") is not None
    return {
        "decomposed_error": decomposed_prediction != target,
        "decomposed_prediction": decomposed_prediction,
        "label": target,
        "label_name": label_name,
        "scored": True,
        "single_label_error": single_prediction != target,
        "single_label_prediction": single_prediction,
    }


def _summary(rows: list[dict[str, object]]) -> dict[str, object]:
    decomposed_errors = sum(int(row.get("decomposed_error_count", 0)) for row in rows)
    single_errors = sum(int(row.get("single_label_error_count", 0)) for row in rows)
    scored_labels = sum(int(row.get("scored_label_count", 0)) for row in rows)
    absolute_reduction = single_errors - decomposed_errors
    return {
        "absolute_error_reduction": absolute_reduction,
        "decomposed_error_count": decomposed_errors,
        "decomposed_error_rate": decomposed_errors / scored_labels if scored_labels else 0.0,
        "holdout_task_count": len(rows),
        "relative_error_reduction": absolute_reduction / single_errors if single_errors else 0.0,
        "scored_label_count": scored_labels,
        "single_label_error_count": single_errors,
        "single_label_error_rate": single_errors / scored_labels if scored_labels else 0.0,
    }


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    return [row for row in value if isinstance(row, dict)] if isinstance(value, list) else []


def _format_float(value: object) -> str:
    return f"{float(value or 0.0):.6f}"


if __name__ == "__main__":
    raise SystemExit(main())
