"""Audit the utility frontier for the span-v4 probe signature model."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_SIGNATURE_MODEL = Path(
    "eval_results/diffusion_language/counterfactual_span_probe_signature_model_v4.json"
)
DEFAULT_JSON_OUTPUT = Path(
    "eval_results/diffusion_language/counterfactual_span_probe_signature_utility_v4.json"
)
DEFAULT_REPORT_OUTPUT = Path(
    "DIFFUSION_COUNTERFACTUAL_SPAN_PROBE_SIGNATURE_UTILITY_FRONTIER_V4.md"
)
DEFAULT_SELECTION_PENALTIES = (0.0, 0.005, 0.01, 0.02, 0.05, 0.1)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--signature-model", type=Path, default=DEFAULT_SIGNATURE_MODEL)
    parser.add_argument(
        "--selection-penalties",
        default=",".join(str(value) for value in DEFAULT_SELECTION_PENALTIES),
        help="Comma-separated per-selected-row utility penalties.",
    )
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    penalties = tuple(
        float(value.strip())
        for value in args.selection_penalties.split(",")
        if value.strip()
    )
    result = analyze_signature_utility_frontier(
        signature_model_path=args.signature_model,
        selection_penalties=penalties,
    )
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(result, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(result), encoding="utf-8")
    print(
        json.dumps(
            {
                "best_low_penalty_false_positives": _dict(
                    result.get("selected_penalty_results")
                )
                .get("0.020000", {})
                .get("false_positive_count"),
                "json_output": str(args.json_output),
                "penalty_count": len(penalties),
                "report_output": str(args.report_output),
                "target_count": result["summary"]["target_count"],
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def analyze_signature_utility_frontier(
    *,
    signature_model_path: Path,
    selection_penalties: tuple[float, ...] = DEFAULT_SELECTION_PENALTIES,
) -> dict[str, object]:
    payload = json.loads(signature_model_path.read_text(encoding="utf-8"))
    rows = _list_of_dicts(_dict(payload.get("leave_one_slice_out")).get("rows"))
    thresholds = _thresholds(rows)
    frontier_rows = [
        _score_threshold(rows, threshold=threshold, selection_penalty=penalty)
        for penalty in selection_penalties
        for threshold in thresholds
    ]
    selected_penalty_results = {
        _format_float(penalty): _best_policy(
            [
                row
                for row in frontier_rows
                if _float(row.get("selection_penalty")) == penalty
            ]
        )
        for penalty in selection_penalties
    }
    oracle = {
        _format_float(penalty): _oracle_summary(rows, selection_penalty=penalty)
        for penalty in selection_penalties
    }
    return {
        "frontier_rows": frontier_rows,
        "generated_by": "experiments/analyze_diffusion_span_probe_signature_utility.py",
        "inputs": {"signature_model": str(signature_model_path)},
        "oracle_by_penalty": oracle,
        "schema": "diffusion_counterfactual_span_probe_signature_utility.v1",
        "selected_penalty_results": selected_penalty_results,
        "summary": {
            "positive_count": sum(1 for row in rows if bool(row.get("label"))),
            "target_count": len(rows),
            "threshold_count": len(thresholds),
        },
    }


def render_markdown(result: dict[str, object]) -> str:
    summary = _dict(result.get("summary"))
    selected = _dict(result.get("selected_penalty_results"))
    lines = [
        "# Diffusion Counterfactual Span Probe Signature Utility Frontier V4",
        "",
        (
            "This file is generated by "
            "`experiments/analyze_diffusion_span_probe_signature_utility.py`."
        ),
        (
            "It asks whether the span-v4 signature score becomes useful once "
            "no-lift selections carry an explicit per-row utility penalty."
        ),
        "",
        "## Summary",
        "",
        f"- Target rows: `{summary.get('target_count', 0)}`",
        f"- Positive rows: `{summary.get('positive_count', 0)}`",
        f"- Thresholds swept: `{summary.get('threshold_count', 0)}`",
        "",
        "## Decision",
        "",
        (
            "Do not promote this utility frontier as a live spend gate. Low "
            "selection penalties keep the broad 26-row policy with 11 false "
            "positives; higher penalties remove false positives only by dropping "
            "most positive rows. The useful finding is the shape of the frontier: "
            "the current signature score is a recall-biased diagnostic, not a "
            "cost-aware controller."
        ),
        "",
        "## Selected Frontier",
        "",
        (
            "| Selection Penalty | Threshold | Selected | FP | FN | Selected Lift | "
            "Utility | Oracle Utility | Regret | Missed Positives | False Positives |"
        ),
        "| ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- | --- |",
    ]
    oracle = _dict(result.get("oracle_by_penalty"))
    for penalty_key in sorted(selected, key=lambda value: _float(value)):
        row = _dict(selected.get(penalty_key))
        oracle_row = _dict(oracle.get(penalty_key))
        lines.append(
            "| "
            f"{penalty_key} | "
            f"{_format_float(row.get('threshold'))} | "
            f"{int(_float(row.get('selected_count')))} | "
            f"{int(_float(row.get('false_positive_count')))} | "
            f"{int(_float(row.get('false_negative_count')))} | "
            f"{_format_float(row.get('selected_lift'))} | "
            f"{_format_float(row.get('policy_utility'))} | "
            f"{_format_float(oracle_row.get('oracle_utility'))} | "
            f"{_format_float(row.get('regret_vs_oracle'))} | "
            f"{_join_tasks(row.get('false_negative_task_ids'))} | "
            f"{_join_tasks(row.get('false_positive_task_ids'))} |"
        )
    lines.extend(
        [
            "",
            "## Reading",
            "",
            (
                "A spend controller needs both recall and specificity. The "
                "`0.020000` penalty is the practical warning point: it still "
                "selects 26 rows and carries 11 false positives, so the signature "
                "score does not expose a cheap no-lift cutoff. The next model "
                "needs a separate no-lift head or a training objective that sees "
                "negative realized lift directly."
            ),
        ]
    )
    return "\n".join(lines) + "\n"


def _thresholds(rows: list[dict[str, object]]) -> list[float]:
    scores = sorted({_float(row.get("probe_signature_score")) for row in rows})
    if not scores:
        return [0.0]
    return [scores[0] - 1.0, *scores, scores[-1] + 1.0]


def _score_threshold(
    rows: list[dict[str, object]],
    *,
    threshold: float,
    selection_penalty: float,
) -> dict[str, object]:
    selected = [
        row
        for row in rows
        if _float(row.get("probe_signature_score")) >= threshold
        and bool(row.get("valid_for_stage1"))
    ]
    false_positives = [row for row in selected if not bool(row.get("label"))]
    false_negatives = [row for row in rows if bool(row.get("label")) and row not in selected]
    selected_lift = sum(_float(row.get("candidate_lift_vs_trajectory")) for row in selected)
    policy_utility = selected_lift - selection_penalty * len(selected)
    oracle = _oracle_summary(rows, selection_penalty=selection_penalty)
    return {
        "false_negative_count": len(false_negatives),
        "false_negative_task_ids": _task_ids(false_negatives),
        "false_positive_count": len(false_positives),
        "false_positive_task_ids": _task_ids(false_positives),
        "policy_utility": policy_utility,
        "regret_vs_oracle": _float(oracle.get("oracle_utility")) - policy_utility,
        "selected_count": len(selected),
        "selected_lift": selected_lift,
        "selection_penalty": selection_penalty,
        "threshold": threshold,
    }


def _best_policy(rows: list[dict[str, object]]) -> dict[str, object]:
    if not rows:
        return {}
    return max(
        rows,
        key=lambda row: (
            _float(row.get("policy_utility")),
            -_float(row.get("false_negative_count")),
            -_float(row.get("false_positive_count")),
            -_float(row.get("selected_count")),
        ),
    )


def _oracle_summary(rows: list[dict[str, object]], *, selection_penalty: float) -> dict[str, object]:
    positive_rows = [
        row
        for row in rows
        if bool(row.get("label"))
        and _float(row.get("candidate_lift_vs_trajectory")) > selection_penalty
    ]
    positive_lift = sum(_float(row.get("candidate_lift_vs_trajectory")) for row in positive_rows)
    return {
        "oracle_selected_count": len(positive_rows),
        "oracle_selected_lift": positive_lift,
        "oracle_utility": positive_lift - selection_penalty * len(positive_rows),
    }


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    if not isinstance(value, list):
        return []
    return [item for item in value if isinstance(item, dict)]


def _float(value: object) -> float:
    if value is None or value == "":
        return 0.0
    try:
        return float(value)
    except (TypeError, ValueError):
        return 0.0


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


def _join_tasks(value: object) -> str:
    values = [str(item) for item in value] if isinstance(value, list) else []
    return ", ".join(f"`{item}`" for item in values) if values else "`none`"


def _task_ids(rows: list[dict[str, object]]) -> list[str]:
    return [str(row.get("task_id", "")) for row in rows]


if __name__ == "__main__":
    raise SystemExit(main())
