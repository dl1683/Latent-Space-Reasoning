"""Analyze the failed v7 expanded-ontology aggregation replay.

This is a no-generation diagnostic. It consumes the v7 replay JSON plus the
generated selected-aspect and realized-answer JSONL artifacts, then turns the
failed promotion gate into a concrete next-experiment target.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from experiments.run_latent_aggregation_multi_aspect_v2_replay import (
    _dict,
    _float,
    _format_counts,
    _format_float,
    _list_of_dicts,
    _read_jsonl,
    _wilson_interval,
)

DEFAULT_REPLAY = Path("eval_results/diffusion_language/latent_aggregation_multi_aspect_v7_replay.json")
DEFAULT_ASPECTS = Path("eval_results/diffusion_language/latent_aggregation_multi_aspect_v7_aspects.jsonl")
DEFAULT_REALIZED = Path("eval_results/diffusion_language/latent_aggregation_multi_aspect_v7_realized.jsonl")
DEFAULT_JSON_OUTPUT = Path(
    "eval_results/diffusion_language/latent_aggregation_multi_aspect_v7_failure_analysis.json"
)
DEFAULT_REPORT_OUTPUT = Path(
    "docs/reports/diffusion/LATENT_AGGREGATION_MULTI_ASPECT_V7_FAILURE.md"
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--replay", type=Path, default=DEFAULT_REPLAY)
    parser.add_argument("--aspects", type=Path, default=DEFAULT_ASPECTS)
    parser.add_argument("--realized", type=Path, default=DEFAULT_REALIZED)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    result = analyze_v7_failure(
        replay_path=args.replay,
        aspects_path=args.aspects,
        realized_path=args.realized,
    )
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(result, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(result), encoding="utf-8")
    print(
        json.dumps(
            {
                "coverage_shortfall": result["summary"]["coverage_shortfall_to_gate"],
                "json_output": str(args.json_output),
                "promotion_shortfall": result["summary"]["promotion_shortfall_to_gate"],
                "report_output": str(args.report_output),
                "wilson_success_shortfall": result["summary"]["wilson_success_shortfall_to_gate"],
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def analyze_v7_failure(
    *,
    replay_path: Path,
    aspects_path: Path,
    realized_path: Path,
) -> dict[str, object]:
    replay = json.loads(replay_path.read_text(encoding="utf-8"))
    aspects = [row for row in _read_jsonl(aspects_path) if bool(row.get("selected", True))]
    realized = _read_jsonl(realized_path)
    tasks = _list_of_dicts(replay.get("tasks"))
    summary = _dict(replay.get("summary"))
    gate_rows = _list_of_dicts(_dict(replay.get("gate_evaluation")).get("gates"))

    gate_thresholds = _gate_thresholds(gate_rows)
    aspects_by_task = _group_by_task(aspects)
    realized_by_task = {str(row.get("task_id")): row for row in realized}
    task_rows = [
        _task_row(task, aspects_by_task.get(str(task.get("task_id")), []), realized_by_task)
        for task in tasks
    ]
    enriched_summary = _summary(summary, gate_thresholds, task_rows, aspects)
    return {
        "evidence_boundary": {
            "reason": (
                "No-generation diagnostic over the completed fresh v7 expanded-ontology "
                "replay. It explains why v7 failed and defines the minimum next-source "
                "coverage needed before another promotion attempt."
            ),
            "status": "fresh_v7_failed_replay_failure_analysis",
        },
        "generated_by": "experiments/analyze_latent_aggregation_multi_aspect_v7_failure.py",
        "inputs": {
            "aspects": str(aspects_path),
            "realized": str(realized_path),
            "replay": str(replay_path),
        },
        "schema": "latent_aggregation_multi_aspect_v7_failure_analysis.v1",
        "summary": enriched_summary,
        "tasks": task_rows,
    }


