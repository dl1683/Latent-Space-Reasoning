        "",
        "This file is generated by `experiments/analyze_latent_aggregation_multi_aspect_v7_failure.py`.",
        "It uses completed v7 replay artifacts only; it does not generate new model outputs and does not promote v7.",
        "",
        "## Evidence Boundary",
        "",
        f"- Status: `{_dict(result['evidence_boundary'])['status']}`",
        f"- Reason: {_dict(result['evidence_boundary'])['reason']}",
        "",
        "## Summary",
        "",
        f"- Replay status: `{summary['gate_status']}`",
        f"- Tasks: `{summary['task_count']}`",
        f"- Complement coverage: `{summary['complement_coverage_count']}/{summary['task_count']}`",
        f"- Coverage gate: `{summary['coverage_gate_count']}`",
        f"- Coverage shortfall: `{summary['coverage_shortfall_to_gate']}`",
        f"- Online promotions: `{summary['online_promoted_task_count']}`",
        f"- Promotion gate: `{summary['promotion_gate_count']}`",
        f"- Promotion shortfall: `{summary['promotion_shortfall_to_gate']}`",
        f"- Wilson lower bound: `{_format_float(summary['wilson_lower_bound'])}`",
        f"- Wilson gate: `{_format_float(summary['wilson_gate_lower_bound'])}`",
        f"- Minimum successes needed for Wilson gate at current n: `{summary['minimum_successes_for_wilson_gate']}`",
        f"- Wilson success shortfall: `{summary['wilson_success_shortfall_to_gate']}`",
        f"- Next-source minimum new promoted coverage floor: `{summary['next_source_minimum_new_promoted_coverage_floor']}`",
        f"- Decision counts: `{_format_counts(summary['decision_status_counts'])}`",
        f"- Selected aspect types: `{_format_counts(summary['selected_aspect_type_counts'])}`",
        f"- Selected source families: `{_format_counts(summary['selected_source_family_counts'])}`",
        f"- Task coverage by source family: `{_format_counts(summary['task_coverage_by_source_family'])}`",
        f"- Unique task coverage by source family: `{_format_counts(summary['unique_task_coverage_by_source_family'])}`",
        f"- Multi-family covered tasks: `{summary['multi_family_covered_task_count']}`",
