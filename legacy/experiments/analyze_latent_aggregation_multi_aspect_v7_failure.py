        "## Interpretation",
        "",
        (
            "V7 failed because coverage remained too sparse for a 48-task promotion claim. "
            "When complements exist, realization is usually strong: conditional promotion "
            "and safety checks are not the binding failure. The next experiment must add "
            "at least the floor above in newly promoted covered tasks, and it should target "
            "the uncovered task IDs directly rather than spending uniformly across all tasks."
        ),
        "",
        "## Next Experiment Contract",
        "",
        f"- Must target at least `{summary['uncovered_task_count']}` currently uncovered tasks.",
        f"- Must newly cover at least `{summary['coverage_shortfall_to_gate']}` tasks to satisfy the coverage count gate.",
        f"- Must newly promote at least `{summary['promotion_shortfall_to_gate']}` tasks to satisfy the win/promotion gate.",
        f"- Must reach at least `{summary['minimum_successes_for_wilson_gate']}` promoted tasks for the Wilson lower-bound gate.",
