"""Build source-preservation targets from diffusion repair labels."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_RAW = Path("eval_results/diffusion_language/source_preservation_v17_label_raw.jsonl")
DEFAULT_SCORES = Path("eval_results/diffusion_language/source_preservation_v17_label_scores.json")
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/diffusion_source_preservation_targets_v17.json")
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_SOURCE_PRESERVATION_TARGETS_V17.md")
DEFAULT_LIFT_MIN = 1e-9


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--raw", type=Path, default=DEFAULT_RAW)
    parser.add_argument("--scores", type=Path, default=DEFAULT_SCORES)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    parser.add_argument("--lift-min", type=float, default=DEFAULT_LIFT_MIN)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    targets = build_source_preservation_targets(raw_path=args.raw, scores_path=args.scores, lift_min=args.lift_min)
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(targets, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(targets), encoding="utf-8")
    summary = _dict(targets.get("summary"))
    print(
        json.dumps(
            {
                "generated_repair_positive_count": summary.get("generated_repair_positive_count", 0),
                "json_output": str(args.json_output),
                "report_output": str(args.report_output),
                "source_positive_repair_degradation_count": summary.get(
                    "source_positive_repair_degradation_count", 0
                ),
                "target_count": summary.get("target_count", 0),
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def build_source_preservation_targets(
    *,
    raw_path: Path,
    scores_path: Path,
    lift_min: float = DEFAULT_LIFT_MIN,
) -> dict[str, object]:
    scores = json.loads(scores_path.read_text(encoding="utf-8"))
    repair_candidates = {
        _task_id(record): record
        for record in _read_jsonl(raw_path)
        if str(record.get("generation_stage", "")) == "repair_candidate" and _task_id(record).startswith("plan_")
    }
    comparison_by_task = {
        str(row.get("task_id", "")): row for row in _list_of_dicts(scores.get("comparison_rows"))
    }
    rows = []
    for spend in _list_of_dicts(scores.get("repair_spend_gate_rows")):
        task_id = str(spend.get("task_id", ""))
        if not task_id.startswith("plan_"):
            continue
        rows.append(
            _target_row(
                spend=spend,
                comparison=_dict(comparison_by_task.get(task_id)),
                repair_candidate=_dict(repair_candidates.get(task_id)),
                lift_min=lift_min,
            )
        )
    rows.sort(key=lambda row: str(row.get("task_id", "")))
    return {
        "generated_by": "experiments/build_diffusion_source_preservation_targets.py",
        "inputs": {
            "raw": str(raw_path),
            "scores": str(scores_path),
        },
        "lift_min": lift_min,
        "rows": rows,
        "schema": "diffusion_source_preservation_targets.v1",
        "summary": _summary(rows),
    }


def render_markdown(targets: dict[str, object]) -> str:
    summary = _dict(targets.get("summary"))
    lines = [
        "# Diffusion Source-Preservation Targets",
        "",
        "This file is generated by `experiments/build_diffusion_source_preservation_targets.py`.",
        (
            "It separates direct source value from generated repair value: source-preservation "
            "rows are positive only when the source beats the selected trajectory and the "
            "generated repair candidate degrades that source."
        ),
        "",
        "## Summary",
        "",
        f"- Raw labels: `{_dict(targets.get('inputs')).get('raw', '')}`",
        f"- Scores: `{_dict(targets.get('inputs')).get('scores', '')}`",
        f"- Target rows: `{summary.get('target_count', 0)}`",
        (
            "- Source-positive repair-degradation rows: "
            f"`{summary.get('source_positive_repair_degradation_count', 0)}`"
        ),
        f"- Source-positive tasks: {_join_tasks(summary.get('source_positive_tasks'))}",
        f"- Repair-degradation tasks: {_join_tasks(summary.get('repair_degradation_tasks'))}",
        f"- Generated repair positive rows: `{summary.get('generated_repair_positive_count', 0)}`",
        f"- Generated repair positive tasks: {_join_tasks(summary.get('generated_repair_positive_tasks'))}",
        f"- Inconclusive source-preservation gate: `{summary.get('source_preservation_gate_inconclusive')}`",
        "",
        "## Rows",
        "",
        (
            "| Task | Run | Source Positive | Candidate Available | Candidate Positive | "
            "Repair Degraded Source | V17 Surface | Source Delta | Candidate Lift vs Traj | "
            "Candidate Lift vs Source | Gap Terms | Coverage | Source |"
        ),
        "| --- | --- | --- | --- | --- | --- | --- | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for row in _list_of_dicts(targets.get("rows")):
        lines.append(
            "| "
            f"`{row.get('task_id', '')}` | "
            f"{bool(row.get('should_run'))} | "
            f"{bool(row.get('source_positive'))} | "
            f"{bool(row.get('candidate_available'))} | "
            f"{bool(row.get('generated_repair_positive'))} | "
            f"{bool(row.get('repair_degraded_source'))} | "
            f"{bool(row.get('source_positive_repair_degradation'))} | "
            f"{_format_float(row.get('source_task_delta_vs_trajectory'))} | "
            f"{_format_float(row.get('candidate_lift_vs_trajectory'))} | "
            f"{_format_float(row.get('candidate_lift_vs_source'))} | "
            f"{int(row.get('prompt_gap_count', 0))} | "
            f"{_format_float(row.get('prompt_coverage'))} | "
            f"`{row.get('source_control', '')}` |"
        )
    lines.extend(
        [
            "",
            "## Reading",
            "",
            (
                "The frozen v17 source-preservation gate is inconclusive when this sheet has zero "
                "source-positive repair-degradation rows. Generated repair positives remain useful "
                "evidence, but they answer a different question: repair generation recovered value "
                "instead of preserving a source that already beat the trajectory."
            ),
        ]
    )
    return "\n".join(lines) + "\n"


def _target_row(
    *,
    spend: dict[str, object],
    comparison: dict[str, object],
    repair_candidate: dict[str, object],
    lift_min: float,
) -> dict[str, object]:
    task_id = str(spend.get("task_id", ""))
    candidate_available = bool(repair_candidate)
    trajectory_task_score = _float(spend.get("trajectory_task_score"))
    source_task_score = _float(spend.get("source_task_score"))
    if candidate_available:
        candidate_task_score = _float(_dict(repair_candidate.get("task_score")).get("score"))
    else:
        candidate_task_score = 0.0
    source_delta = source_task_score - trajectory_task_score
    candidate_lift_vs_trajectory = candidate_task_score - trajectory_task_score if candidate_available else 0.0
    candidate_lift_vs_source = candidate_task_score - source_task_score if candidate_available else 0.0
    source_positive = source_delta > lift_min
    generated_repair_positive = candidate_available and candidate_lift_vs_trajectory > lift_min
    repair_degraded_source = candidate_available and candidate_lift_vs_source < -lift_min
    return {
        "candidate_available": candidate_available,
        "candidate_lift_vs_source": candidate_lift_vs_source,
        "candidate_lift_vs_trajectory": candidate_lift_vs_trajectory,
        "candidate_task_score": candidate_task_score,
        "generated_repair_positive": generated_repair_positive,
        "oracle_delta_vs_trajectory": _float(comparison.get("oracle_delta_vs_trajectory")),
        "prompt_coverage": _float(spend.get("prompt_coverage")),
        "prompt_gap_count": int(_float(spend.get("prompt_gap_count"))),
        "repair_degraded_source": repair_degraded_source,
        "repair_task_score": _float(comparison.get("repair_task_score")),
        "selected_repair_lift": _float(comparison.get("repair_delta_vs_evolved")),
        "should_run": bool(spend.get("should_run")),
        "source_control": str(spend.get("source_control", "")),
        "source_positive": source_positive,
        "source_positive_repair_degradation": source_positive
        and repair_degraded_source
        and candidate_lift_vs_trajectory <= lift_min,
        "source_task_delta_vs_trajectory": source_delta,
        "source_task_score": source_task_score,
        "task_id": task_id,
        "trajectory_task_score": trajectory_task_score,
    }


def _summary(rows: list[dict[str, object]]) -> dict[str, object]:
    source_positive_rows = [row for row in rows if row.get("source_positive")]
    repair_degradation_rows = [row for row in rows if row.get("repair_degraded_source")]
    surface_rows = [row for row in rows if row.get("source_positive_repair_degradation")]
    generated_positive_rows = [row for row in rows if row.get("generated_repair_positive")]
    return {
        "generated_repair_positive_count": len(generated_positive_rows),
        "generated_repair_positive_tasks": [str(row.get("task_id", "")) for row in generated_positive_rows],
        "repair_degradation_count": len(repair_degradation_rows),
        "repair_degradation_tasks": [str(row.get("task_id", "")) for row in repair_degradation_rows],
        "source_positive_count": len(source_positive_rows),
        "source_positive_repair_degradation_count": len(surface_rows),
        "source_positive_repair_degradation_tasks": [str(row.get("task_id", "")) for row in surface_rows],
        "source_positive_tasks": [str(row.get("task_id", "")) for row in source_positive_rows],
        "source_preservation_gate_inconclusive": len(surface_rows) == 0,
        "target_count": len(rows),
    }


def _read_jsonl(path: Path) -> list[dict[str, object]]:
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        row = json.loads(line)
        if isinstance(row, dict):
            rows.append(row)
    return rows


def _task_id(record: dict[str, object]) -> str:
    task = record.get("task")
    if isinstance(task, dict):
        task_id = task.get("task_id")
        if task_id:
            return str(task_id)
    return str(record.get("task_id", ""))


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    return [row for row in value if isinstance(row, dict)] if isinstance(value, list) else []


def _float(value: object) -> float:
    if value is None:
        return 0.0
    return float(value)


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


def _join_tasks(value: object) -> str:
    values = [str(item) for item in value] if isinstance(value, list) else []
    return ", ".join(f"`{item}`" for item in values) if values else "`none`"


if __name__ == "__main__":
    raise SystemExit(main())
