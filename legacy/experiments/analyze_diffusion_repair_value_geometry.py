"""Analyze feature geometry for cost-aware diffusion repair value."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from statistics import mean

DEFAULT_LOSS_TARGETS = Path("eval_results/diffusion_language/diffusion_budget_policy_loss_targets.jsonl")
DEFAULT_JSON_OUTPUT = Path("eval_results/diffusion_language/diffusion_repair_value_geometry.json")
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_REPAIR_VALUE_GEOMETRY.md")
DEFAULT_COST_PENALTY_LAMBDA = 0.18
DEFAULT_RUNNER_SOURCE_QUALITY_MAX = 0.31
DEFAULT_RUNNER_PROMPT_GAP_MAX = 9


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--loss-targets", type=Path, default=DEFAULT_LOSS_TARGETS)
    parser.add_argument("--cost-penalty-lambda", type=float, default=DEFAULT_COST_PENALTY_LAMBDA)
    parser.add_argument(
        "--runner-source-quality-max",
        type=float,
        default=DEFAULT_RUNNER_SOURCE_QUALITY_MAX,
    )
    parser.add_argument(
        "--runner-prompt-gap-max",
        type=int,
        default=DEFAULT_RUNNER_PROMPT_GAP_MAX,
    )
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    audit = build_repair_value_geometry(
        loss_targets_path=args.loss_targets,
        cost_penalty_lambda=args.cost_penalty_lambda,
        runner_source_quality_max=args.runner_source_quality_max,
        runner_prompt_gap_max=args.runner_prompt_gap_max,
    )
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(audit, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(audit), encoding="utf-8")
    print(
        json.dumps(
            {
                "json_output": str(args.json_output),
                "report_output": str(args.report_output),
                "runner_policy_regret": _float(_dict(audit.get("runner_policy")).get("regret_vs_oracle")),
                "target_count": len(_list_of_dicts(audit.get("coordinate_rows"))),
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def build_repair_value_geometry(
    *,
    loss_targets_path: Path,
    cost_penalty_lambda: float = DEFAULT_COST_PENALTY_LAMBDA,
    runner_source_quality_max: float = DEFAULT_RUNNER_SOURCE_QUALITY_MAX,
    runner_prompt_gap_max: int = DEFAULT_RUNNER_PROMPT_GAP_MAX,
) -> dict[str, object]:
    targets = _load_jsonl(loss_targets_path)
    coordinate_rows = [
        _coordinate_row(
            target,
            cost_penalty_lambda=cost_penalty_lambda,
            runner_prompt_gap_max=runner_prompt_gap_max,
            runner_source_quality_max=runner_source_quality_max,
        )
        for target in targets
    ]
    runner_policy = _score_policy(
        {
            "max_prompt_gap": runner_prompt_gap_max,
            "max_source_quality": runner_source_quality_max,
            "policy_id": "runner_source_quality_gap",
            "type": "source_quality_gap",
        },
        targets,
        cost_penalty_lambda=cost_penalty_lambda,
    )
    separability_rows = _separability_rows(
        targets,
        cost_penalty_lambda=cost_penalty_lambda,
        runner_prompt_gap_max=runner_prompt_gap_max,
        runner_source_quality_max=runner_source_quality_max,
    )
    return {
        "cost_penalty_lambda": cost_penalty_lambda,
        "coordinate_rows": coordinate_rows,
        "generated_by": "experiments/analyze_diffusion_repair_value_geometry.py",
        "loss_targets_path": str(loss_targets_path),
        "runner_policy": runner_policy,
        "runner_prompt_gap_max": runner_prompt_gap_max,
        "runner_source_quality_max": runner_source_quality_max,
        "schema": "diffusion_repair_value_geometry.v1",
        "separability_rows": separability_rows,
        "summary": _summary(
            coordinate_rows,
            runner_policy=runner_policy,
            runner_prompt_gap_max=runner_prompt_gap_max,
            runner_source_quality_max=runner_source_quality_max,
        ),
    }


def render_markdown(audit: dict[str, object]) -> str:
    summary = _dict(audit.get("summary"))
    runner = _dict(audit.get("runner_policy"))
    lines = [
        "# Diffusion Repair-Value Geometry",
        "",
        "This file is generated by `experiments/analyze_diffusion_repair_value_geometry.py`.",
        (
            "It turns the cost-aware repair target into a small feature-geometry audit: "
            "which label-free denoise features separate high-value repair spends from "
            "low-value or wasteful spends before an extra GPU generation is used."
        ),
        "",
        "## Summary",
        "",
        f"- Loss targets: `{audit.get('loss_targets_path', '')}`",
        f"- Cost penalty lambda: `{_format_float(audit.get('cost_penalty_lambda'))}`",
        f"- Profitable repair tasks: `{_join_tasks(summary.get('profitable_tasks'))}`",
        f"- Runner proxy tasks: `{_join_tasks(runner.get('selected_tasks'))}`",
        f"- Runner proxy regret: `{_format_float(runner.get('regret_vs_oracle'))}`",
        f"- Runner proxy utility: `{_format_float(runner.get('policy_utility_delta'))}`",
        (
            "- Runner rule: "
            f"`first_repairable_step exists and source_needs_repair and prompt_gap_count <= "
            f"{audit.get('runner_prompt_gap_max')} and source_quality <= "
            f"{_format_float(audit.get('runner_source_quality_max'))}`"
        ),
        f"- Source-quality separation gap inside prompt band: `{_format_optional(summary.get('source_quality_band_gap'))}`",
        f"- Lowest excluded prompt gap with low source quality: `{_format_optional(summary.get('lowest_low_quality_excluded_gap'))}`",
        "",
        "## Feature Separability",
        "",
        "| Policy | Regret | Utility | TP | FP | TN | FN | Selected Tasks | Rule |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- | --- |",
    ]
    for row in _list_of_dicts(audit.get("separability_rows")):
        lines.append(
            "| "
            f"`{row.get('policy_id', '')}` | "
            f"{_format_float(row.get('regret_vs_oracle'))} | "
            f"{_format_float(row.get('policy_utility_delta'))} | "
            f"{row.get('true_positive_count', 0)} | "
            f"{row.get('false_positive_count', 0)} | "
            f"{row.get('true_negative_count', 0)} | "
            f"{row.get('false_negative_count', 0)} | "
            f"{_join_tasks(row.get('selected_tasks'))} | "
            f"{_policy_description(row)} |"
        )
    lines.extend(
        [
            "",
            "## Value Coordinates",
            "",
            (
                "| Task | Profitable | Utility | Break-even Lambda | First Step | Step Fraction | "
                "Gap | Prompt Coverage | Source Quality | Trajectory Score | Runner Decision | "
                "Quality Margin | Gap Margin |"
            ),
            "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- | ---: | ---: |",
        ]
    )
    predictions = _dict(runner.get("predictions"))
    for row in _list_of_dicts(audit.get("coordinate_rows")):
        task_id = str(row.get("task_id", ""))
        lines.append(
            "| "
            f"{task_id} | "
            f"{bool(row.get('profitable'))} | "
            f"{_format_float(row.get('utility'))} | "
            f"{_format_float(row.get('break_even_lambda'))} | "
            f"{_format_optional(row.get('first_repairable_step'))} | "
            f"{_format_optional(row.get('first_repairable_step_fraction'))} | "
            f"{_format_optional(row.get('prompt_gap_count'))} | "
            f"{_format_optional(row.get('prompt_coverage'))} | "
            f"{_format_optional(row.get('source_quality'))} | "
            f"{_format_optional(row.get('trajectory_score'))} | "
            f"`{predictions.get(task_id, '')}` | "
            f"{_format_optional(row.get('runner_quality_margin'))} | "
            f"{_format_optional(row.get('runner_gap_margin'))} |"
        )
    lines.extend(
        [
            "",
            "## Reading",
            "",
            (
                "The important geometry is not simply early repairability. Early repairs at "
                "`plan_001` and `plan_003` are real but low marginal value at lambda "
                f"`{_format_float(audit.get('cost_penalty_lambda'))}`. The current value "
                "surface keeps one compact early gap and the late low-quality repair phases, "
                "while rejecting low-value early repairs and the late gap-outside-band case."
            ),
        ]
    )
    return "\n".join(lines) + "\n"


def _coordinate_row(
    target: dict[str, object],
    *,
    cost_penalty_lambda: float,
    runner_prompt_gap_max: int,
    runner_source_quality_max: float,
) -> dict[str, object]:
    utility = _target_utility(target, cost_penalty_lambda=cost_penalty_lambda)
    source_quality = _optional_float(target.get("source_quality"))
    prompt_gap = _optional_float(target.get("prompt_gap_count"))
    return {
        "aggregate_score_lift": _float(target.get("aggregate_score_lift")),
        "break_even_lambda": _float(target.get("break_even_lambda")),
        "first_repairable_step": _optional_float(target.get("first_repairable_step")),
        "first_repairable_step_fraction": _optional_float(
            target.get("first_repairable_step_fraction")
        ),
        "profitable": utility > 0.0,
        "prompt_coverage": _optional_float(target.get("prompt_coverage")),
        "prompt_gap_count": prompt_gap,
        "runner_gap_margin": (
            runner_prompt_gap_max - prompt_gap if prompt_gap is not None else None
        ),
        "runner_quality_margin": (
            runner_source_quality_max - source_quality
            if source_quality is not None
            else None
        ),
        "source_needs_repair": bool(target.get("source_needs_repair", False)),
        "source_quality": source_quality,
        "task_id": str(target.get("task_id", "")),
        "trajectory_score": _optional_float(target.get("trajectory_score")),
        "utility": utility,
    }


def _separability_rows(
    targets: list[dict[str, object]],
    *,
    cost_penalty_lambda: float,
    runner_prompt_gap_max: int,
    runner_source_quality_max: float,
) -> list[dict[str, object]]:
    policies = [
        {
            "max_prompt_gap": runner_prompt_gap_max,
            "max_source_quality": runner_source_quality_max,
            "policy_id": "runner_source_quality_gap",
            "type": "source_quality_gap",
        },
        _best_threshold_policy(
            targets,
            policy_id="best_source_quality_gap",
            policy_type="source_quality_gap",
            threshold_field="source_quality",
            cost_penalty_lambda=cost_penalty_lambda,
            prompt_gap_max=runner_prompt_gap_max,
        ),
        _best_threshold_policy(
            targets,
            policy_id="best_trajectory_score_gap",
            policy_type="trajectory_score_gap",
            threshold_field="trajectory_score",
            cost_penalty_lambda=cost_penalty_lambda,
            prompt_gap_max=runner_prompt_gap_max,
        ),
        _best_threshold_policy(
            targets,
            policy_id="best_prompt_gap_only",
            policy_type="prompt_gap",
            threshold_field="prompt_gap_count",
            cost_penalty_lambda=cost_penalty_lambda,
            prompt_gap_max=runner_prompt_gap_max,
        ),
        _best_late_or_specific_policy(
            targets,
            cost_penalty_lambda=cost_penalty_lambda,
            prompt_gap_max=runner_prompt_gap_max,
        ),
    ]
    rows = [
        _score_policy(policy, targets, cost_penalty_lambda=cost_penalty_lambda)
        for policy in policies
    ]
    return sorted(
        rows,
        key=lambda row: (
            _float(row.get("regret_vs_oracle")),
            _float(row.get("false_positive_count")),
            -_float(row.get("true_positive_count")),
            str(row.get("policy_id", "")),
        ),
    )


def _best_threshold_policy(
    targets: list[dict[str, object]],
    *,
    policy_id: str,
    policy_type: str,
    threshold_field: str,
    cost_penalty_lambda: float,
    prompt_gap_max: int,
) -> dict[str, object]:
    thresholds = sorted(_threshold_candidates(targets, threshold_field))
    if not thresholds:
        thresholds = [0.0]
    best_policy: dict[str, object] | None = None
    best_row: dict[str, object] | None = None
    for threshold in thresholds:
        policy = {
            "max_prompt_gap": prompt_gap_max,
            "policy_id": policy_id,
            "threshold": threshold,
            "threshold_field": threshold_field,
            "type": policy_type,
        }
        row = _score_policy(policy, targets, cost_penalty_lambda=cost_penalty_lambda)
        if best_row is None or _row_sort_key(row, policy) < _row_sort_key(best_row, best_policy):
            best_policy = policy
            best_row = row
    return best_policy or {
        "max_prompt_gap": prompt_gap_max,
        "policy_id": policy_id,
        "threshold": 0.0,
        "threshold_field": threshold_field,
        "type": policy_type,
    }


def _best_late_or_specific_policy(
    targets: list[dict[str, object]],
    *,
    cost_penalty_lambda: float,
    prompt_gap_max: int,
) -> dict[str, object]:
    gap_thresholds = sorted(_threshold_candidates(targets, "prompt_gap_count") | {3.0})
    step_thresholds = sorted(_threshold_candidates(targets, "first_repairable_step") | {20.0})
    best_policy: dict[str, object] | None = None
    best_row: dict[str, object] | None = None
    for specific_gap in gap_thresholds:
        for min_first_step in step_thresholds:
            policy = {
                "max_prompt_gap": prompt_gap_max,
                "min_first_step": min_first_step,
                "policy_id": "best_specific_or_late",
                "specific_prompt_gap": specific_gap,
                "type": "specific_or_late",
            }
            row = _score_policy(policy, targets, cost_penalty_lambda=cost_penalty_lambda)
            if best_row is None or _row_sort_key(row, policy) < _row_sort_key(best_row, best_policy):
                best_policy = policy
                best_row = row
    return best_policy or {
        "max_prompt_gap": prompt_gap_max,
        "min_first_step": 20.0,
        "policy_id": "best_specific_or_late",
        "specific_prompt_gap": 3.0,
        "type": "specific_or_late",
    }


def _row_sort_key(row: dict[str, object], policy: dict[str, object] | None) -> tuple[float, ...]:
    policy = policy or {}
    return (
        _float(row.get("regret_vs_oracle")),
        _float(row.get("false_positive_count")),
        -_float(row.get("true_positive_count")),
        _float(policy.get("threshold"), default=0.0),
        _float(policy.get("specific_prompt_gap"), default=999.0),
        _float(policy.get("min_first_step"), default=999.0),
    )


def _score_policy(
    policy: dict[str, object],
    targets: list[dict[str, object]],
    *,
    cost_penalty_lambda: float,
) -> dict[str, object]:
    true_positive = false_positive = true_negative = false_negative = 0
    policy_utility = 0.0
    oracle_utility = 0.0
    predictions: dict[str, str] = {}
    selected_tasks = []
    for target in targets:
        task_id = str(target.get("task_id", ""))
        utility = _target_utility(target, cost_penalty_lambda=cost_penalty_lambda)
        profitable = utility > 0.0
        predicted_spend = _predict_spend(policy, target)
        predictions[task_id] = "spend_repair" if predicted_spend else "skip_repair"
        if profitable:
            oracle_utility += utility
        if predicted_spend:
            policy_utility += utility
            selected_tasks.append(task_id)
        if predicted_spend and profitable:
            true_positive += 1
        elif predicted_spend and not profitable:
            false_positive += 1
        elif not predicted_spend and not profitable:
            true_negative += 1
        else:
            false_negative += 1
    return {
        **policy,
        "false_negative_count": false_negative,
        "false_positive_count": false_positive,
        "oracle_utility_delta": oracle_utility,
        "policy_utility_delta": policy_utility,
        "predictions": predictions,
        "regret_vs_oracle": oracle_utility - policy_utility,
        "selected_tasks": selected_tasks,
        "true_negative_count": true_negative,
        "true_positive_count": true_positive,
    }


def _predict_spend(policy: dict[str, object], target: dict[str, object]) -> bool:
    first_step = _optional_float(target.get("first_repairable_step"))
    if first_step is None or not bool(target.get("source_needs_repair", False)):
        return False
    prompt_gap = _float(target.get("prompt_gap_count"), default=999.0)
    max_gap = _float(policy.get("max_prompt_gap"), default=999.0)
    policy_type = str(policy.get("type", ""))
    if policy_type == "source_quality_gap":
        return (
            prompt_gap <= max_gap
            and _float(target.get("source_quality"), default=1.0)
            <= _float(policy.get("max_source_quality", policy.get("threshold")))
        )
    if policy_type == "trajectory_score_gap":
        return (
            prompt_gap <= max_gap
            and _float(target.get("trajectory_score"), default=1.0)
            <= _float(policy.get("threshold"))
        )
    if policy_type == "prompt_gap":
        return prompt_gap <= _float(policy.get("threshold"))
    if policy_type == "specific_or_late":
        return prompt_gap <= max_gap and (
            prompt_gap <= _float(policy.get("specific_prompt_gap"))
            or first_step >= _float(policy.get("min_first_step"))
        )
    raise ValueError(f"unsupported policy type: {policy_type}")


def _target_utility(target: dict[str, object], *, cost_penalty_lambda: float) -> float:
    return _float(target.get("aggregate_score_lift")) - cost_penalty_lambda * _float(
        target.get("marginal_relative_cost")
    )


def _summary(
    rows: list[dict[str, object]],
    *,
    runner_policy: dict[str, object],
    runner_prompt_gap_max: int,
    runner_source_quality_max: float,
) -> dict[str, object]:
    profitable = [str(row.get("task_id", "")) for row in rows if bool(row.get("profitable"))]
    prompt_band_rows = [
        row
        for row in rows
        if row.get("first_repairable_step") is not None
        and bool(row.get("source_needs_repair", False))
        and _float(row.get("prompt_gap_count"), default=999.0) <= runner_prompt_gap_max
    ]
    band_positive_source = [
        _float(row.get("source_quality"))
        for row in prompt_band_rows
        if bool(row.get("profitable")) and row.get("source_quality") is not None
    ]
    band_negative_source = [
        _float(row.get("source_quality"))
        for row in prompt_band_rows
        if not bool(row.get("profitable")) and row.get("source_quality") is not None
    ]
    low_quality_excluded_gaps = [
        _float(row.get("prompt_gap_count"))
        for row in rows
        if row.get("source_quality") is not None
        and _float(row.get("source_quality")) <= runner_source_quality_max
        and _float(row.get("prompt_gap_count"), default=999.0) > runner_prompt_gap_max
    ]
    return {
        "mean_profitable_break_even_lambda": _mean(
            row.get("break_even_lambda") for row in rows if bool(row.get("profitable"))
        ),
        "mean_unprofitable_break_even_lambda": _mean(
            row.get("break_even_lambda") for row in rows if not bool(row.get("profitable"))
        ),
        "profitable_tasks": profitable,
        "runner_false_positive_count": runner_policy.get("false_positive_count", 0),
        "runner_regret_vs_oracle": runner_policy.get("regret_vs_oracle", 0.0),
        "source_quality_band_gap": (
            min(band_negative_source) - max(band_positive_source)
            if band_positive_source and band_negative_source
            else None
        ),
        "lowest_low_quality_excluded_gap": (
            min(low_quality_excluded_gaps) if low_quality_excluded_gaps else None
        ),
    }


def _policy_description(policy: dict[str, object]) -> str:
    policy_type = str(policy.get("type", ""))
    if policy_type == "source_quality_gap":
        return (
            "`repairable and source_needs_repair and prompt_gap_count <= "
            f"{_format_float(policy.get('max_prompt_gap'))} and source_quality <= "
            f"{_format_float(policy.get('max_source_quality', policy.get('threshold')))}`"
        )
    if policy_type == "trajectory_score_gap":
        return (
            "`repairable and source_needs_repair and prompt_gap_count <= "
            f"{_format_float(policy.get('max_prompt_gap'))} and trajectory_score <= "
            f"{_format_float(policy.get('threshold'))}`"
        )
    if policy_type == "prompt_gap":
        return (
            "`repairable and source_needs_repair and prompt_gap_count <= "
            f"{_format_float(policy.get('threshold'))}`"
        )
    if policy_type == "specific_or_late":
        return (
            "`repairable and source_needs_repair and prompt_gap_count <= "
            f"{_format_float(policy.get('max_prompt_gap'))} and "
            f"(prompt_gap_count <= {_format_float(policy.get('specific_prompt_gap'))} "
            f"or first_repairable_step >= {_format_float(policy.get('min_first_step'))})`"
        )
    return "`unsupported policy`"


def _threshold_candidates(targets: list[dict[str, object]], field: str) -> set[float]:
    return {
        _float(target.get(field))
        for target in targets
        if target.get(field) is not None and target.get(field) != ""
    }


def _load_jsonl(path: Path) -> list[dict[str, object]]:
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            value = json.loads(line)
            if isinstance(value, dict):
                rows.append(value)
    return rows


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    return [item for item in value if isinstance(item, dict)] if isinstance(value, list) else []


def _float(value: object, *, default: float = 0.0) -> float:
    if value is None or value == "":
        return default
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def _optional_float(value: object) -> float | None:
    if value is None or value == "":
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def _mean(values: object) -> float | None:
    numeric = [_float(value) for value in values if value is not None and value != ""]
    return mean(numeric) if numeric else None


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


def _format_optional(value: object) -> str:
    if value is None or value == "":
        return ""
    return _format_float(value)


def _string_list(value: object) -> list[str]:
    return [str(item) for item in value] if isinstance(value, list) else []


def _join_tasks(value: object) -> str:
    return ", ".join(_string_list(value))


