"""Evaluate repair promotion selectors on an independent diffusion transfer slice."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_ALL_REPAIRABLE_SCORES = Path(
    "eval_results/diffusion_language/"
    "llada_moe_mixed_transfer_v2_all_repairable_frontier_v1_scores.json"
)
DEFAULT_POLICY_SCORES = (
    Path(
        "eval_results/diffusion_language/"
        "llada_moe_mixed_transfer_v2_decomposed_spend_transfer_rule_margin0_frontier_v1_scores.json"
    ),
    Path(
        "eval_results/diffusion_language/"
        "llada_moe_mixed_transfer_v2_decomposed_spend_transfer_rule_inherit_margin0_frontier_v1_scores.json"
    ),
)
DEFAULT_JSON_OUTPUT = Path(
    "eval_results/diffusion_language/diffusion_transfer_promotion_value_eval.json"
)
DEFAULT_REPORT_OUTPUT = Path("DIFFUSION_TRANSFER_PROMOTION_VALUE.md")
DEFAULT_LIFT_MIN = 1e-9


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--all-repairable-scores", type=Path, default=DEFAULT_ALL_REPAIRABLE_SCORES)
    parser.add_argument(
        "--policy-scores",
        type=Path,
        nargs="+",
        default=list(DEFAULT_POLICY_SCORES),
        help="One or more policy score JSON files to compare.",
    )
    parser.add_argument("--lift-min", type=float, default=DEFAULT_LIFT_MIN)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT)
    parser.add_argument("--report-output", type=Path, default=DEFAULT_REPORT_OUTPUT)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    evaluation = evaluate_transfer_promotion_value(
        all_repairable_scores_path=args.all_repairable_scores,
        lift_min=args.lift_min,
        policy_score_paths=tuple(args.policy_scores),
    )
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(json.dumps(evaluation, indent=2, sort_keys=True), encoding="utf-8")
    args.report_output.write_text(render_markdown(evaluation), encoding="utf-8")
    print(
        json.dumps(
            {
                "best_policy": _dict(evaluation.get("summary")).get("best_policy", ""),
                "json_output": str(args.json_output),
                "policy_count": len(_list_of_dicts(evaluation.get("policies"))),
                "report_output": str(args.report_output),
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def evaluate_transfer_promotion_value(
    *,
    all_repairable_scores_path: Path,
    policy_score_paths: tuple[Path, ...],
    lift_min: float = DEFAULT_LIFT_MIN,
) -> dict[str, object]:
    all_repairable = json.loads(all_repairable_scores_path.read_text(encoding="utf-8"))
    availability_rows = _availability_rows(all_repairable, lift_min=lift_min)
    policies = [
        _policy_summary(path=path, availability_rows=availability_rows, lift_min=lift_min)
        for path in policy_score_paths
    ]
    best_policy = min(
        policies,
        key=lambda policy: (
            _float(policy.get("oracle_headroom_vs_repair")),
            -_float(policy.get("repair_task_delta_vs_trajectory")),
            _float(policy.get("repair_mean_generation_budget_per_task")),
            str(policy.get("policy_id", "")),
        ),
    ) if policies else {}
    return {
        "all_repairable_scores": str(all_repairable_scores_path),
        "availability_rows": availability_rows,
        "generated_by": "experiments/evaluate_diffusion_transfer_promotion_value.py",
        "lift_min": lift_min,
        "policies": policies,
        "schema": "diffusion_transfer_promotion_value_eval.v1",
        "summary": {
            "available_repair_count": sum(int(row.get("available", False)) for row in availability_rows),
            "available_repair_tasks": [
                str(row.get("task_id", "")) for row in availability_rows if row.get("available")
            ],
            "best_policy": str(best_policy.get("policy_id", "")),
            "best_policy_run_id": str(best_policy.get("run_id", "")),
            "planning_row_count": len(availability_rows),
        },
    }


def render_markdown(evaluation: dict[str, object]) -> str:
    summary = _dict(evaluation.get("summary"))
    lines = [
        "# Diffusion Transfer Promotion Value",
        "",
        "This file is generated by `experiments/evaluate_diffusion_transfer_promotion_value.py`.",
        (
            "It evaluates repair promotion selectors after the spend gate has "
            "identified an available independent transfer repair."
        ),
        "",
        "## Summary",
        "",
        f"- All-repairable labels: `{evaluation.get('all_repairable_scores', '')}`",
        f"- Planning rows: `{summary.get('planning_row_count', 0)}`",
        f"- Positive repair-availability rows: `{summary.get('available_repair_count', 0)}`",
        f"- Positive repair-availability tasks: {_join_tasks(summary.get('available_repair_tasks'))}",
        f"- Best promotion policy: `{summary.get('best_policy', '')}`",
        f"- Best promotion run: `{summary.get('best_policy_run_id', '')}`",
        "",
        "## Policy Comparison",
        "",
        (
            "| Policy | Run | Generations | Repair Budget | Repair Task | "
            "Delta vs Traj | Oracle Headroom | Selected Available | Missed Available |"
        ),
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for policy in _list_of_dicts(evaluation.get("policies")):
        lines.append(
            "| "
            f"`{policy.get('policy_id', '')}` | "
            f"`{policy.get('run_id', '')}` | "
            f"{int(policy.get('all_generation_count', 0))} | "
            f"{_format_float(policy.get('repair_mean_generation_budget_per_task'))} | "
            f"{_format_float(policy.get('repair_mean_task_score'))} | "
            f"{_format_float(policy.get('repair_task_delta_vs_trajectory'))} | "
            f"{_format_float(policy.get('oracle_headroom_vs_repair'))} | "
            f"{policy.get('selected_available_count', 0)} | "
            f"{policy.get('missed_available_count', 0)} |"
        )
    lines.extend(
        [
            "",
            "## Available Repair Rows",
            "",
            "| Task | Repair Lift | Oracle Task | Trajectory Task | Selected By Best | Best Selected Lift |",
            "| --- | ---: | ---: | ---: | --- | ---: |",
        ]
    )
    best_policy_id = str(summary.get("best_policy", ""))
    best = next(
        (
            policy
            for policy in _list_of_dicts(evaluation.get("policies"))
            if policy.get("policy_id") == best_policy_id
        ),
        {},
    )
    best_rows = {
        str(row.get("task_id", "")): row for row in _list_of_dicts(best.get("rows"))
    }
    for row in _list_of_dicts(evaluation.get("availability_rows")):
        if not row.get("available"):
            continue
        task_id = str(row.get("task_id", ""))
        best_row = _dict(best_rows.get(task_id))
        lines.append(
            "| "
            f"`{task_id}` | "
            f"{_format_float(row.get('oracle_lift'))} | "
            f"{_format_float(row.get('oracle_task_score'))} | "
            f"{_format_float(row.get('trajectory_task_score'))} | "
            f"{bool(best_row.get('selected_positive_lift'))} | "
            f"{_format_float(best_row.get('selected_lift'))} |"
        )
    lines.extend(
        [
            "",
            "## Reading",
            "",
            (
                "Repair availability and repair promotion value are separate "
                "heads. This evaluator now labels availability from generated "
                "repair-candidate lift rather than nonrepair oracle lift. The "
                "older v2 transfer slice no longer contributes positive "
                "repair-only rows, so current promotion evidence should be read "
                "from `DIFFUSION_CANDIDATE_PROMOTION_TARGETS_V5.md` and the "
                "`candidate_aware_promotion_v1` runner selector."
            ),
        ]
    )
    return "\n".join(lines) + "\n"


def _availability_rows(scores: dict[str, object], *, lift_min: float) -> list[dict[str, object]]:
    rows = []
    for row in _list_of_dicts(scores.get("comparison_rows")):
        task_id = str(row.get("task_id", ""))
        if not task_id.startswith("plan_"):
            continue
        trajectory = _float(row.get("trajectory_task_score"))
        oracle = _float(row.get("oracle_task_score"))
        lift = _repair_lift(row)
        rows.append(
            {
                "available": lift > lift_min,
                "oracle_lift": lift,
                "oracle_task_score": oracle,
                "task_id": task_id,
                "trajectory_task_score": trajectory,
            }
        )
    return rows


def _policy_summary(
    *,
    path: Path,
    availability_rows: list[dict[str, object]],
    lift_min: float,
) -> dict[str, object]:
    scores = json.loads(path.read_text(encoding="utf-8"))
    available_by_task = {
        str(row.get("task_id", "")): row for row in availability_rows if row.get("available")
    }
    rows = []
    selected_available_count = 0
    missed_available_count = 0
    for row in _list_of_dicts(scores.get("comparison_rows")):
        task_id = str(row.get("task_id", ""))
        if not task_id.startswith("plan_"):
            continue
        selected_lift = _float(row.get("repair_delta_vs_evolved"))
        is_available = task_id in available_by_task
        selected_positive = selected_lift > lift_min
        if is_available and selected_positive:
            selected_available_count += 1
        elif is_available:
            missed_available_count += 1
        rows.append(
            {
                "available": is_available,
                "oracle_lift": _float(_dict(available_by_task.get(task_id)).get("oracle_lift")),
                "repair_selection_reason": str(row.get("repair_selection_reason", "")),
                "selected_lift": selected_lift,
                "selected_positive_lift": selected_positive,
                "task_id": task_id,
            }
        )
    repair_arm = _dict(_dict(scores.get("arms")).get("repair_selected"))
    return {
        "all_generation_count": int(scores.get("all_generation_count", 0)),
        "content_hash": str(scores.get("content_hash", "")),
        "missed_available_count": missed_available_count,
        "oracle_headroom_vs_repair": _float(scores.get("oracle_headroom_vs_repair")),
        "policy_id": str(scores.get("repair_selector", "")),
        "repair_mean_generation_budget_per_task": _float(
            repair_arm.get("mean_generation_budget_per_task")
        ),
        "repair_mean_task_score": _float(repair_arm.get("mean_task_score")),
        "repair_task_delta_vs_trajectory": _float(scores.get("repair_task_delta_vs_trajectory")),
        "rows": rows,
        "run_id": str(scores.get("run_id", "")),
        "score_path": str(path),
        "selected_available_count": selected_available_count,
    }


def _repair_lift(row: dict[str, object]) -> float:
    if "repair_delta_vs_evolved" in row:
        return _float(row.get("repair_delta_vs_evolved"))
    if "repair_task_score" in row and "trajectory_task_score" in row:
        return _float(row.get("repair_task_score")) - _float(row.get("trajectory_task_score"))
    return 0.0


def _dict(value: object) -> dict[str, object]:
    return value if isinstance(value, dict) else {}


def _list_of_dicts(value: object) -> list[dict[str, object]]:
    return [row for row in value if isinstance(row, dict)] if isinstance(value, list) else []


def _float(value: object) -> float:
    if value is None:
        return 0.0
    return float(value)


def _format_float(value: object) -> str:
    return f"{_float(value):.6f}"


def _join_tasks(value: object) -> str:
    values = [str(item) for item in value] if isinstance(value, list) else []
    return ", ".join(f"`{item}`" for item in values) if values else "`none`"


if __name__ == "__main__":
    raise SystemExit(main())
