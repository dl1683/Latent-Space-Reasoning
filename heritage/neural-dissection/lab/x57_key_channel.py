def fate_of(read: float | None) -> str | None:
    if read is None:
        return None
    if read <= DEAD_CUT:
        return "DEAD"
    if read >= ALIVE_CUT_T:
        return "ALIVE"
    return "MID"


def arm_verdict(fates: list[str | None]) -> str | None:
    """e346's own verdict form: PROTECTS iff all three ALIVE; EXECUTED
    iff all three DEAD; MIXED otherwise."""
    vals = [f for f in fates if f is not None]
    if len(vals) < 3:
        return None
    if all(f == "ALIVE" for f in vals):
        return "PROTECTS"
    if all(f == "DEAD" for f in vals):
        return "EXECUTED"
    return "MIXED"


def read_of(row: dict) -> float | None:
    """the host read of a row, full ('read') or light ('host')."""
    if row is None:
        return None
    return row.get("read", row.get("host"))


def guest_of(row: dict) -> float | None:
    if row is None:
        return None
    if "dual" in row:
        return row["dual"]["means"]["g0"]
    return row.get("guest")


