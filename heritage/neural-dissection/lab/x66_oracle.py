def variant_record(p0: dict, vid: str, tag: str, host: str, seed: int,
                   menu: str, steps: int, wash_out: dict,
                   inst_rows: dict, K: float | None = None,
                   label: str | None = None) -> dict:
    """One variant's sweep record: the features + the retention."""
    t0 = wash_out["rows"][0]["read"]
    end = wash_out["rows"][max(wash_out["rows"])]["read"]
    inst_keys = sorted(inst_rows, key=lambda k: int(k.rsplit("_s", 1)[1]))
    mid_reads = [inst_rows[k]["read"] for k in inst_keys
                 if int(k.rsplit("_s", 1)[1]) >= 100] \
        or [inst_rows[inst_keys[-1]]["read"]]
    ireads = [inst_rows[k]["read"] for k in inst_keys]
    isteps = [int(k.rsplit("_s", 1)[1]) for k in inst_keys]
    iw1 = inst_rows[inst_keys[0]]["write_norm"]
    iw_end = inst_rows[inst_keys[-1]]["write_norm"]
    seed_K = p0["seed_K_map"].get(str(seed))
    return {
        "vid": vid, "tag": tag, "host": host, "seed": seed,
        "menu": MENU_CLASS.get(menu, menu), "menu_key": menu,
        "steps": steps,
        "wash": {"t0": t0, "end": end,
                 "retention": (end / t0 if t0 > 0 else None),
                 "panels": {str(s): r["read"] for s, r in
                            sorted(wash_out["rows"].items())},
                 "n_draws": len(wash_out["draws"])},
        "traj": {"reads": dict(zip([str(s) for s in isteps], ireads)),
                 "write_s1": iw1, "write_end": iw_end},
        "features": {
            "dose_steps": steps,
            "menu_jit": float(MENU_CLASS.get(menu) == "jittered"),
            "menu_rnd": float(MENU_CLASS.get(menu) == "random"),
            "menu_other": float(MENU_CLASS.get(menu) == "other"),
            "read_t0": t0,
            "dip_ratio": (min(mid_reads) / max(mid_reads)
                          if max(mid_reads) > 0 else None),
            "write_growth": iw_end - iw1,
            "seed_K": seed_K,
            "name_prior": p0["name_prior"][host],
        },
        "K": K, "label": label,
        "powered": bool(t0 >= INSTALL_FLOOR),
    }


