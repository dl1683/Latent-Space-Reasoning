def make_rider_draw(p0: dict, slot_keys: tuple):
    """x55's make_draw VERBATIM (e345's per-slot keyed draw): batch 32
    = 16 keyed jittered-pool draws (name-masked) + 8 cons_anchor
    originals + 8 random corpus windows; generator consumption
    IDENTICAL for every keying."""
