def build_menus(p0: dict):
    """The sweep's menu pools (frozen at birth): authored-60 (both
    names), jittered-300 (G1's jitter set, x55's construction), and the
    derived menus (random-60, half, co-occupant)."""
    train_ids = p0["train_ids"]
    install_occ = p0["install_occ"]
    name_ids_q, name_ids_n = p0["name_ids_q"], p0["name_ids_n"]

    def authored_pool(name_ids, occ):
        ix = torch.stack([
            torch.cat([train_ids[p - G1.PRE: p], name_ids,
                       train_ids[p + len(h): p + len(h) + G1.POST_CAP]])
            for p, h in occ])
        im = torch.zeros(len(occ), G1.BLOCK - 1, dtype=torch.bool)
        im[:, G1.PRE - 1: G1.PRE - 1 + 7] = True
        return ix, im

    def jittered_pool(name_ids):
        """x55's jittered_pool VERBATIM (G1's jitter set)."""
        jit_x, jit_mask = {}, {}
        for j in G1.JITTERS:
            jwins = []
            for p, h in install_occ:
                pre = train_ids[p - G1.PRE - j: p]
                post = train_ids[p + len(h):
                                 p + len(h) + G1.POST_CAP - j]
                w = torch.cat([pre, name_ids, post])
                if len(w) != G1.BLOCK:
                    raise RuntimeError(f"jit window len {len(w)} at j={j}")
                jwins.append(w)
            jit_x[j] = torch.stack(jwins)
            m = torch.zeros(len(jwins), G1.BLOCK - 1, dtype=torch.bool)
            m[:, G1.PRE - 1 + j: G1.PRE - 1 + j + len(name_ids)] = True
            jit_mask[j] = m
        return torch.cat([jit_x[j] for j in G1.JITTERS]), \
            torch.cat([jit_mask[j] for j in G1.JITTERS])

    # the random menu: 60 fresh corpus positions (rng 26116, frozen);
    # the name inserted at PRE replacing the 7 following chars
    rng = np.random.default_rng(RNG_RANDOM_MENU)
