def loo_q2(X: np.ndarray, y: np.ndarray) -> tuple[float, list[float]]:
    """OLS with leave-one-out cross-validation; returns (Q2, preds)."""
    n = X.shape[0]
    preds = []
    for i in range(n):
        idx = [j for j in range(n) if j != i]
        Xi, yi = X[idx], y[idx]
        try:
            beta, *_ = np.linalg.lstsq(
                np.column_stack([np.ones(len(idx)), Xi]), yi,
                rcond=None)
            preds.append(float(
                beta[0] + float(np.dot(beta[1:], X[i]))))
        except np.linalg.LinAlgError:
            preds.append(None)
    p = np.array([v if v is not None else np.nan for v in preds])
    ok = np.isfinite(p)
    sse = float(np.sum((y[ok] - p[ok]) ** 2))
    sst = float(np.sum((y - y.mean()) ** 2))
    return (1.0 - sse / sst if sst > 0 else float("nan")), \
        ([float(v) for v in p])


